	IMPLICIT NONE

	INTEGER EDOF,ENODE,NG,NPROP,PDSKY2
	INTEGER MAX_ITER

	INTEGER NELE_A,NTDOF_A,NCOUNT_AM,NMAT_A
	INTEGER NELE_B,NTDOF_B,NCOUNT_BM,NMAT_B,NSEG
	INTEGER OSTIF,OSTRAIN,NPEFI
	INTEGER OPT_ANALYSIS,STNOP,DIV_OPT,RESTART

        REAL*8 TOT_INC
	REAL*8 LENGTH,FRI,PCE,DT
	REAL*8 LDTIME
	REAL*8 VELX_A,VELY_A,VELZ_A,VELX_B,VELY_B,VELZ_B
	REAL*8 ACCX_A,ACCY_A,ACCZ_A,ACCX_B,ACCY_B,ACCZ_B
	REAL*8 TOLEC
	INTEGER	I

	INTEGER STRESS_OPTION
	
c	DICLARATIONS FOR SELF CONTACT ROUTINES.....BIGIN	
	INTEGER SOFT_BODY,SELFCON_NODES_IN,SELFCON_NODES_OUT
	
c	DICLARATIONS FOR SELF CONTACT ROUTINES.....END


	PARAMETER (EDOF = 24)        !DEGREE OF FREEDOM PER ELEMENT
	PARAMETER (ENODE = 8)        !NODES PER ELEMENT
	PARAMETER (NG = 2)           !NO. OF GAUSS POINTS
	PARAMETER (NPROP = 7)        !NO. OF PROPERTIES NEEDED
	PARAMETER (PDSKY2 = 90000000) !DIMENSION FOR SKY2 MATRIX

C	WRITE(*,*) 'READING OPTIONS FOR OVERALL EXECUTION'

	CALL RO_EXEC(TOT_INC,MAX_ITER,DT,OPT_ANALYSIS,
     1	  STNOP,LDTIME,TOLEC,DIV_OPT)

C	WRITE(*,*) 'READING OPTIONS FOR INTERNAL EXECUTION'

	CALL RI_EXEC(PCE,OSTIF,OSTRAIN,NPEFI,STRESS_OPTION,RESTART)

C	WRITE(*,*) 'READING ESSENTIAL PARAMETERS'

	CALL RE_PARA(NELE_A,NELE_B,NTDOF_A,NTDOF_B,NCOUNT_AM,
     1	NCOUNT_BM,NSEG,NMAT_A,NMAT_B,FRI,LENGTH,SOFT_BODY,
     1	SELFCON_NODES_IN,SELFCON_NODES_OUT)
     
     
        CALL DYNA_INPUT(VELX_A,VELY_A,VELZ_A,VELX_B,VELY_B,
     1	VELZ_B,ACCX_A,ACCY_A,ACCZ_A,ACCX_B,ACCY_B,ACCZ_B)
     

C    	WRITE(*,*) 'before contact analysis'
     	
	CALL CONTACT_ANALYSES(NELE_A,NELE_B,EDOF,ENODE,NTDOF_A,
     1  NTDOF_B,NCOUNT_AM,NCOUNT_BM,NSEG,NPROP,NMAT_A,NMAT_B,LENGTH,
     1  NG,PDSKY2,FRI,TOT_INC,MAX_ITER,PCE,OSTIF,OSTRAIN,NPEFI,DT,
     1	OPT_ANALYSIS,STNOP,LDTIME,VELX_A,VELY_A,VELZ_A,VELX_B,
     1	VELY_B,VELZ_B,ACCX_A,ACCY_A,ACCZ_A,ACCX_B,ACCY_B,ACCZ_B,
     1	TOLEC,DIV_OPT,STRESS_OPTION,RESTART,SOFT_BODY,SELFCON_NODES_IN,
     1	SELFCON_NODES_OUT)

C	WRITE(*,*)'THE END OF RUN 6'


	STOP
	END


C	CONTACT ANALYSES

	SUBROUTINE CONTACT_ANALYSES(NELE_A,NELE_B,EDOF,ENODE,
     1   NTDOF_A,NTDOF_B,NCOUNT_AM,NCOUNT_BM,NSEG,NPROP,NMAT_A,NMAT_B,
     1   LENGTH,NG,PDSKY2,FRI,TOT_INC,MAX_ITER,PCE,OSTIF,OSTRAIN,
     1	 NPEFI,DT,OPT_ANALYSIS,STNOP,LDTIME,VELX_A,VELY_A,VELZ_A,VELX_B,
     1	 VELY_B,VELZ_B,ACCX_A,ACCY_A,ACCZ_A,ACCX_B,ACCY_B,ACCZ_B,
     1	 TOLEC,DIV_OPT,STRESS_OPTION,RESTART,SOFT_BODY,SELFCON_NODES_IN,
     1	 SELFCON_NODES_OUT)


	IMPLICIT NONE


	INTEGER EDOF,ENODE,NSEG,NPROP,NG,RNUMBER,PDSKY2,IBODY
	INTEGER NELE_A,NTDOF_A,NMAT_A
	INTEGER NELE_B,NTDOF_B,NMAT_B
	INTEGER NCOUNT_AM,NCOUNT_BM
        INTEGER MAX_ITER
	INTEGER OSTIF,OSTRAIN,NPEFI,RESTART

c	DICLARATIONS FOR SELF CONTACT ROUTINES.....BIGIN	
	INTEGER SOFT_BODY,SELFCON_NODES_IN,SELFCON_NODES_OUT
	
	INTEGER S_NCONTACT_IN(SELFCON_NODES_IN),
     1    S_NCONTACT_OUT(SELFCON_NODES_OUT)
     
c	DICLARATIONS FOR SELF CONTACT ROUTINES.....END
     
	INTEGER NODE_A(ENODE,NELE_A),NCONTACT_AM(NCOUNT_AM),
     1	IBDISP_A(NTDOF_A)
	INTEGER NODE_B(ENODE,NELE_B),NCONTACT_BM(NCOUNT_BM),
     1	IBDISP_B(NTDOF_B)

     
	INTEGER F_FACE_A(6,NELE_A)
	INTEGER F_FACE_B(6,NELE_B)

	INTEGER WRESULT_A,WRINC_A
	INTEGER WRESULT_B,WRINC_B
	INTEGER WRPARA_A(6),WRPARA_B(6)
	INTEGER WRELE_A(NELE_A),WRELE_B(NELE_B)

	INTEGER FNODE(4,6)
	INTEGER CFACE(2,NSEG)

	REAL*8 FRI,LENGTH,PCE,TOT_INC

	REAL*8 MPROP_A(NPROP,NELE_A),MPROP_B(NPROP,NELE_B)

	REAL*8 XCOORD_A(ENODE,NELE_A),YCOORD_A(ENODE,NELE_A),
     1	  ZCOORD_A(ENODE,NELE_A)
	REAL*8 XCOORD_B(ENODE,NELE_B),YCOORD_B(ENODE,NELE_B),
     1	  ZCOORD_B(ENODE,NELE_B)
    	REAL*8 B_GP(4,3,6)

	REAL*8 FNODAL_A(NTDOF_A),FNODAL_B(NTDOF_B)

	REAL *8 DT
	INTEGER OPT_ANALYSIS,STNOP,DIV_OPT
	REAL *8 LDTIME
	REAL*8 VELX_A,VELY_A,VELZ_A,VELX_B,VELY_B,VELZ_B
	REAL*8 ACCX_A,ACCY_A,ACCZ_A,ACCX_B,ACCY_B,ACCZ_B
	REAL*8 TOLEC

	INTEGER STRESS_OPTION


C	WRITE(*,*)'OPENING REQUIRED FILES'

	CALL OPEN_FILES_IP

C	WRITE(*,*)'READING OPTONS FOR RESULTS'

	IBODY = 1

	CALL RO_RESULT(WRELE_A,WRPARA_A,WRESULT_A,WRINC_A,
     1	  NELE_A,IBODY)

	IBODY = 2

	CALL RO_RESULT(WRELE_B,WRPARA_B,WRESULT_B,WRINC_B,
     1	  NELE_B,IBODY)

	CALL OPEN_FILES_OP(WRPARA_A,WRPARA_B)


C	WRITE(*,*)'READING REQUIRED PARAMETERS'

	CALL MREAD (MPROP_A,MPROP_B,FNODAL_A,FNODAL_B,XCOORD_A,
     1	XCOORD_B,YCOORD_A,YCOORD_B,ZCOORD_A,ZCOORD_B,B_GP,NODE_A,
     1  NODE_B,F_FACE_A,F_FACE_B,FNODE,IBDISP_A,IBDISP_B,
     1	NCONTACT_AM,NCONTACT_BM,CFACE,NELE_A,NELE_B,
     1  NTDOF_A,NTDOF_B,NCOUNT_AM,NCOUNT_BM,EDOF,ENODE,NSEG,NPROP,
     1  NMAT_A,NMAT_B,SELFCON_NODES_IN,SELFCON_NODES_OUT,S_NCONTACT_IN,
     1	S_NCONTACT_OUT)
     
     
C	CONTACT ANALYSIS NUMBERS CONTACT NODES FIRST
C	WE NEED RENUMBERING NODES
C	RNUMBER = 1 FOR RENUMBERING NODES
C	RNUMBER = 0 FOR NO RENUMBERING OF NODES

	RNUMBER = 1

C	WRITE(*,*)'ELASTO-PLASTIC CONTACT ANALYSES'

	CALL STRESS_ANALYSES(MPROP_A,MPROP_B,FNODAL_A,FNODAL_B,
     1	XCOORD_A,XCOORD_B,YCOORD_A,YCOORD_B,ZCOORD_A,ZCOORD_B,B_GP,
     1  NODE_A,NODE_B,FNODE,F_FACE_A,F_FACE_B,IBDISP_A,IBDISP_B,
     1	NCONTACT_AM,NCONTACT_BM,CFACE,FRI,LENGTH,NCOUNT_AM,
     1	NCOUNT_BM,NELE_A,NELE_B,NTDOF_A,NTDOF_B,EDOF,ENODE,NSEG,
     1	NPROP,NG,PDSKY2,TOT_INC,MAX_ITER,RNUMBER,PCE,OSTIF,OSTRAIN,
     1  NPEFI,WRELE_A,WRELE_B,WRPARA_A,WRPARA_B,WRESULT_A,WRESULT_B,
     1  WRINC_A,WRINC_B,DT,OPT_ANALYSIS,STNOP,LDTIME,
     1	VELX_A,VELY_A,VELZ_A,VELX_B,VELY_B,VELZ_B,ACCX_A,ACCY_A,
     1	ACCZ_A,ACCX_B,ACCY_B,ACCZ_B,TOLEC,DIV_OPT,STRESS_OPTION,
     1  RESTART,SOFT_BODY,SELFCON_NODES_IN,SELFCON_NODES_OUT,
     1	S_NCONTACT_IN,S_NCONTACT_OUT)



	RETURN
	END

