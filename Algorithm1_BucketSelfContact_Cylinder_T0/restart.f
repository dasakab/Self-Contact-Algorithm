C       OPENING FILES TO READ DIFFERENT VARIABLE VALUES FOR RESTART OPTION

        SUBROUTINE OPEN_RESTART_FILES

C	FILE FOR PARAMETERS

	OPEN (UNIT=6613,FILE='RESTART/PARA')

C	FILE FOR CAUCHY STRESS

	OPEN (UNIT=6614,FILE='RESTART/STRESS_A')

	OPEN (UNIT=6615,FILE='RESTART/STRESS_B')

C	FILE FOR DISPLACEMENTS

	OPEN (UNIT=6616,FILE='RESTART/DISPLACEMENT_A')

	OPEN (UNIT=6617,FILE='RESTART/DISPLACEMENT_B')

C	FILE FOR EQUIVALENT PLASTIC STRAIN

	OPEN (UNIT=6618,FILE='RESTART/EPSTRAIN_A')

	OPEN (UNIT=6619,FILE='RESTART/EPSTRAIN_B')

C	FILE FOR YIELD STRESS

	OPEN (UNIT=6620,FILE='RESTART/YSTRESS_A')

       	OPEN (UNIT=6621,FILE='RESTART/YSTRESS_B')

C	FILE FOR STATE AT GAUSS POINTS

       	OPEN (UNIT=6622,FILE='RESTART/STATE_A')

      	OPEN (UNIT=6623,FILE='RESTART/STATE_B')

C	FILE FOR VELOCITY

       	OPEN (UNIT=6624,FILE='RESTART/VELOCITY_A')

       	OPEN (UNIT=6625,FILE='RESTART/VELOCITY_B')

C	FILE FOR ACCELERATION

       	OPEN (UNIT=6626,FILE='RESTART/ACCELERATION_A')

       	OPEN (UNIT=6627,FILE='RESTART/ACCELERATION_B')
	
C	FILE FOR SELFCONTACT- SORTED LIST

	OPEN (UNIT=6699,FILE='RESTART/SDATA')

	OPEN (UNIT=6700,FILE='RESTART/IN')
	
	OPEN (UNIT=6701,FILE='RESTART/OUT')

       RETURN
       END


