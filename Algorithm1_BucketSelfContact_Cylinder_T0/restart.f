C       SUBROUTINE FOR WRITING ESSENTIAL VALUES REQUIRED FOR RESTART OPTION

        SUBROUTINE WRITE_FOR_RESTART_A(CSTRESS,DISP,EQUI_PSTRAIN,
     1	  YSTRESS,NSTATE,VELS1,ACCS1,NELE,NG,EDOF,ENODE,
     1    NTDOF,NPROP)

        IMPLICIT NONE

        INTEGER NELE,NG,EDOF,ENODE,NPROP,NTDOF
        INTEGER K1,K2,K3

        INTEGER NSTATE(NG*NG*NG,NELE)
        REAL*8 CSTRESS(NG*NG*NG,6,NELE),DISP(EDOF,NELE)
        REAL*8 EQUI_PSTRAIN(NG*NG*NG,NELE),YSTRESS(NG*NG*NG,NELE)
        REAL*8 VELS1(EDOF,NELE)
        REAL*8 ACCS1(EDOF,NELE)

        WRITE(6614,*) '\CAUCHY STRESS AT EACH GAUSS POINTS'
        WRITE(6614,*) '\1 ... 6 COMPONENTS'

        DO K1=1,NELE
             DO K2=1,NG*NG*NG
                  WRITE(6614,*) (CSTRESS(K2,K3,K1),K3=1,6)
             ENDDO
        ENDDO

        WRITE(6616,*) '\DISPLACEMENTS OF BODY A AT EACH NODE POINTS'
        WRITE(6616,*) '\NODE POINTS 1 ... 8'

        DO K1=1,NELE
            WRITE(6616,*) (DISP(K2,K1),K2=1,EDOF)
        ENDDO

        WRITE(6618,*) '\EQUIVALENT PLASTIC STRAIN AT GAUSS POMITS'
        WRITE(6618,*) '\GAUSS POINTS 1 ... 8'

        DO K1=1,NELE
            WRITE(6618,*) (EQUI_PSTRAIN(K2,K1),K2=1,NG*NG*NG)
        ENDDO

        WRITE(6620,*) '\YIELD STRESS OF ALL GAUSS POINTS OF BODY A'
        WRITE(6620,*) '\GAUSS POINTS 1 ... 8'

        DO K1=1,NELE
            WRITE(6620,*) (YSTRESS(K2,K1),K2=1,NG*NG*NG)
        ENDDO

        WRITE(6622,*) 'STATE OF EACH GAUSS POINTS/ALL ELEMENTS OF A'
        WRITE(6622,*) 'ELASTIC = 1  PLASTIC = 3'

        DO K1=1,NELE
            WRITE(6622,*) (NSTATE(K2,K1),K2=1,NG*NG*NG)
        ENDDO

        WRITE(6624,*) '\VELOSITY OF EACH NODE POINTS OF BODY A'
        WRITE(6624,*) 'EDOF 1 ..... 24'

        DO K1=1,NELE
            WRITE(6624,*) (VELS1(K2,K1),K2=1,EDOF)
        ENDDO

        WRITE(6626,*) '\ACCELERATION OF EACH NODE POINTS OF BODY A'
        WRITE(6626,*) 'EDOF 1 ..... 24'

        DO K1=1,NELE
            WRITE(6626,*) (ACCS1(K2,K1),K2=1,EDOF)
        ENDDO

        RETURN
        END


	
	
	SUBROUTINE WRITE_FOR_SELFCON(THETA_ROW_IN,THETA_CLMN_IN,
     1	  THETA_NODES_IN,THETA_ROW_OUT,THETA_CLMN_OUT,THETA_NODES_OUT)
	
	IMPLICIT NONE
	INTEGER THETA_ROW_IN,THETA_CLMN_IN,THETA_ROW_OUT,THETA_CLMN_OUT
	INTEGER THETA_NODES_IN(THETA_ROW_IN,THETA_CLMN_IN)
	INTEGER THETA_NODES_OUT(THETA_ROW_OUT,THETA_CLMN_OUT)
	INTEGER K1,K2
	
	WRITE(6699,*) (THETA_ROW_IN)
	WRITE(6699,*) (THETA_CLMN_IN)
	WRITE(6699,*) (THETA_ROW_OUT)
	WRITE(6699,*) (THETA_CLMN_OUT)
	
	 DO K2=1,THETA_CLMN_IN 
             WRITE(6700,*) (THETA_NODES_IN(K1,K2),K1=1,THETA_ROW_IN)
        ENDDO
	
         DO K2=1,THETA_CLMN_OUT
         WRITE(6701,*) (THETA_NODES_OUT(K1,K2),K1=1,THETA_ROW_OUT)
         ENDDO
	
	RETURN 
	END

