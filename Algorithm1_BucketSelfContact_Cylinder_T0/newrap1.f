C	SUBROUTINE TO FIND UNBALANCE FORCE

	SUBROUTINE UNBALANCE_FORCE(GFORCE,INTFORCE,UNBFORCE,CDISP_A,
     1	  CDISP_B,NCOUNT_A,NCOUNT_B,ITRCON,INCNUMBER,TOLEC,
     1    UNB_RATIO)


	IMPLICIT NONE

	COMMON/INTER/IA,IIA,IB,IIB,IDA,IDB,ID,IID

	INTEGER IA,IIA,IB,IIB,IDA,IDB,ID,IID
	INTEGER K1,ITRCON,INCNUMBER,NCOUNT_A,NCOUNT_B

C     CDISP arrays contain only ordinary contact degrees of freedom.
C     IA/IB also contain self-contact dofs and must not bound these.
	INTEGER CDISP_A(3*NCOUNT_A),CDISP_B(3*NCOUNT_B)

        REAL*8 UNB_RATIO,DUMMY1,DUMMY2
	REAL*8 GFORCE(IDA+IDB),INTFORCE(IDA+IDB),UNBFORCE(IDA+IDB)

	REAL*8 TOLEC

C	WRITE(*,*)'ENWRAP COUNTER 2'
	DO K1 = 1, IDA+IDB
	  UNBFORCE(K1)=GFORCE(K1)-INTFORCE(K1)
	ENDDO

C	UNBALANCE FORCE MADE ZERO AT SPECIFIED BCS

C	WRITE(*,*)'ENWRAP COUNTER 3'
	DO K1 = 1,3*NCOUNT_A
	  IF (CDISP_A(K1) .EQ. 0) THEN
	    UNBFORCE(K1) = 0.0
	  ENDIF
	ENDDO

	DO K1 = 1,3*NCOUNT_B
	  IF (CDISP_B(K1) .EQ. 0) THEN
	    UNBFORCE(K1+IA) = 0.0
C	    WRITE(*,*)'ENWRAP COUNTER 4'
	  ENDIF
	ENDDO

C	CONDITION FOR CONVERGENCE

	DUMMY1=0.0
	DUMMY2=0.0

	DO K1 = 1,IDA+IDB
	  DUMMY1=UNBFORCE(K1)**2+DUMMY1
C	  WRITE(*,*)'ENWRAP COUNTER 5'
	ENDDO
	
	WRITE(*,*) 'DUMMY 1 =',DUMMY1

C	WRITE(*,*)'ENWRAP COUNTER 6'
	DO K1=1,IDA+IDB
	  DUMMY2=GFORCE(K1)**2+DUMMY2
C	  WRITE(*,*)'ENWRAP COUNTER 7',DUMMY2
	ENDDO

C	WRITE(*,*)'ENWRAP COUNTER 8'
	UNB_RATIO = SQRT(DUMMY1/DUMMY2)
C	WRITE(*,*)'ENWRAP COUNTER 9'

	WRITE(*,*) '  '
	WRITE(*,*)'UNBALANCE FORCE = ', UNB_RATIO
	WRITE(*,*)'TOLEC=',TOLEC

	WRITE(709,*)'UNBALANCE FORCE = ', UNB_RATIO
	WRITE(709,*)'--------------------------------------------------'
	WRITE(709,*)' '

	IF (UNB_RATIO .LT. TOLEC) THEN
	  ITRCON = 1
	ELSE
	  ITRCON = 2
	ENDIF

	IF (UNB_RATIO .GT. 10000000.0) THEN
	  WRITE(711,*) 'UNBALANCE FORCE UNMANAGEABLE'
	  WRITE(711,*) '   '
	  WRITE(711,*) 'UNBALANCE FORCE = ',UNB_RATIO
	  WRITE(711,*) '  '
	  WRITE(711,*) 'INCREMENT NUMBER  = ',INCNUMBER
	  WRITE(711,*) '  '
	  WRITE(711,*) 'TERMINATING EXECUTION'
	  
	  WRITE(*,*) 'UNBALANCE FORCE UNMANAGEABLE'
	  WRITE(*,*) 'TERMINATING EXECUTION  '

	  STOP

	ENDIF

	RETURN
	END

