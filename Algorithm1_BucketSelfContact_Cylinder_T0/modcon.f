C	SUBROUTINE TO FIND MODIFIED CONNECTIVITY

	SUBROUTINE IG_CONECT(NODE,NE,NCONTACT,NCOUNT,NTDOF,EDOF,
     1   ENODE,IDISP,IG,RNUMBER,S_HIT_COUNTER_IN,S_HIT_COUNTER_OUT,
     1   S_HNODE_IN,TOTAL_TNODES_IN,S_HNODE_OUT,TOTAL_TNODES_OUT,SIZE1,
     1	 SIZE2,SIZE3,SIZE4)
	

	IMPLICIT NONE
	
	INTEGER EDOF,ENODE,NE,NTDOF,NCOUNT,RNUMBER
	
	INTEGER NODE(ENODE,NE),IG(EDOF,NE)
	INTEGER NCONTACT(NCOUNT)
	
	INTEGER NEXTINT(NTDOF),NINTEXT(NTDOF)
	INTEGER NDC(NTDOF/3),NDBC(NTDOF/3)
	
	INTEGER IDISP(NTDOF) 
C*********************************************************************
C	DECLARATIONS FOR SELF CONTACT
	INTEGER SIZE1,SIZE2,SIZE3,SIZE4
	INTEGER S_HIT_COUNTER_IN,S_HIT_COUNTER_OUT
	INTEGER TOTAL_TNODES_IN(SIZE2),S_HNODE_IN(SIZE1),
     1		TOTAL_TNODES_OUT(SIZE4),S_HNODE_OUT(SIZE3)

C*********************************************************************

C	RNUMBER = 1  RENUMBER NODES
C	RNUMBER = 0  NO RENUMBERING OF NODES
	
	CALL CONCON(NTDOF,EDOF,ENODE,NCONTACT,NCOUNT,NDC,NDBC,
     1	NEXTINT,NINTEXT,RNUMBER,S_HIT_COUNTER_IN,S_HIT_COUNTER_OUT,
     1  S_HNODE_IN,TOTAL_TNODES_IN,S_HNODE_OUT,TOTAL_TNODES_OUT,SIZE1,
     1	SIZE2,SIZE3,SIZE4)
	
	CALL MODCON (IDISP,NEXTINT,NINTEXT,NTDOF,EDOF,ENODE,NE,
     1	NDC,NDBC,NODE,IG)
	
	RETURN
	END

C	SUBROUTINE TO CONVERT OLD CONNECTIVITY
C	TO NEW CONNECTIVITY

	SUBROUTINE CONCON(NTDOF,EDOF,ENODE,NCONTACT,NCOUNT,NDC,NDBC,
     1	NEXTINT,NINTEXT,RNUMBER,S_HIT_COUNTER_IN,S_HIT_COUNTER_OUT,
     1  S_HNODE_IN,TOTAL_TNODES_IN,S_HNODE_OUT,TOTAL_TNODES_OUT,SIZE1,
     1	SIZE2,SIZE3,SIZE4)

     
    
	IMPLICIT NONE
	
	INTEGER K,K1,K2,K3,K4,MM,MN,NN,K5,K6,K7
	INTEGER EDOF,ENODE,RNUMBER,NTDOF,NCOUNT
	
	INTEGER NCONTACT(NCOUNT)

	INTEGER  NDC(NTDOF/3),NDBC(NTDOF/3)
	INTEGER  NEXTINT(NTDOF),NINTEXT(NTDOF)
C*********************************************************************
C	DECLARATIONS FOR SELF CONTACT
	INTEGER SIZE1,SIZE2,SIZE3,SIZE4
	INTEGER S_HIT_COUNTER_IN,S_HIT_COUNTER_OUT
	INTEGER TOTAL_TNODES_IN(SIZE2),S_HNODE_IN(SIZE1),
     1		TOTAL_TNODES_OUT(SIZE4),S_HNODE_OUT(SIZE3)
C*********************************************************************	


	DO 10 K=1,NTDOF/3
	  NDC(K)=0
10	CONTINUE

	MN=1

C	RNUMBER = 1  RENUMBER NODES
C	RNUMBER = 0  NO RENUMBERING OF NODES

c	WRITE(*,*) 'CON1'	
	IF(RNUMBER.EQ.1) THEN
	
C	  NUMBERING CONTACT NODES FIRST (FOR BODY A ONLY)
	  
	  DO K2 = 1,NCOUNT
	    NN=NCONTACT(K2)
	    NDC(NN)=MN
	    MN=MN+1
	  ENDDO
C	  WRITE(*,*) 'CON2',S_HIT_COUNTER_IN
	  
C	NUMBERING SC_IN NODES NEXT
	IF (S_HIT_COUNTER_IN .EQ. 1) THEN
C		SIZE1 = SIZE(S_HNODE_IN)
C		SIZE2 = SIZE(TOTAL_TNODES_IN)
C		WRITE(*,*) 'CON3'
		DO K3 = 1,SIZE1
			NN = S_HNODE_IN(K3)
			NDC(NN) = MN
			MN = MN+1
		ENDDO 
		DO K4 = 1,SIZE2
			NN = TOTAL_TNODES_IN(K4)
			NDC(NN) = MN
			MN = MN+1
		ENDDO
	ENDIF

C	NUMBERING SC_OUT NODES NEXT
	IF (S_HIT_COUNTER_OUT .EQ. 1) THEN
C		SIZE3 = SIZE(S_HNODE_OUT)
C		SIZE4 = SIZE(TOTAL_TNODES_OUT)
C  		WRITE(*,*) 'CON4'
		DO K5 = 1,SIZE3
			NN = S_HNODE_OUT(K5)
			NDC(NN) = MN
			MN = MN+1
		ENDDO 
		DO K6 = 1,SIZE4
			NN = TOTAL_TNODES_OUT(K6)
			NDC(NN) = MN
			MN = MN+1
		ENDDO
	ENDIF	  

C	  NUMBERING REST NODES
	  DO K7 = 1,NTDOF/3
	    IF(NDC(K7) .EQ. 0) THEN
	      NDC(K7)=MN
	      MN=MN+1
	    ENDIF
	  ENDDO
C	  WRITE(*,*) 'CON5'
	ELSE
	  
	  DO K1 = 1,NTDOF/3
	    NDC(K1) =K1
	  ENDDO
C	WRITE(*,*) 'CON6'
	ENDIF

C	WRITE(*,*) 'CON7'	
	DO 50 K4 = 1,NTDOF/3
	  MM=NDC(K4)
	  NDBC(MM)=K4
50	CONTINUE
C	WRITE(*,*) 'CON8'
C	NODE NUMBERS IN TERMS OF TOTAL DEGREE OF FREEDOM

	DOK1=1,NTDOF/3
	  
	  NEXTINT(3*K1-2)=3*NDC(K1)-2
	  NEXTINT(3*K1-1)=3*NDC(K1)-1
	  NEXTINT(3*K1)  =3*NDC(K1)
C	  WRITE(*,*) 'CON9'
	  NINTEXT(3*K1-2)=3*NDBC(K1)-2
	  NINTEXT(3*K1-1)=3*NDBC(K1)-1
	  NINTEXT(3*K1)  =3*NDBC(K1)
C	WRITE(*,*) 'CON10'	
	ENDDO
C	WRITE(*,*) 'CON11'
	RETURN
	END

C	SUBROUTINE TO CONVERT CONNECTIVITY INTO
C	INTERNAL SYSTEM

	SUBROUTINE MODCON(IDISP,NEXTINT,NINTEXT,NTDOF,EDOF,ENODE,NE,
     1	NDC,NDBC,NEXTNODE,INTIG)
	

	IMPLICIT NONE
	
	INTEGER ENODE,EDOF,NE,NTDOF
        INTEGER MDUMMY,K,KK,K1,K3,K4,K5,K6,MN

	INTEGER IDISP(NTDOF),NBCINT(NTDOF),NBCINT1(NTDOF)

        INTEGER NDC(NTDOF/3),NDBC(NTDOF/3)
        
	INTEGER NEXTINT(NTDOF),NINTEXT(NTDOF)
        
	INTEGER NEXTNODE(ENODE,NE),INTNODE(ENODE,NE),INTIG(EDOF,NE)

C	INITIALISING BCS ARRAY IN TERMS OF
C	INTERNAL NODE SYSTEM

	DO 10 KK = 1,NTDOF
	  NBCINT(KK)=1
10	CONTINUE
	

C	CONVERT BOUNDARY CONDITIONS INTO INTERNAL
C	NODE NUMBERING SYSTEM

	DO11K=1,NTDOF
	  IF(IDISP(K).EQ.0) THEN
	    MN=NEXTINT(K)
	    NBCINT(MN)=0
	  ENDIF
11	CONTINUE

C	MODIFING INTERNAL SYSTEM TO TAKE INTO
C	ACCOUNT BCS
	
	MN=1
	DOK1=1,NTDOF
	  IF(NBCINT(K1).EQ.1)THEN
	    NBCINT1(K1)=MN
	    MN=MN+1
	  ELSE
	    NBCINT1(K1)=0
	  ENDIF
	ENDDO	
	
	DOK3=1,NE
	  DOK4=1,ENODE
	    MDUMMY=NEXTNODE(K4,K3)
	    INTNODE(K4,K3)=NDC(MDUMMY)
	  ENDDO
	ENDDO

	DOK5=1,NE
	  DOK6=1,ENODE
	    MDUMMY=INTNODE(K6,K5)
	
	    INTIG(3*K6-2,K5)=NBCINT1(3*MDUMMY-2)
	    INTIG(3*K6-1,K5)=NBCINT1(3*MDUMMY-1)
	    INTIG(3*K6,K5)=NBCINT1(3*MDUMMY)

	  ENDDO
	ENDDO

	RETURN 
	END
	
C	********* SUBROUTINE FOR RENUMBERING ONLY **********

	SUBROUTINE RENUM(NTDOF,NCONTACT,NCOUNT,NDC,NDBC)


	IMPLICIT NONE
	
	INTEGER K,MM,MN,NN
	INTEGER NTDOF,NCOUNT
	
	INTEGER NCONTACT(NCOUNT)

	INTEGER  NDC(NTDOF/3),NDBC(NTDOF/3)

	DO 10 K=1,NTDOF/3
	  NDC(K)=0
10	CONTINUE

	MN=1

C	  NUMBERING CONTACT NODES FIRST
	  
	  DO K=1,NCOUNT
	    NN=NCONTACT(K)
	    NDC(NN)=MN
	    MN=MN+1
	  ENDDO

C	  NUMBERING REST NODES

	  DO K=1,NTDOF/3
	    IF(NDC(K).EQ.0) THEN
	      NDC(K)=MN
	      MN=MN+1
	    ENDIF
	  ENDDO
	
	DO 50 K=1,NTDOF/3
	  MM=NDC(K)
	  NDBC(MM)=K
50	CONTINUE

	RETURN
	END
