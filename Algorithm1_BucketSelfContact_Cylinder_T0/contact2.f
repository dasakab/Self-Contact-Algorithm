	SUBROUTINE CONTACT(SKYA,SKYB,SKY2,LOCA,LOCB,JCHTA,JCHTB,
     1	LOC2,JCHT2,GFOR,U,YK1I,F_HAT,XHITTING,YHITTING,ZHITTING,XSEG,
     1  YSEG,ZSEG,CONSEG,CSEG,CDISP_A,CDISP_B,NDC_A,NDC_B,NDBC_A,
     1  NDBC_B,C_REACT,C_R_INI,NCOUNT_A,NCOUNT_B,NDIMSKY_A,NDIMSKY_B,
     1  NDIMSKY2,NDIMLOC_A,NDIMLOC_B,NSEG,FRI,NTDOF_A,NTDOF_B,GETCON,
     1  INCNUMBER,ITR,NCSEG,NODE_SEG,INC_U,NELE_A,NELE_B,NODE_A,
     1  NODE_B,EDOF,ENODE,VELS1_A,VELS1_B,SIZE1,SIZE2,SIZE3,SIZE4,
     1	SIZE_SEG_IN,SIZE_SEG_OUT,S_HIT_COUNTER_IN,S_HIT_COUNTER_OUT,
     1	XHITTING_IN,YHITTING_IN,ZHITTING_IN,XHITTING_OUT,YHITTING_OUT,
     1	ZHITTING_OUT,XSEG_IN,YSEG_IN,ZSEG_IN,XSEG_OUT,YSEG_OUT,ZSEG_OUT,
     1	CONSEG_IN,CONSEG_OUT,CSEG_IN,CSEG_OUT, NCSEG_IN,NCSEG_OUT,
     1	NODE_SEG_OUT,NODE_SEG_IN,S_HNODE_IN,S_HNODE_OUT,TOTAL_TNODES_IN,
     1	TOTAL_TNODES_OUT)

C	OUT :: C_REACT,U	

	IMPLICIT NONE

     	COMMON/INTER/IA,IIA,IB,IIB,IDA,IDB,ID,IID
     	
	INTEGER IA,IIA,IB,IIB,IDA,IDB,ID,IID
	
	INTEGER NTDOF_A,NCOUNT_A,NDIMSKY_A,NDIMLOC_A
	INTEGER NTDOF_B,NCOUNT_B,NDIMSKY_B,NDIMLOC_B
	INTEGER NDIMSKY2
	INTEGER SIZE1,SIZE2,SIZE3,SIZE4,S1,S2,A_TYPE1,SIZE_SEG_IN,H,S3
	INTEGER S_HIT_COUNTER_IN,S_HIT_COUNTER_OUT,SIZE_SEG_OUT	
	
	
	INTEGER EDOF,ENODE,NELE_A,NELE_B
	INTEGER NODE_A(ENODE,NELE_A),NODE_B(ENODE,NELE_B)
	REAL *8 VELS1_A(EDOF,NELE_A),VELS1_B(EDOF,NELE_B)
	REAL *8 VELO(3*(NCOUNT_A+SIZE1+SIZE2+SIZE3+SIZE4+NCOUNT_B))

	INTEGER NSEG,C_ITR,IFLAG1,IFLAG,GETCON,INCNUMBER,ITR
	
	INTEGER IDDD,I,J,K1,K2,M,M1,M2
	
	INTEGER CDISP_A(3*NCOUNT_A),CDISP_B(3*NCOUNT_B)
	
	INTEGER NDC_A(NTDOF_A/3),NDBC_A(NTDOF_A/3)
	INTEGER NDC_B(NTDOF_B/3),NDBC_B(NTDOF_B/3)
	
	INTEGER LOCA(NDIMLOC_A),JCHTA(NDIMLOC_A)
	INTEGER LOCB(NDIMLOC_B),JCHTB(NDIMLOC_B)
	INTEGER LOC2(IID+1),JCHT2(IID+1),CNODE_K1

	INTEGER CONSEG(4,NSEG),CSEG(NCOUNT_A),NCSEG(NSEG)

	REAL*8 FRI,DETERM
	REAL*8 XHITTING(NCOUNT_A),YHITTING(NCOUNT_A),
     1	         ZHITTING(NCOUNT_A)
	
	REAL*8 XSEG(4,NSEG),YSEG(4,NSEG),ZSEG(4,NSEG)
	
	REAL*8 SKYA(NDIMSKY_A),SKYB(NDIMSKY_B)
	REAL*8 SKY2(NDIMSKY2)

	REAL*8 YK1I(ID,ID),ZK1I(ID,ID),F_HAT(ID)
	
	REAL*8 G_LANG(ID+3*NCOUNT_A+3*SIZE1+3*SIZE3,
     1               ID+3*NCOUNT_A+3*SIZE1+3*SIZE3),
     1       GF_LANG(ID+3*NCOUNT_A+3*SIZE1+3*SIZE3)
       
     	REAL*8 A(ID+3*NCOUNT_A+3*SIZE1+3*SIZE3,
     1	        ID+3*NCOUNT_A+3*SIZE1+3*SIZE3),
     1	      B(ID+3*NCOUNT_A+3*SIZE1+3*SIZE3)
     	
     	REAL*8 X(ID+3*NCOUNT_A+3*SIZE1+3*SIZE3)
     	
	REAL*8 Q1(3*NCOUNT_A+3*SIZE1+3*SIZE3,ID),
     1	       Q2(ID,3*NCOUNT_A+3*SIZE1+3*SIZE3)
    
	REAL*8 GFOR(ID+IID)
        
	REAL*8 C_R_INI(ID),C_REACT(ID)
	
	REAL*8 TTF1(NCOUNT_A+SIZE1+SIZE3),TTF2(NCOUNT_A+SIZE1+SIZE3),
     1	                                  TTF3(NCOUNT_A+SIZE1+SIZE3)
 
	REAL*8 C_FORCE(3*NCOUNT_A+3*SIZE1+3*SIZE3),
     1	      INI_CFOR(3*NCOUNT_A+3*SIZE1+3*SIZE3)           
	
	REAL*8 N1(3,NCOUNT_A),N2(3,NCOUNT_A),N3(3,NCOUNT_A)
	
	REAL*8 U2DIS(ID+IID),U(ID+IID)
 	
	INTEGER CNODE(NCOUNT_A),ROWS_Q1,CON_CONECT(5,NCOUNT_A)
	
	REAL*8 THETA(NCOUNT_A),DUMMY,INC_U(ID),INC_U_IN(ID)
	REAL*8 U_REL(NCOUNT_A)
	INTEGER MAX_SIZE,NODE_SEG(NCOUNT_B,4),CON_CONECT_K1(5)
	
	REAL*8 CZI(NCOUNT_A),CET(NCOUNT_A)
	REAL*8 N2_K1(3),N3_K1(3)
	REAL*8 CET_K1,CZI_K1,THETA_K1,U_REL_K1
C*********************************************************************
C	DECLARATION FOR SELF CONTACT

	INTEGER CNODE_IN(SIZE1),CNODE_OUT(SIZE3),CON_CONECT_IN(5,SIZE1)
        REAL*8  THETA_IN(SIZE1),THETA_OUT(SIZE3)
	REAL*8  XHITTING_IN(SIZE1),YHITTING_IN(SIZE1),ZHITTING_IN(SIZE1)
	REAL*8  XSEG_IN(4,SIZE_SEG_IN),YSEG_IN(4,SIZE_SEG_IN),
     1		ZSEG_IN(4,SIZE_SEG_IN)
	INTEGER CONSEG_IN(4,SIZE_SEG_IN),CSEG_IN(SIZE1)    
	INTEGER NCSEG_IN(SIZE_SEG_IN),NODE_SEG_IN(SIZE2,4)
	REAL*8  N1_IN(3,SIZE1),N2_IN(3,SIZE1),N3_IN(3,SIZE1)
	REAL*8 CZI_IN(SIZE1),CET_IN(SIZE1)
	REAL*8  XHITTING_OUT(SIZE3),YHITTING_OUT(SIZE3),
     1	                            ZHITTING_OUT(SIZE3)	
      	REAL*8  XSEG_OUT(4,SIZE_SEG_OUT),YSEG_OUT(4,SIZE_SEG_OUT),
     1		                         ZSEG_OUT(4,SIZE_SEG_OUT)	

        INTEGER CONSEG_OUT(4,SIZE_SEG_OUT),NCSEG_OUT(SIZE_SEG_OUT)
	INTEGER CSEG_OUT(SIZE3),NODE_SEG_OUT(SIZE4,4),S_HNODE_OUT(SIZE3)
	REAL*8  N1_OUT(3,SIZE3),N2_OUT(3,SIZE3),N3_OUT(3,SIZE3)
	INTEGER CON_CONECT_OUT(5,SIZE3),S_HNODE_IN(SIZE1)
	REAL*8 CZI_OUT(SIZE3),CET_OUT(SIZE3)
	INTEGER TOTAL_TNODES_IN(SIZE2),TOTAL_TNODES_OUT(SIZE4)
	REAL*8  U_REL_IN(SIZE1),U_REL_OUT(SIZE3)

C*********************************************************************	

		
	IF (NCOUNT_A .EQ. 0 .AND. S_HIT_COUNTER_IN .NE. 1
     1    .AND. S_HIT_COUNTER_OUT .NE. 1) GOTO 50    !BYPASS THE CONTACT CALCULATIONS
	
C	WRITE(*,*) 'CONTACT 0'
	MAX_SIZE = ID+3*NCOUNT_A+3*SIZE1+3*SIZE3
	
	DO I = 1,ID
	  DO J = 1,ID
	    ZK1I(I,J) = YK1I(I,J)
	  ENDDO
	ENDDO
	
	DO I = 1,ID
	  INC_U_IN(I) = INC_U(I)
	ENDDO
	
C	CNODE(K1) INDICATES CONTACT STATUS
C	    CNODE(K1)=0 : OUT OF CONTACT NODE
C	    CNODE(K1)=1 : SLIPPING NODE
C	    CNODE(K1)=3 : STICKING NODE

C	THETA(K1) IS THE ANGLE OF SHEAR FORCE WITH LOCAL N2 TANGENTIAL DIR.

C	IN THE FIRST CONTACT ITERATION ALL POTENTIAL HITTING NODES ARE 
C	ASSUMED TO BE IN STICKING CONDITION

	DO K1 = 1,NCOUNT_A
	  CNODE(K1) = 3
	  THETA(K1) = 0.0
	ENDDO
	
	IF (S_HIT_COUNTER_IN .EQ. 1) THEN
	DO K1 = 1,SIZE1
	  CNODE_IN(K1) = 3
	  THETA_IN(K1) = 0.0
	ENDDO
c	WRITE(*,*) 'CONTACT 1'
	ENDIF
	
	IF (S_HIT_COUNTER_OUT .EQ. 1) THEN
	DO K1 = 1,SIZE3
	  CNODE_OUT(K1) = 3
	  THETA_OUT(K1) = 0.0
	ENDDO
C	WRITE(*,*) 'CONTACT 2'
	ENDIF
	
	
C	CONTACT ITERATIONS AT THE BEGINNING OF ITERATION
	
	C_ITR = 1
	
	A_TYPE1 = NCOUNT_A+SIZE1+SIZE2+SIZE3+SIZE4
	S1 = NCOUNT_A
	S2 = NCOUNT_A+SIZE1+SIZE2
	S3 = 0
	CALL CONTACT_SEARCH(XHITTING,YHITTING,ZHITTING,XSEG,YSEG,
     1    ZSEG,CONSEG,CSEG,NCOUNT_A,NCOUNT_B,NSEG,ITR,NCSEG,
     1	  N1,N2,N3,NODE_SEG,CON_CONECT,CZI,CET,A_TYPE1,S1,S2,S3)
     
C	CALL CONTCT_SEARCH FOR BOTH INSIDE AND OUTSIDE NODES

	IF (S_HIT_COUNTER_IN .EQ. 1) THEN
C	OPEN(UNIT=16,FILE='HCOORD_IN_CONTACT')
C	DO K1= 1,SIZE1
C	WRITE(16,*)XHITTING_IN(K1),YHITTING_IN(K1),ZHITTING_IN(K1)
C	ENDDO
C	
C	DO K1=1,SIZE_SEG_IN
C	WRITE(*,*)'CONSEG_IN',CONSEG_IN(1,K1),CONSEG_IN(2,K1),
C    1				CONSEG_IN(3,K1),CONSEG_IN(4,K1)
C	ENDDO
C	
C	CLOSE(16)
C	OPEN(UNIT=17,FILE='TARGET_SEGS_IN_CONTACT')
C	DO K1=1,SIZE_SEG_IN
C	WRITE(17,*)XSEG_IN(1,K1),XSEG_IN(2,K1),XSEG_IN(3,K1),
C    1						XSEG_IN(4,K1)
C	WRITE(17,*)YSEG_IN(1,K1),YSEG_IN(2,K1),YSEG_IN(3,K1),
C     1						YSEG_IN(4,K1)
C	WRITE(17,*)ZSEG_IN(1,K1),ZSEG_IN(2,K1),ZSEG_IN(3,K1),
C     1						ZSEG_IN(4,K1)
C	ENDDO
C	CLOSE(17)
C	WRITE(*,*) 'SIZE1',SIZE1
C	WRITE(*,*) 'SIZE2',SIZE2
C	WRITE(*,*) 'NCSEG',NCSEG_IN(SIZE_SEG_IN)
C	
	S3 = NCOUNT_A+SIZE1
	CALL CONTACT_SEARCH(XHITTING_IN,YHITTING_IN,ZHITTING_IN,
     1	  XSEG_IN,YSEG_IN,ZSEG_IN,CONSEG_IN,CSEG_IN,SIZE1,
     1    SIZE2,SIZE_SEG_IN,ITR,NCSEG_IN,N1_IN,N2_IN,N3_IN,
     1	  NODE_SEG_IN,CON_CONECT_IN,CZI_IN,CET_IN,1,S1,S2,S3)
C     	DO K1=1,SIZE1
C	WRITE(*,*)CON_CONECT_IN(1,K1)
C	WRITE(*,*)CON_CONECT_IN(2,K1),CON_CONECT_IN(3,K1),
C     1	          CON_CONECT_IN(4,K1),CON_CONECT_IN(5,K1)
C	ENDDO
C	
C	DO K1 = 1,SIZE1
C	WRITE(*,*) CSEG_IN(K1)
C	ENDDO
C	

	ENDIF
C         WRITE(*,*) 'CONTACT 4'
         IF (S_HIT_COUNTER_OUT .EQ. 1) THEN
	S3 = NCOUNT_A+SIZE1+SIZE2+SIZE3
     	CALL CONTACT_SEARCH(XHITTING_OUT,YHITTING_OUT,ZHITTING_OUT,
     1	  XSEG_OUT,YSEG_OUT,ZSEG_OUT,CONSEG_OUT,CSEG_OUT,SIZE3,
     1    SIZE4,SIZE_SEG_OUT,ITR,NCSEG_OUT,N1_OUT,N2_OUT,
     1	  N3_OUT,NODE_SEG_OUT,CON_CONECT_OUT,CZI_OUT,CET_OUT,2,S1,S2,S3)
         ENDIF
     

	CALL VEL_PIC(NDBC_A,NDBC_B,VELS1_A,VELS1_B,
     1   NELE_A,NELE_B,NODE_A,NODE_B,VELO,ENODE,EDOF,
     1   NTDOF_A,NTDOF_B,NCOUNT_A,NCOUNT_B,ID,SIZE1,SIZE2,H,
     1	 S_HIT_COUNTER_IN,S_HNODE_IN,TOTAL_TNODES_IN,S_HIT_COUNTER_OUT,
     1   SIZE3,SIZE4,S_HNODE_OUT,TOTAL_TNODES_OUT)
     
C	WRITE(*,*) 'CONTACT 5'
     	
     	DO K1=1,NCOUNT_A
C     	   IF(CNODE(K1) .EQ. 1)THEN
     	     DO I=1,3
     	        N2_K1(I)=N2(I,K1)
     	        N3_K1(I)=N3(I,K1)
     	     ENDDO
     	     
     	     DO I=1,5
     	        CON_CONECT_K1(I)=CON_CONECT(I,K1)
     	        
     	     ENDDO
     	     
     	     CZI_K1=CZI(K1)
     	     CET_K1=CET(K1)

C       now relative velocities at the contact nodes of body A
C       calculated on the previous converged values of the velocities.
C       Theta is calculated on the basis of this relative velocities.
C       It is assumed that state (stick or slip not out of contact) of
C       the contact nodes does not change within the increment.

             CALL SLIP_DIR(VELO,THETA_K1,N2_K1,N3_K1,CZI_K1,CET_K1,
     1	        CON_CONECT_K1,U_REL_K1,NCOUNT_A,NCOUNT_B,CNODE_K1,ID)
       
            THETA(K1)=THETA_K1
            U_REL(K1)=U_REL_K1
            CNODE(K1)=CNODE_K1
C            WRITE(*,*)'CNODE',K1,':',CNODE_K1
C           ENDIF
        ENDDO  
	
	
C	FOR INNER SELF CONTACT     	
	IF (S_HIT_COUNTER_IN .EQ. 1) THEN	
	DO K1=1,SIZE1

     	     DO I=1,3
     	        N2_K1(I)=N2_IN(I,K1)
     	        N3_K1(I)=N3_IN(I,K1)
     	     ENDDO
     	     
     	     DO I=1,5
     	        CON_CONECT_K1(I)=CON_CONECT_IN(I,K1)
     	        
     	     ENDDO
     	     
     	     CZI_K1=CZI_IN(K1)
     	     CET_K1=CET_IN(K1)


             CALL SLIP_DIR(VELO,THETA_K1,N2_K1,N3_K1,CZI_K1,CET_K1,
     1	        CON_CONECT_K1,U_REL_K1,SIZE1,SIZE2,CNODE_K1,ID)
       
            THETA_IN(K1)=THETA_K1
            U_REL_IN(K1)=U_REL_K1
            CNODE_IN(K1)=CNODE_K1
	    
C            WRITE(*,*)'CNODE_IN',K1,':',CNODE_K1	    

        ENDDO  	
	ENDIF
	
	
C	FOR OUTER SELF CONTACT     	
	IF (S_HIT_COUNTER_OUT.EQ. 1) THEN	
	DO K1=1,SIZE3

     	     DO I=1,3
     	        N2_K1(I)=N2_OUT(I,K1)
     	        N3_K1(I)=N3_OUT(I,K1)
     	     ENDDO
     	     
     	     DO I=1,5
     	        CON_CONECT_K1(I)=CON_CONECT_OUT(I,K1)
     	        
     	     ENDDO
     	     
     	     CZI_K1=CZI_OUT(K1)
     	     CET_K1=CET_OUT(K1)


             CALL SLIP_DIR(VELO,THETA_K1,N2_K1,N3_K1,CZI_K1,CET_K1,
     1	        CON_CONECT_K1,U_REL_K1,SIZE3,SIZE4,CNODE_K1,ID)
       
            THETA_OUT(K1)=THETA_K1
            U_REL_OUT(K1)=U_REL_K1
            CNODE_OUT(K1)=CNODE_K1
	    
C            WRITE(*,*)'CNODE_OUT',K1,':',CNODE_K1	    

        ENDDO  	
	ENDIF	
C     	WRITE(*,*) 'CONTACT COUNTER 1'
	
100	WRITE(*,*) 'CONTACT ITERATIONS = ', C_ITR
	WRITE(710,*) '  '
	WRITE(710,*)'CONTACT ITERATIONS = ',C_ITR	
	WRITE(710,*) '  '
	
	IFLAG1 = 0  !FLAG FOR CHECKING CONTACT STATUS
	
C	WRITE(*,*) 'CONTACT COUNTER 2'
     	CALL K_CONTACT(Q1,Q2,N1,N2,N3,CNODE,NCOUNT_A,ID,FRI,ROWS_Q1,
     1	    THETA,CON_CONECT,CZI,CET,SIZE1,SIZE3,
     1	   S_HIT_COUNTER_IN,CZI_IN,CET_IN,N1_IN,N2_IN,N3_IN,CNODE_IN,
     1	   CON_CONECT_IN,THETA_IN,S_HIT_COUNTER_OUT,CZI_OUT,CET_OUT,
     1	   N1_OUT,N2_OUT,N3_OUT,CNODE_OUT,CON_CONECT_OUT,THETA_OUT)
     	
C	WRITE(*,*) 'CONTACT COUNTER 3'
	CALL LANG (ZK1I,G_LANG,NCOUNT_A,ID,Q1,Q2,ROWS_Q1,SIZE1,SIZE3)
	
C	WRITE(*,*) 'CONTACT COUNTER 4'
C	G_LANG FORMAT 

C	 ___     ___
C	|           |    Q1 : (ROWS_Q1) X (ID)
C	|  0   -Q1  |  
C	|           |    Q2 : (ID) X (ROWS_Q1)
C	| -Q2    K  |
C	|__      ___|
	
C	WRITE(*,*) 'CONTACT COUNTER 5'
C	WRITE(*,*) 'ID',ID
C	DO K1=1,ID
C	WRITE(*,*)'F_HAT',F_HAT(K1)
C	ENDDO
C	 
	CALL CON_RSVEC(XHITTING,YHITTING,ZHITTING,XSEG,YSEG,
     1    ZSEG,CON_CONECT,NSEG,CSEG,Q1,NCOUNT_A,ID,F_HAT,GF_LANG,
     1    ROWS_Q1,S_HIT_COUNTER_IN,SIZE1,SIZE2,SIZE_SEG_IN,
     1	  S_HIT_COUNTER_OUT,SIZE3,SIZE_SEG_OUT,XHITTING_IN,YHITTING_IN,
     1	  ZHITTING_IN,CSEG_IN,CON_CONECT_IN,XSEG_IN,YSEG_IN,ZSEG_IN,
     1	  XHITTING_OUT,YHITTING_OUT,ZHITTING_OUT,CSEG_OUT,CON_CONECT_OUT,
     1	  XSEG_OUT,YSEG_OUT,ZSEG_OUT)  
     
C	WRITE(*,*) 'CONTACT COUNTER 6'
 	CALL CONTACT_CONDITION(G_LANG,GF_LANG,CNODE,CDISP_A,CDISP_B,
     1	  NCOUNT_A,NCOUNT_B,A,B,NTDOF_A,THETA,ROWS_Q1,S_HIT_COUNTER_IN,
     1	  SIZE1,S_HIT_COUNTER_OUT,SIZE3,CNODE_IN,CNODE_OUT)
     
C	WRITE(*,*) 'CONTACT COUNTER 7'
	IDDD = ID+ROWS_Q1
	
	CALL GAUSS_ELMN(A,B,IDDD,X,MAX_SIZE,ROWS_Q1)
C	CALL solve(A,B,IDDD,X)
	DO I = 1,IDDD
	  B(I) = X(I)
	ENDDO

	DO I = 1,ID
	  U(I) = B(I+ROWS_Q1)
	  INC_U(I) = INC_U_IN(I) + U(I)
	ENDDO
		
C	LAGRANGE MULTIPLIERS (CONTACT FORCES)
C	WRITE(*,*) 'CONTACT COUNTER 8'
	J = 1
	DO I = 1, NCOUNT_A
	  IF ( CNODE(I).EQ.3) THEN
	    C_FORCE(3*I-2) = B(J)
	    C_FORCE(3*I-1) = B(J+1)
	    C_FORCE(3*I) = B(J+2)
	    J = J+3
	  ELSEIF (CNODE(I) .EQ. 1) THEN
	    C_FORCE(3*I-2) = B(J)
	    C_FORCE(3*I-1) = 0.0 
	    C_FORCE(3*I) = 0.0   
	    J = J+1
	    ELSEIF (CNODE(I) .EQ. 0) THEN
	    C_FORCE(3*I-2) = 0.0
	    C_FORCE(3*I-1) = 0.0
	    C_FORCE(3*I) = 0.0
	    J = J+3
	  END IF
	ENDDO
	
C	MODIFICATION FOR SELF CONTACT
	IF(S_HIT_COUNTER_IN .EQ. 1) THEN
	
	DO I = 1, SIZE1
	  IF ( CNODE_IN(I).EQ.3) THEN
	    C_FORCE(3*NCOUNT_A+3*I-2) = B(J)
	    C_FORCE(3*NCOUNT_A+3*I-1) = B(J+1)
	    C_FORCE(3*NCOUNT_A+3*I) = B(J+2)
	    J = J+3
	  ELSEIF (CNODE_IN(I) .EQ. 1) THEN
	    C_FORCE(3*NCOUNT_A+3*I-2) = B(J)
	    C_FORCE(3*NCOUNT_A+3*I-1) = 0.0 
	    C_FORCE(3*NCOUNT_A+3*I) = 0.0   
	    J = J+1
	    ELSEIF (CNODE_IN(I) .EQ. 0) THEN
	    C_FORCE(3*NCOUNT_A+3*I-2) = 0.0
	    C_FORCE(3*NCOUNT_A+3*I-1) = 0.0
	    C_FORCE(3*NCOUNT_A+3*I) = 0.0
	    J = J+3
	  END IF
	ENDDO
	
	ENDIF
	
	IF(S_HIT_COUNTER_OUT .EQ. 1) THEN
	
	DO I = 1, SIZE3
	  IF ( CNODE_OUT(I).EQ.3) THEN
	    C_FORCE(3*NCOUNT_A+3*SIZE1+3*I-2) = B(J)
	    C_FORCE(3*NCOUNT_A+3*SIZE1+3*I-1) = B(J+1)
	    C_FORCE(3*NCOUNT_A+3*SIZE1+3*I) = B(J+2)
	    J = J+3
	  ELSEIF (CNODE_OUT(I) .EQ. 1) THEN
	    C_FORCE(3*NCOUNT_A+3*SIZE1+3*I-2) = B(J)
	    C_FORCE(3*NCOUNT_A+3*SIZE1+3*I-1) = 0.0 
	    C_FORCE(3*NCOUNT_A+3*SIZE1+3*I) = 0.0   
	    J = J+1
	    ELSEIF (CNODE_OUT(I) .EQ. 0) THEN
	    C_FORCE(3*NCOUNT_A+3*SIZE1+3*I-2) = 0.0
	    C_FORCE(3*NCOUNT_A+3*SIZE1+3*I-1) = 0.0
	    C_FORCE(3*NCOUNT_A+3*SIZE1+3*I) = 0.0
	    J = J+3
	  END IF
	ENDDO
	
	ENDIF
	
C	--------------------------------------------------------

C	CALCULATING INITIAL CONTACT FORCES. ALL DIRECTIONS FOR HITTING -
C	NODE ARE TAKEN TO BE OPPOSITE TO THAT OF THE TARGET SEGMENT.
C	WRITE(*,*) 'CONTACT COUNTER 9'
	DO K1 = 1,NCOUNT_A
	  INI_CFOR(3*K1-2) = -(N1(1,K1)*C_R_INI(3*K1-2)+
     1	               N1(2,K1)*C_R_INI(3*K1-1) + N1(3,K1)*C_R_INI(3*K1))

