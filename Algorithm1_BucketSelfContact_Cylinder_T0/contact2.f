	REAL*8 DFDET,DGDET
	REAL*8 HH,KK

	REAL*8 XC(4),YC(4),ZC(4)
	REAL*8 DN(4),DNDZI(4),DNDET(4),DNDZIDET(4)

	ZI = 0.0
	ET = 0.0
C	WRITE(*,*)'INSIDE C POINT'
	
	ITR =0
	
100	ITR = ITR +1

	CALL CONTACTN(DN,DNDZI,DNDET,DNDZIDET,ZI,ET)
	
	X = 0.0
	Y = 0.0
	Z = 0.0
	
	DO K1 = 1,4
	  X = X + XC(K1)*DN(K1)
	  Y = Y + YC(K1)*DN(K1)
	  Z = Z + ZC(K1)*DN(K1)
	ENDDO

	DXDZI = 0.0
	DXDET = 0.0
	DYDZI = 0.0
	DYDET = 0.0
	DZDZI = 0.0
	DZDET = 0.0
	
	DO K1 = 1,4
	  DXDZI = DXDZI + XC(K1)*DNDZI(K1)
	  DXDET = DXDET + XC(K1)*DNDET(K1)
	  DYDZI = DYDZI + YC(K1)*DNDZI(K1)
	  DYDET = DYDET + YC(K1)*DNDET(K1)
	  DZDZI = DZDZI + ZC(K1)*DNDZI(K1)
	  DZDET = DZDET + ZC(K1)*DNDET(K1)
	ENDDO
C	WRITE(*,*)'C POINT 2'
 	DXDZIDET = 0.0	
 	DYDZIDET = 0.0	
 	DZDZIDET = 0.0	
	
	DO K1 = 1,4
	  DXDZIDET = DXDZIDET + XC(K1)*DNDZIDET(K1)
	  DYDZIDET = DYDZIDET + YC(K1)*DNDZIDET(K1)
	  DZDZIDET = DZDZIDET + ZC(K1)*DNDZIDET(K1)
	ENDDO

	F = DXDZI*(X-XH) + DYDZI*(Y-YH) + DZDZI*(Z-ZH)
	
	G = DXDET*(X-XH) + DYDET*(Y-YH) + DZDET*(Z-ZH)
	
	DFDZI = DXDZI**2 + DYDZI**2 +DZDZI**2

	DFDET = DXDZIDET*DXDET + DYDZIDET*DYDET + DZDZIDET*DZDET
	
	DGDZI = DXDZIDET*DXDZI + DYDZIDET*DYDZI + DZDZIDET*DZDZI
	
	DGDET = DXDET**2 + DYDET**2 +DZDET**2

	KK = (-F*DGDZI+G*DFDZI)/(DFDET*DGDZI - DGDET*DFDZI)

	HH = (-F-KK*DFDET)/DFDZI

	IF((HH .LT. 0.0001) .AND. (KK .LT. 0.0001)) THEN
	  ZI = ZI + HH
	  ET = ET + KK
	ELSE
	  ZI = ZI + HH
	  ET = ET + KK
	 
	  GOTO 100
	ENDIF
C	WRITE(*,*)'C POINT 3'
	RETURN
	END

C	SUBROUTINE TO STORE SHAPE FUNCTION AND THEIR
C	DERIVATIVES FOR CONTACT FACES
	
	SUBROUTINE CONTACTN(DN,DNDZI,DNDET,DNDZIDET,ZI,ET)

	IMPLICIT NONE

	REAL*8 ZI,ET
	
	REAL*8 DN(4),DNDZI(4),DNDET(4),DNDZIDET(4)

	DN(1) = (1-ZI)*(1-ET)/4.0
	DN(2) = (1+ZI)*(1-ET)/4.0
	DN(3) = (1+ZI)*(1+ET)/4.0
	DN(4) = (1-ZI)*(1+ET)/4.0
	
	DNDZI(1) = -(1-ET)/4.0
	DNDZI(2) =  (1-ET)/4.0
	DNDZI(3) =  (1+ET)/4.0
	DNDZI(4) = -(1+ET)/4.0

	DNDET(1) = -(1-ZI)/4.0
	DNDET(2) = -(1+ZI)/4.0
	DNDET(3) =  (1+ZI)/4.0
	DNDET(4) =  (1-ZI)/4.0

	DNDZIDET(1) =  1.0/4.0
	DNDZIDET(2) = -1.0/4.0
	DNDZIDET(3) =  1.0/4.0
	DNDZIDET(4) = -1.0/4.0

	RETURN
	END

