	DO J = 1,IIA
	 J2 = J+IA
	 IF(JCHTA(J2) .GT. J)THEN
	  JCHT2(J)=J
	 ELSE
	  JCHT2(J)=JCHTA(J2)
	 ENDIF
	ENDDO
	
	LOC2(1)=1
	
	DO J = 1,IIA
	 LOC2(J+1)=LOC2(J)+JCHT2(J)
	ENDDO
	
