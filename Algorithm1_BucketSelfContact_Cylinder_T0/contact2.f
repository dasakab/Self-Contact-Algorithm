	INTEGER K5,K6,S_HNODE_OUT(SIZE_HIT_OUT)
	INTEGER TOTAL_TNODES_OUT(SIZE_TTOTAL_OUT)
	INTEGER K7,MM,NELE,ENODE,NDUMMY
	INTEGER NODE(ENODE,NELE),INTNODE(ENODE,NELE)
	INTEGER NSEG_IN,SIZE_SEG_IN,SIZE_SEG_OUT,NSEG_OUT
	INTEGER NCSEG_IN(SIZE_SEG_IN),S_CONSEG_IN(4,SIZE_SEG_IN)
	INTEGER ND,CONSEG_IN(4,SIZE_SEG_IN)
	INTEGER NCSEG_OUT(SIZE_SEG_OUT),S_CONSEG_OUT(4,SIZE_SEG_OUT)
	INTEGER CONSEG_OUT(4,SIZE_SEG_OUT)
	
	
C	FINDING CONNECTIVITY IN INTERNAL SYSTEM
	
	DO K1 = 1,NTDOF/3
	  NDC(K1) = 0
	ENDDO

	  MN = 1

C	  WRITE(*,*) 'SEG1'
C	  NUMBERING CONTACT NODES FIRST (FOR BODY A ONLY)
	  
	  DO K2 = 1,NCOUNT
	    NN=NCONTACT(K2)
	    NDC(NN)=MN
	    MN=MN+1
C		WRITE(*,*)'AFTER EXT CONTCT',(MN-1)
	  ENDDO
	  
C	  WRITE(*,*) 'SEG2'
