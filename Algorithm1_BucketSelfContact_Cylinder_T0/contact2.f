C	SUBROUTINE FOR CHECKING THE SLIPPING DIRECTION BASED ON CONTACT -
C	NODE DISPLACEMENTS

	SUBROUTINE SLIP_DIR(INC_U,THETA,N2,N3,ZI,ET,CON_CONECT,U_REL,
     1	  NCOUNT_A,NCOUNT_B,CNODE,ID)
     
     
	
C	OUT :: THETA,IFLAG1
	
	IMPLICIT NONE
	
	INTEGER ID,IFLAG1,CON_CONECT(5)

        INTEGER I,J,ND,NCOUNT_A,NCOUNT_B,CNODE

	REAL *8 THETA_OLD,THETA,N2(3),N3(3),ZI,ET
	REAL *8 INC_U(ID) ! CHANGE DECLARATION

	REAL *8 QC(3,15),N2QC(15),N3QC(15)
	REAL *8 U2_REL,U3_REL,U_REL,DUMMY
	
	REAL*8, PARAMETER :: PI = 3.141592654
	
	
C	THETA_OLD = THETA
C	WRITE(*,*) 'CONTACT COUNTER 104'
	CALL Q_C(ZI,ET,QC)
C	WRITE(*,*) 'CONTACT COUNTER 105'
	DO I = 1,15	    	  
	  N2QC(I) = N2(1)*QC(1,I)+N2(2)*QC(2,I)+N2(3)*QC(3,I)
	  N3QC(I) = N3(1)*QC(1,I)+N3(2)*QC(2,I)+N3(3)*QC(3,I)     
	ENDDO
	
	U2_REL = 0.0
	U3_REL = 0.0
	
	DO I = 1,5
	  
	  ND = CON_CONECT(I)
  	  U2_REL = U2_REL - N2QC(3*I-2)*INC_U(3*ND-2) - N2QC(3*I-1)*
     1       INC_U(3*ND-1) - N2QC(3*I)*INC_U(3*ND)

	  U3_REL = U3_REL - N3QC(3*I-2)*INC_U(3*ND-2) - N3QC(3*I-1)*
     1       INC_U(3*ND-1) - N3QC(3*I)*INC_U(3*ND)

	ENDDO
	
	U_REL = SQRT(U2_REL**2+U3_REL**2)
	
	IF (U_REL .GT. 1E-3) THEN
	  CNODE=1
	  THETA = ACOS(ABS(U2_REL/U_REL))
	
	  IF (U2_REL .LT. 0.0 .AND. U3_REL .GE. 0.0)  
     1			THETA = PI - THETA
	  IF (U2_REL .LT. 0.0 .AND. U3_REL .LT. 0.0)  
     1			THETA = PI + THETA
          IF (U2_REL .GE. 0.0 .AND. U3_REL .LT. 0.0)  
     1			THETA = -THETA
       ELSE
         CNODE=3
         THETA=0.0
	
	ENDIF
	
	RETURN
	END
	
C      This subroutine picks the values of (here velocity, but
C      acceleration and coordinates can also be picked) the
C      contact nodes for both bodies. Values of body A are
C      stored first.

       SUBROUTINE VEL_PIC(NDBC_A,NDBC_B,VELS1_A,VELS1_B,
     1   NELE_A,NELE_B,NODE_A,NODE_B,VELO,ENODE,EDOF,
     1   NTDOF_A,NTDOF_B,NCOUNT_A,NCOUNT_B,ID,SIZE1,SIZE2,H,
     1	 S_HIT_COUNTER_IN,S_HNODE_IN,TOTAL_TNODES_IN,S_HIT_COUNTER_OUT,
     1   SIZE3,SIZE4,S_HNODE_OUT,TOTAL_TNODES_OUT)
       
       IMPLICIT NONE
          
       	INTEGER NELE_A,NELE_B,ENODE,EDOF
       	INTEGER NTDOF_A,NTDOF_B,ID
    	INTEGER NCOUNT_A,NCOUNT_B
     	INTEGER S_HIT_COUNTER_IN,SIZE1,SIZE2,H 
	INTEGER S_HIT_COUNTER_OUT,SIZE3,SIZE4             
      	 INTEGER NODE_A(ENODE,NELE_A),NODE_B(ENODE,NELE_B)
      	 INTEGER NDBC_A(NTDOF_A/3),NDBC_B(NTDOF_B/3)
       
      	 INTEGER I,J,DUMMY,K
       
      	 REAL *8 VELS1_A(EDOF,NELE_A),VELS1_B(EDOF,NELE_B)
      	 REAL *8 VELO(3*(NCOUNT_A+SIZE1+SIZE2+SIZE3+SIZE4+NCOUNT_B))
      	 REAL *8 VEL_A(3*NTDOF_A),VEL_B(3*NTDOF_B)
C*********************************************************************
C	DECLARATIONS FOR SELF CONTACT

	INTEGER S_HNODE_IN(SIZE1),TOTAL_TNODES_IN(SIZE2)

	INTEGER S_HNODE_OUT(SIZE3),TOTAL_TNODES_OUT(SIZE4)
C*********************************************************************             
C       WRITE(*,*) 'CONTACT COUNTER 106'
       DO I=1,NELE_A
          DO J=1,ENODE
            DUMMY=NODE_A(J,I)
            VEL_A(3*DUMMY-2)=VELS1_A(3*J-2,I)
            VEL_A(3*DUMMY-1)=VELS1_A(3*J-1,I)
            VEL_A(3*DUMMY)=VELS1_A(3*J,I)
          ENDDO
       ENDDO
       DO I=1,NELE_B
          DO J=1,ENODE
            DUMMY=NODE_B(J,I)
            VEL_B(3*DUMMY-2)=VELS1_B(3*J-2,I)
            VEL_B(3*DUMMY-1)=VELS1_B(3*J-1,I)
            VEL_B(3*DUMMY)=VELS1_B(3*J,I)
          ENDDO
       ENDDO
C       WRITE(*,*)'INSIDE EL_PIC'
       K = 1
       DO I=1,NCOUNT_A
         J=NDBC_A(I)
          VELO(3*K-2)=VEL_A(3*J-2) 
          VELO(3*K-1)=VEL_A(3*J-1)   
          VELO(3*K)=VEL_A(3*J)
          K = K+1
       ENDDO
       
       
       IF(S_HIT_COUNTER_IN .EQ. 1) THEN
       DO I = 1,SIZE1
       	  H = S_HNODE_IN(I)
	  VELO(3*K-2)=VEL_A(3*H-2) 
          VELO(3*K-1)=VEL_A(3*H-1)   
          VELO(3*K)=VEL_A(3*H)
          K = K+1
	ENDDO
	
	DO I = 1,SIZE2
	   H = TOTAL_TNODES_IN(I)
	   VELO(3*K-2)=VEL_A(3*H-2) 
           VELO(3*K-1)=VEL_A(3*H-1)   
           VELO(3*K)=VEL_A(3*H)
           K = K+1
C	WRITE(*,*)'EXTRACTING VELOCITY',VELO(3*K)
	ENDDO
       ENDIF
       
       IF(S_HIT_COUNTER_OUT .EQ. 1) THEN
       DO I = 1,SIZE3
       	  H = S_HNODE_OUT(I)
	  VELO(3*K-2)=VEL_A(3*H-2) 
          VELO(3*K-1)=VEL_A(3*H-1)   
          VELO(3*K)=VEL_A(3*H)
          K = K+1
	ENDDO
	
	DO I = 1,SIZE4
	   H = TOTAL_TNODES_OUT(I)
	   VELO(3*K-2)=VEL_A(3*H-2) 
           VELO(3*K-1)=VEL_A(3*H-1)   
           VELO(3*K)=VEL_A(3*H)
           K = K+1
	ENDDO
       ENDIF 

C      K is the next free contact-node slot following the
C      ordinary, inner-hit, inner-target, outer-hit, outer-target
C      velocity entries. Do not overwrite self-contact velocities.
       DO I=1,NCOUNT_B
         J=NDBC_B(I)
         VELO(3*(K+I-1)-2)=VEL_B(3*J-2)
         VELO(3*(K+I-1)-1)=VEL_B(3*J-1)
         VELO(3*(K+I-1))=VEL_B(3*J)
       ENDDO
     
       RETURN
       END
