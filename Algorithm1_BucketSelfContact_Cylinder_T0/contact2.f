c	SUBROUTINE TO APPLY CONTACT CONDITION
	
	
	  SUBROUTINE CONTACT_CONDITION(ZK1I,GF,CNODE,CDISP_A,CDISP_B,
     1	  NCOUNT_A,NCOUNT_B,A,B,NTDOF_A,THETA,ROWS_Q1,S_HIT_COUNTER_IN,
     1	  SIZE1,S_HIT_COUNTER_OUT,SIZE3,CNODE_IN,CNODE_OUT)


C	OUT :: A,B

	IMPLICIT NONE
	
	COMMON/INTER/IA,IIA,IB,IIB,IDA,IDB,ID,IID
	
	INTEGER IA,IIA,IB,IIB,IDA,IDB,ID,IID,ROWS_Q1
        INTEGER NCOUNT_A,NCOUNT_B,JCONTCT,NTDOF_A
	INTEGER I,J,NN,MM,KK,K1,SIZE1,SIZE3
	
	INTEGER IDISP(ID+3*NCOUNT_A+3*SIZE1+3*SIZE3)
	
	INTEGER CDISP_A(3*NCOUNT_A),CDISP_B(3*NCOUNT_B)

	REAL*8 ZK1I(ID+3*NCOUNT_A+3*SIZE1+3*SIZE3,
     1	        ID+3*NCOUNT_A+3*SIZE1+3*SIZE3)
        REAL*8 GF(ID+3*NCOUNT_A+3*SIZE1+3*SIZE3)

	REAL*8 A(ID+3*NCOUNT_A+3*SIZE1+3*SIZE3,
     1	        ID+3*NCOUNT_A+3*SIZE1+3*SIZE3)
        REAL*8 B(ID+3*NCOUNT_A+3*SIZE1+3*SIZE3)
	
	REAL*8 U(ID+3*NCOUNT_A+3*SIZE1+3*SIZE3)

	INTEGER CNODE(NCOUNT_A), ROW_NUM
	REAL *8 THETA(NCOUNT_A)
C********************************************************************
C	DECLARATIONS FOR SELF CONTACT
	INTEGER S_HIT_COUNTER_IN,S_HIT_COUNTER_OUT
	INTEGER CNODE_IN(SIZE1),CNODE_OUT(SIZE3)

C********************************************************************	

C	WRITE(*,*) 'CONTACT COUNTER 18'
C       WRITE [ZK1I] IN [A] AND WORK WITH [A]
        DO 700 I = 1,ID+ROWS_Q1
        DO 700 J = 1,ID+ROWS_Q1
           A(I,J) = ZK1I(I,J)
700     CONTINUE

C       WRITE [GF] INTO [B] AND WORK WITH [B]
        
	DO 800 I = 1,ID+ROWS_Q1
           B(I) = GF(I)
800     CONTINUE
 
C       APPLYING THE BOUNDARY CONDITIONS: 
C       STORING THE D.O.F. FOR WHICH THE DISP IS PRESCRIBED AS:
C        IDISP(I) = 0 IF I TH D.O.F. IS A DISPLACEMENT B.C. OR A CONTACT - 
C		FORCE CORRESPONDING TO AN OUT OF CONTACT NODE
C        IDISP(I) = 1 IF I TH D.O.F. IS A FORCE B.C. (ZERO OR NON-ZERO)
C       ------------------------------------------------------------
C	WRITE(*,*) 'CONTACT COUNTER 19'
	DO K1 = 1,ID+ROWS_Q1
	  IDISP(K1) = 1
	ENDDO

C	BOUNDARY CONDITIONS ALONG CONTACT FOR HITTING BODY
C	WRITE(*,*) 'CONTACT COUNTER 20'
	DO K1 = 1,3*NCOUNT_A
	  IDISP(ROWS_Q1+K1) = CDISP_A(K1)
	ENDDO

C	BONDARY CONDITIONS ALONG CONTACT FOR TARGET BODY
C	WRITE(*,*) 'CONTACT COUNTER 21'
	DO K1 = 1,3*NCOUNT_B
	  IDISP(ROWS_Q1+IA+K1) = CDISP_B(K1)
	ENDDO

C	IF NODE GOES OUT OF CONTACT CORRESPONDING LAGRANGE MULTIPLIER
C	IS ZERO (CONTACT FORCE AT THAT NODE IS ZERO)
C	WE NEED TO ENFORCE ABOVE CONDITION
	
C	WRITE(*,*) 'CONTACT COUNTER 22'
	ROW_NUM = 1
	DO K1 = 1,NCOUNT_A
	  JCONTCT = CNODE(K1)	  
	  IF(JCONTCT .EQ. 0) THEN
	    IDISP(ROW_NUM) = 0
	    IDISP(ROW_NUM+1) = 0
	    IDISP(ROW_NUM+2) = 0
	  ENDIF
	  ROW_NUM = ROW_NUM + 1
	  IF (JCONTCT .EQ. 0 .OR. JCONTCT .EQ. 3) ROW_NUM = ROW_NUM+2
	ENDDO

	IF(S_HIT_COUNTER_IN .EQ. 1) THEN
	DO K1 = 1,SIZE1
	  JCONTCT = CNODE_IN(K1)	  
	  IF(JCONTCT .EQ. 0) THEN
	    IDISP(ROW_NUM) = 0
	    IDISP(ROW_NUM+1) = 0
	    IDISP(ROW_NUM+2) = 0
	  ENDIF
	  ROW_NUM = ROW_NUM + 1
	  IF (JCONTCT .EQ. 0 .OR. JCONTCT .EQ. 3) ROW_NUM = ROW_NUM+2
	ENDDO
	ENDIF
	
	IF(S_HIT_COUNTER_OUT .EQ. 1) THEN
	DO K1 = 1,SIZE3
	  JCONTCT = CNODE_OUT(K1)	  
	  IF(JCONTCT .EQ. 0) THEN
	    IDISP(ROW_NUM) = 0
	    IDISP(ROW_NUM+1) = 0
	    IDISP(ROW_NUM+2) = 0
	  ENDIF
	  ROW_NUM = ROW_NUM + 1
	  IF (JCONTCT .EQ. 0 .OR. JCONTCT .EQ. 3) ROW_NUM = ROW_NUM+2
	ENDDO
	ENDIF
C       MODIFY THE GLOBAL STIFFNESS MATRIX, [A],
C        TO TAKE CARE OF DISPLACEMENT B.C.S.
C       ------------------------------------------------------------
C	WRITE(*,*) 'CONTACT COUNTER 23'
        DO 2351 I=1,ID+ROWS_Q1
          DO 2357 J=1,ID+ROWS_Q1
            IF(IDISP(I) .NE. 1 .OR. IDISP(J) .NE. 1) A(I,J) = 0.0
            IF(I .EQ. J .AND. IDISP(I) .EQ. 0) A(I,J) = 1.0
            IF(IDISP(I) .EQ. 0) B(I) = 0.0
      
2357      CONTINUE
2351    CONTINUE
	
	RETURN 
	END

C	SUBROUTINE TO CHECK CONTACT STATUS 

	SUBROUTINE CHECK_CONTACT(NDBC_A,TTF1,TTF2,TTF3,CNODE,THETA,FRI,
     1	  NTDOF_A,NCOUNT_A,IFLAG1,INC_U,N2,N3,CON_CONECT,ID,CZI,CET,
     1	  S_HIT_COUNTER_IN,S_HIT_COUNTER_OUT,SIZE1,SIZE2,SIZE3,CNODE_IN,
     1	  CNODE_OUT)


C	OUT :: CNODE,THETA,IFLAG1

	IMPLICIT NONE
	
	INTEGER NTDOF_A,NCOUNT_A,ID
	INTEGER IFLAG1,NONO,JCONTCT,I,J,L
	
	INTEGER NDBC_A(NTDOF_A/3)
	INTEGER T,S_HIT_COUNTER_IN,SIZE1,S_HIT_COUNTER_OUT,SIZE3
	INTEGER X,SIZE2
     	REAL*8 TTF1(NCOUNT_A+SIZE1+SIZE3),TTF2(NCOUNT_A+SIZE1+SIZE3),
     1	                                  TTF3(NCOUNT_A+SIZE1+SIZE3)
	REAL*8 FRI,TTFT(NCOUNT_A),THETA(NCOUNT_A)
	
	INTEGER CNODE(NCOUNT_A),CON_CONECT(5,NCOUNT_A)
	
	REAL *8 N2(3,NCOUNT_A),N3(3,NCOUNT_A)
	REAL *8 CZI(NCOUNT_A),CET(NCOUNT_A)
	REAL *8 INC_U(ID),MAX_F1,TAN_F_RATIO(NCOUNT_A),MAX_RATIO
	
	REAL *8 N2_L(3),N3_L(3),CZI_L,CET_L,THETA_L
	INTEGER CON_CONECT_L(5)
	
	REAL*8, PARAMETER :: PI = 3.141592654
C********************************************************************
C	DECLARATIONS FOR SELF CONTACT

	INTEGER CNODE_IN(SIZE1),CNODE_OUT(SIZE3)

C********************************************************************
	
C	WRITE(*,*) 'CONTACT COUNTER 24'
	IFLAG1 = 0
	MAX_F1 = 1.0E-15
	T = NCOUNT_A
	IF(S_HIT_COUNTER_IN .EQ. 1) THEN
	  T = NCOUNT_A+SIZE1
	ENDIF
	IF(S_HIT_COUNTER_OUT .EQ. 1) THEN
	  T = NCOUNT_A+SIZE1+SIZE3
	ENDIF
	
	DO L = 1,T
	  IF (TTF1(L) .GT. MAX_F1) MAX_F1 = TTF1(L)
	ENDDO
	
C	WRITE(*,*) 'CONTACT COUNTER 25'
	IF (MAX_F1 .GT. 1.1E-15) THEN
	  
	  DO L = 1,T
	 
C       NDBC_A stores the ordinary candidate nodes, not the
C       appended self-contact node list.  Use the local ordinal
C       for self-contact diagnostics until the original global
C       node lists are passed into this routine.
          IF (L .LE. NCOUNT_A) THEN
            NONO = NDBC_A(L)
          ELSE
            NONO = -L
          ENDIF
	    
	    IF (TTF1(L) .GE. (MAX_F1/5.0)) THEN
	        
	      WRITE(710,*)'OUT OF CONTACT NODE ',NONO
	      WRITE(710,*)' TTF1 = ',TTF1(L),'    TTF2 = ',TTF2(L),
     1			'    TTF3 = ',TTF3(L)
	      
     
               IF (L .LE. NCOUNT_A) THEN
            IF (CNODE(L) .NE. 0) IFLAG1=1
            CNODE(L)=0
          ELSEIF (L .LE. NCOUNT_A+SIZE1) THEN
            X = L-NCOUNT_A
            IF (CNODE_IN(X) .NE. 0) IFLAG1=1
            CNODE_IN(X)=0
          ELSEIF (L .LE. NCOUNT_A+SIZE1+SIZE3) THEN
            X = L-NCOUNT_A-SIZE1
            IF (CNODE_OUT(X) .NE. 0) IFLAG1=1
            CNODE_OUT(X)=0
          ENDIF
	      
	    ENDIF	
	  ENDDO
	  
          RETURN	  
	ENDIF


	RETURN

        END
