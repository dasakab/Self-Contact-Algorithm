C	SUBROUTINE TO FIND DIRECTION VECTOR

	SUBROUTINE DIR_VECTOR(XC,YC,ZC,PT_N1,PT_N2,PT_N3,ZI,ET)

C	OUT :: PT_N1,PT_N2,PT_N3
	
	IMPLICIT NONE

	INTEGER K2
	
	REAL*8 NORM,IN1,JN1,KN1
	REAL*8 ZI,ET,IN3,JN3,KN3
	REAL*8 DXDZI,DYDZI,DZDZI
	REAL*8 DXDET,DYDET,DZDET

	REAL*8 XC(4),YC(4),ZC(4)
	
	REAL*8 DN(4),DNDZI(4),DNDET(4),DNDZIDET(4)

	REAL*8 PT_N1(3),PT_N2(3),PT_N3(3)

	CALL CONTACTN(DN,DNDZI,DNDET,DNDZIDET,ZI,ET)

	    DXDZI = 0.0
	    DXDET = 0.0
	    DYDZI = 0.0
	    DYDET = 0.0
	    DZDZI = 0.0
	    DZDET = 0.0

	  DO K2 = 1,4
	    DXDZI = DXDZI + XC(K2)*DNDZI(K2)
	    DXDET = DXDET + XC(K2)*DNDET(K2)
	    DYDZI = DYDZI + YC(K2)*DNDZI(K2)
	    DYDET = DYDET + YC(K2)*DNDET(K2)
	    DZDZI = DZDZI + ZC(K2)*DNDZI(K2)
	    DZDET = DZDET + ZC(K2)*DNDET(K2)
	  ENDDO
	  
	  NORM = SQRT(DXDZI**2+DYDZI**2+DZDZI**2)

	  PT_N2(1) = DXDZI/NORM
	  PT_N2(2) = DYDZI/NORM
	  PT_N2(3) = DZDZI/NORM

C	  NORM = SQRT(DXDET**2+DYDET**2+DZDET**2)
C
C	  PT_N3(1) = DXDET/NORM
C	  PT_N3(2) = DYDET/NORM
C	  PT_N3(3) = DZDET/NORM
	
	  IN1 =  (DYDZI*DZDET - DZDZI*DYDET)
	  JN1 = -(DXDZI*DZDET - DZDZI*DXDET)
	  KN1 =  (DXDZI*DYDET - DYDZI*DXDET)
	
	  NORM = SQRT(IN1**2+JN1**2+KN1**2)

	  PT_N1(1) = IN1/NORM
	  PT_N1(2) = JN1/NORM
	  PT_N1(3) = KN1/NORM
	  
	  IN3 = (PT_N1(2)*PT_N2(3)-PT_N1(3)*PT_N2(2))
	  JN3 = -(PT_N1(1)*PT_N2(3)-PT_N1(3)*PT_N2(1))
	  KN3 = (PT_N1(1)*PT_N2(2)-PT_N1(2)*PT_N2(1))

	  NORM = SQRT(IN3**2+JN3**2+KN3**2)
	  
	  PT_N3(1) = IN3/NORM
	  PT_N3(2) = JN3/NORM
	  PT_N3(3) = KN3/NORM
	  

	
	RETURN
	END


