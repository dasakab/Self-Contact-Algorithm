C	CALCULATING NORMAL AND SHEAR STRESSES ON THE BOUNDARY
	
	SUBROUTINE BSTRESS(GPSTRESS,NST_VECTOR,XSEG,YSEG,ZSEG,B_GP,
     1	  CFACE,NODE,NTDOF,NELE,NSEG,ENODE,NG)


	IMPLICIT NONE

	INTEGER NDUMMY,K1,K2,K3,M1,M2,NE,NF
	INTEGER ENODE,NSEG,NELE,NTDOF,NG

	INTEGER NODE(8,NELE)
	INTEGER CFACE(2,NSEG)

	REAL*8 E,Z,SI
	REAL*8 SF(ENODE)

	REAL*8 XC(4),YC(4),ZC(4)
	REAL*8 XSEG(4,NSEG),YSEG(4,NSEG),ZSEG(4,NSEG)

	REAL*8 B_GP(4,3,6)  !STORES GAUSS POINT COORD. FOR BOUNDARY

	REAL*8 N1(4,3,NSEG),N2(4,3,NSEG),N3(4,3,NSEG)
	REAL*8 PT_N1(3),PT_N2(3),PT_N3(3)

	REAL*8 BDST(6),NODST(6,8)
	REAL*8 CSTRESS_C(6),CSTRESS_M(3,3)
	REAL*8 GPSTRESS(NG*NG*NG,6,NELE)
	REAL*8 BDSTRESS(4,6,NSEG),NDSTRESS(8,6,NELE)

	REAL*8 ST_VECTOR(4,3,NSEG),NST_VECTOR(4,3,NSEG)

C	CALLING SUBROUTINE FOR FINDING NORMAL STRESS

	CALL NSTRESS (GPSTRESS,NDSTRESS,NODE,NTDOF,NELE,NG)

C	FINDING BOUNDARY STRESSES

	DO K1 = 1,NSEG
	  NF = CFACE(1,K1)
	  NE  = CFACE(2,K1)

	  DO M1 = 1,8
	    DO M2 = 1,6
	      NODST(M2,M1) = NDSTRESS(M1,M2,NE)
	    ENDDO
	  ENDDO

	  NDUMMY = 1
	  DO K3 = 1,4

	    E  = B_GP(NDUMMY,1,NF)
	    Z  = B_GP(NDUMMY,2,NF)
	    SI = B_GP(NDUMMY,3,NF)

	    CALL SF_3DL(SF,E,Z,SI)

	    CALL MATMUL(NODST,SF,BDST,6,ENODE,1)

	    DO M1 = 1,6
	      BDSTRESS(NDUMMY,M1,K1) = BDST(M1)
	    ENDDO

	    NDUMMY = NDUMMY +1
	  ENDDO


	ENDDO

	
	DO K1 = 1,NSEG
	  
	  DO M1 = 1,4
	    XC(M1) = XSEG(M1,K1)
	    YC(M1) = YSEG(M1,K1)
	    ZC(M1) = ZSEG(M1,K1)
	  ENDDO
	 
	 NDUMMY = 1
	  DO K2 = 1,2
	    DO K3 = 1,2
	      
	      NF = CFACE(1,K1)
	      
	      IF((NF .EQ. 1) .OR. (NF .EQ. 2)) THEN
	        E = B_GP(NDUMMY,1,NF)
	        Z = B_GP(NDUMMY,2,NF)
	      ELSEIF((NF .EQ. 3) .OR. (NF .EQ. 4)) THEN
	        E = B_GP(NDUMMY,1,NF)
	        Z = B_GP(NDUMMY,3,NF)
	      ELSEIF((NF .EQ. 5) .OR. (NF .EQ. 6)) THEN
	        E = B_GP(NDUMMY,2,NF)
	        Z = B_GP(NDUMMY,3,NF)
	      ENDIF 
	      
	      CALL DIR_VECTOR(XC,YC,ZC,PT_N1,PT_N2,PT_N3,Z,E)
	     
	      DO M1 = 1,3
	        N1(NDUMMY,M1,K1) = PT_N1(M1)
	        N2(NDUMMY,M1,K1) = PT_N2(M1)
	        N3(NDUMMY,M1,K1) = PT_N3(M1)
	      ENDDO
	      
	      NDUMMY = NDUMMY + 1
	    ENDDO
	  ENDDO
	
	ENDDO

	DO K1 = 1,NSEG
	  DO K2 = 1,4
	    
	    DO M1 = 1,6
	      CSTRESS_C(M1) = BDSTRESS(K2,M1,K1)
	    ENDDO

	    CALL COLM_SMAT(CSTRESS_C,CSTRESS_M)

	    ST_VECTOR(K2,1,K1) = CSTRESS_M(1,1)*N1(K2,1,K1) +
     1	                         CSTRESS_M(1,2)*N1(K2,2,K1) +
     1	                         CSTRESS_M(1,3)*N1(K2,3,K1) 
	    
	    ST_VECTOR(K2,2,K1) = CSTRESS_M(2,1)*N1(K2,1,K1) +
     1	                         CSTRESS_M(2,2)*N1(K2,2,K1) +
     1	                         CSTRESS_M(2,3)*N1(K2,3,K1) 
	    
	    ST_VECTOR(K2,3,K1) = CSTRESS_M(3,1)*N1(K2,1,K1) +
     1	                         CSTRESS_M(3,2)*N1(K2,2,K1) +
     1	                         CSTRESS_M(3,3)*N1(K2,3,K1) 
	    
	    NST_VECTOR(K2,1,K1) = ST_VECTOR(K2,1,K1)*N1(K2,1,K1) +
     1	                          ST_VECTOR(K2,2,K1)*N1(K2,2,K1) +
     1	                          ST_VECTOR(K2,3,K1)*N1(K2,3,K1) 
	    
	    NST_VECTOR(K2,2,K1) = ST_VECTOR(K2,1,K1)*N2(K2,1,K1) +
     1	                          ST_VECTOR(K2,2,K1)*N2(K2,2,K1) +
     1	                          ST_VECTOR(K2,3,K1)*N2(K2,3,K1) 
	    
	    NST_VECTOR(K2,3,K1) = ST_VECTOR(K2,1,K1)*N3(K2,1,K1) +
     1	                          ST_VECTOR(K2,2,K1)*N3(K2,2,K1) +
     1	                          ST_VECTOR(K2,3,K1)*N3(K2,3,K1) 
	  
	  ENDDO
	ENDDO
	
	RETURN
	END

C	SUBROUTINE FOR FINDING NODAL STRESSES
	
	SUBROUTINE NSTRESS (GPSTRESS,NDSTRESS,NODE,NTDOF,NELE,NG)

	
	IMPLICIT NONE

	INTEGER NDUMMY,ND,K1,K2,K3,M,M1
	INTEGER NELE,NTDOF,NG
	INTEGER NODE(8,NELE),DNODE(NTDOF/3)

	REAL*8 E,Z,SI,DETERM

	REAL*8 GP(2)
	REAL*8 AN(8,8),SF(8)
	REAL*8 BDUMMY(8)

	REAL*8 GPSTRESS(NG*NG*NG,6,NELE)
	REAL*8 NDSTRESS(8,6,NELE)
	REAL*8 DSTRESS(6,NTDOF/3)
	
C	FOR FINDING NODAL STRESS LINEAR VARIATION OF STRESS 
C	IS ASSUMED

C	FINDING NODAL STRESSES ONLY WHEN TWO GAUSS POINTS ARE USED

	GP(1) = 0.57735
	GP(2) = -0.57735
	
	NDUMMY = 1

	DO K1 = 1,2
	  DO K2 = 1,2
	    DO K3 = 1,2
	      
	      E  = GP(K1)
	      Z  = GP(K2)
	      SI = GP(K3)
	     
	      CALL SF_3DL(SF,E,Z,SI)
	      
	      DO M1 = 1,8
		AN(NDUMMY,M1) = SF(M1)
	      ENDDO

	      NDUMMY = NDUMMY + 1
	     ENDDO
	   ENDDO
	ENDDO

	CALL MATIN(AN,8,BDUMMY,0,DETERM)
	
	DO K1 = 1,NELE
	  DO K2 = 1,8
	    DO K3 = 1,6
	      
	        NDSTRESS(K2,K3,K1)= AN(K2,1)*GPSTRESS(1,K3,K1)+
     1                              AN(K2,2)*GPSTRESS(2,K3,K1)+
     1                              AN(K2,3)*GPSTRESS(3,K3,K1)+
     1                              AN(K2,4)*GPSTRESS(4,K3,K1)+
     1                              AN(K2,5)*GPSTRESS(5,K3,K1)+
     1                              AN(K2,6)*GPSTRESS(6,K3,K1)+
     1                              AN(K2,7)*GPSTRESS(7,K3,K1)+
     1                              AN(K2,8)*GPSTRESS(8,K3,K1)

	    ENDDO
	  ENDDO
	ENDDO

C	FINDING AVERAGE NODAL STRESSES
	
	DO K1 = 1,NTDOF/3
	  DNODE(K1) = 0
	ENDDO

	DO K1 = 1,NELE
	  DO K2 = 1,8
	    ND = NODE(K2,K1)
	    DNODE(ND) = DNODE(ND) +1
	  ENDDO
	ENDDO
	
	DO K1 = 1,NTDOF/3
	  DO K3 = 1,6
	    DSTRESS(K3,K1) = 0.0
	  ENDDO
	ENDDO
	
	DO K1 = 1,NELE
	  DO K2 = 1,8
	    ND = NODE(K2,K1)
	    
	    IF(ND .EQ. 0) THEN
	      WRITE(711,*) 'ERROR IN NODE NUMBERING'
	      WRITE(711,*) 'NSTRESS SUBROUTINE '
	      WRITE(711,*) 'TERMINATING EXECUTION '

	      STOP
	    ENDIF
	    
	    DO K3 = 1,6
	      DSTRESS(K3,ND) = DSTRESS(K3,ND) + NDSTRESS(K2,K3,K1)
	    ENDDO
	  ENDDO
	ENDDO
	
	DO K1 = 1,NTDOF/3
	  DO K2 = 1,6
	    DSTRESS(K2,K1) = DSTRESS(K2,K1)/DNODE(K1)
	  ENDDO
	ENDDO
	
	DO K1 = 1,NELE
	  DO K2 = 1,8
	    ND = NODE(K2,K1)
	    DO K3 = 1,6
	      NDSTRESS(K2,K3,K1) = DSTRESS(K3,ND)
	    ENDDO
	  ENDDO
	ENDDO

	RETURN
	END


C	SUBROUTINE FOR STORING  3-D LINEAR SHAPE FUNCTION
	
	SUBROUTINE SF_3DL(SF,E,Z,SI)

	IMPLICIT NONE
	
	REAL*8 E,Z,SI
	REAL*8 SF(8)

	SF(1) = (1-Z)*(1-E)*(1-SI)/8.0
	SF(2) = (1+Z)*(1-E)*(1-SI)/8.0
	SF(3) = (1+Z)*(1+E)*(1-SI)/8.0
	SF(4) = (1-Z)*(1+E)*(1-SI)/8.0
	
	SF(5) = (1-Z)*(1-E)*(1+SI)/8.0
	SF(6) = (1+Z)*(1-E)*(1+SI)/8.0
	SF(7) = (1+Z)*(1+E)*(1+SI)/8.0
	SF(8) = (1-Z)*(1+E)*(1+SI)/8.0
								
	RETURN
	END



