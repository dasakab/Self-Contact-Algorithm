     	    TTF3(K1) = -FRI*TTF1(K1)*SIN(THETA(K1))
           ELSE
           TTF2(K1) = INI_CFOR(3*K1-1) + C_FORCE(3*K1-1)
	    TTF3(K1) = INI_CFOR(3*K1) + C_FORCE(3*K1)
          ENDIF
