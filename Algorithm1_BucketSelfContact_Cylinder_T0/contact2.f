	IMPLICIT NONE
	
	INTEGER K1,NTDOF,MN,K2,NCOUNT,NN
	INTEGER S_HIT_COUNTER_IN,SIZE1,SIZE2,SIZE3,SIZE4
	INTEGER NDC(NTDOF/3),NCONTACT(NCOUNT),NDBC(NTDOF/3)
	INTEGER SIZE_HIT_IN,SIZE_TTOTAL_IN,SIZE_HIT_OUT,SIZE_TTOTAL_OUT
	INTEGER K3,K4,S_HNODE_IN(SIZE_HIT_IN)
	INTEGER TOTAL_TNODES_IN(SIZE_TTOTAL_IN)
