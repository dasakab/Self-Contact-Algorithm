	IF (S_HIT_COUNTER_IN .EQ. 1) THEN
		SIZE1 = SIZE_HIT_IN
		SIZE2 = SIZE_TTOTAL_IN
		DO K3 = 1,SIZE1
			NN = S_HNODE_IN(K3)
			NDC(NN) = MN
			MN = MN+1
C		WRITE(*,*)'IN iN H CONTCT',(MN-1),NDC(NN)
		ENDDO 
		DO K4 = 1,SIZE2
			NN = TOTAL_TNODES_IN(K4)
			NDC(NN) = MN
			MN = MN+1
C		WRITE(*,*)'TRGT NODES',(MN-1),NDC(NN)
		ENDDO
	ENDIF
C	WRITE(*,*) 'SEG3'
C	NUMBERING SC_OUT NODES NEXT
	IF (S_HIT_COUNTER_OUT .EQ. 1) THEN
C	WRITE(*,*)'RENUMBERING'
C	
		SIZE3 = SIZE_HIT_OUT
		SIZE4 = SIZE_TTOTAL_OUT
		DO K5 = 1,SIZE3
			NN = S_HNODE_OUT(K5)
			NDC(NN) = MN
			MN = MN+1
		ENDDO 
		DO K6 = 1,SIZE4
			NN = TOTAL_TNODES_OUT(K6)
			NDC(NN) = MN
			MN = MN+1
		ENDDO
	ENDIF	  
	  
C	  WRITE(*,*) 'SEG4'
C	  NUMBERING REST NODES
	  DO K7 = 1,NTDOF/3
	    IF(NDC(K7) .EQ. 0) THEN
	      NDC(K7)=MN
	      MN=MN+1
	    ENDIF
	  ENDDO
	
C	  WRITE(*,*) 'SEG5'
C	REVERSE RELATION	  
	DO K4 = 1,NTDOF/3
	  MM=NDC(K4)
	  NDBC(MM)=K4
	ENDDO

C	WRITE(*,*) 'SEG6'
C	ELEMENT CONNECTIVITY IN INTERNAL SYSTEM	
	DO K1 = 1,NELE
	  DO K2 = 1,ENODE
 	    NDUMMY = NODE(K2,K1)
C	    WRITE(*,*) NDUMMY
C	    WRITE(*,*) NDC(NDUMMY)
	    INTNODE(K2,K1) = NDC(NDUMMY)
	  ENDDO
	ENDDO

	
C	WRITE(*,*) 'SEG7'
	IF (S_HIT_COUNTER_IN .EQ. 1) THEN	
	NSEG_IN = SIZE_SEG_IN
	DO K1 = 1,NSEG_IN
	NCSEG_IN(K1) = 1
	    DO K2 = 1,4
	    ND = S_CONSEG_IN(K2,K1)
	    CONSEG_IN(K2,K1) = NDC(ND)  !CONSEG_IN IN NEW NUMBERING SYS
	    ENDDO
	ENDDO
	ENDIF

c	DO K1=1,NSEG_IN
C	WRITE(*,*)'S_CONSEG_IN',S_CONSEG_IN(1,K1),S_CONSEG_IN(2,K1),
C     1	                        S_CONSEG_IN(3,K1),S_CONSEG_IN(4,K1)
C	ENDDO
c	DO K1 = 1,NSEG_IN
C	WRITE(*,*)'CONSEG_IN',CONSEG_IN(1,K1),CONSEG_IN(2,K1),
C     1				CONSEG_IN(3,K1),CONSEG_IN(4,K1)
C	ENDDO
C	
C	WRITE(*,*) 'SEG8 IN'
	IF (S_HIT_COUNTER_OUT .EQ. 1) THEN
	NSEG_OUT = SIZE_SEG_OUT
	DO K1 = 1,NSEG_OUT
	NCSEG_OUT(K1) = 1
	    DO K2 = 1,4
	    ND = S_CONSEG_OUT(K2,K1)
	    CONSEG_OUT(K2,K1) = NDC(ND)
	    ENDDO
	ENDDO
	ENDIF
	
C	WRITE(*,*) 'SEG9'
	RETURN
	END
	
		
