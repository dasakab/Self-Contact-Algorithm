	  JCHT2(J)=J-IIA
	 ELSE
	  JCHT2(J)=JCHTB(J2)
	 ENDIF
	ENDDO
	
	DO J = IIA+1,IID
	 LOC2(J+1)=LOC2(J)+JCHT2(J)
	ENDDO
	
	NDIMSKY2=LOC2(IID)+JCHT2(IID)-1
	
