	SUBROUTINE C_BCON (IDISP,NCONTACT,CDISP,NDC,NDBC,
     1	  EDOF,ENODE,NTDOF,NCOUNT,RNUMBER,S_HIT_COUNTER_IN,
     1	  S_HIT_COUNTER_OUT,S_HNODE_IN,TOTAL_TNODES_IN,S_HNODE_OUT,
     1    TOTAL_TNODES_OUT,SIZE1,SIZE2,SIZE3,SIZE4)
  


	IMPLICIT NONE
	
	INTEGER EDOF,ENODE,NTDOF,NCOUNT,RNUMBER
	INTEGER K,MN,K1,KK,ND

	INTEGER NCONTACT(NCOUNT)

	INTEGER IDISP(NTDOF),NBCINT(NTDOF)
	INTEGER NDC(NTDOF/3),NDBC(NTDOF/3)
	INTEGER NEXTINT(NTDOF),NINTEXT(NTDOF)
	
	INTEGER CDISP(3*NCOUNT)
C*********************************************************************
C	DECLARATIONS FOR SELF CONTACT
	INTEGER SIZE1,SIZE2,SIZE3,SIZE4
	INTEGER S_HIT_COUNTER_IN,S_HIT_COUNTER_OUT
	INTEGER TOTAL_TNODES_IN(SIZE2),S_HNODE_IN(SIZE1),
     1		TOTAL_TNODES_OUT(SIZE4),S_HNODE_OUT(SIZE3)

C*********************************************************************	
	

C	WRITE(*,*) 'CONTACT COUNTER 87'
	CALL CONCON(NTDOF,EDOF,ENODE,NCONTACT,NCOUNT,NDC,NDBC,
     1	  NEXTINT,NINTEXT,RNUMBER,S_HIT_COUNTER_IN,S_HIT_COUNTER_OUT,
     1    S_HNODE_IN,TOTAL_TNODES_IN,S_HNODE_OUT,TOTAL_TNODES_OUT,SIZE1,
     1	  SIZE2,SIZE3,SIZE4)
	
     
C	WRITE(*,*) 'CONTACT COUNTER 88'
C	INITIALISING BCS ARRAY IN TERMS OF
C	INTERNAL NODE SYSTEM

	DO 10 KK = 1,NTDOF
	  NBCINT(KK)=1
10	CONTINUE
	

C	CONVERT BOUNDARY CONDITIONS INTO INTERNAL
C	NODE NUMBERING SYSTEM

	DO 11 K = 1,NTDOF
	  IF(IDISP(K) .EQ. 0) THEN
	    MN = NEXTINT(K)
	    NBCINT(MN) = 0
	  ENDIF
11	CONTINUE
	
	DO K1 = 1,NCOUNT
	  
	  ND = NCONTACT(K1)

C	  CONTACT REGION BOUNDARY CONDITIONS

	  CDISP(3*K1-2) = NBCINT(3*K1-2)
	  CDISP(3*K1-1) = NBCINT(3*K1-1)
	  CDISP(3*K1)   = NBCINT(3*K1)
	  
C	  NON-CONTACT REGION  BOUNDARY CONDITIONS

	  IDISP(3*ND-2) = 1
	  IDISP(3*ND-1) = 1
	  IDISP(3*ND)   = 1
	
	ENDDO

	RETURN
	END
	
