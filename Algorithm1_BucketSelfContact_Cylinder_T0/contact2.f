C	SUBROUTINE TO FIND THE CONNECTIVITY OF CONTACT SEGMENTS (WITHIN BODY)
C	RENUMBERING OF SOFTBODY IS DONE HERE
	SUBROUTINE S_CON_SEGMENT(NTDOF,NCOUNT,S_HIT_COUNTER_IN,SIZE1,
     1	SIZE2,SIZE3,SIZE4,NDC,NCONTACT,NDBC,SIZE_HIT_IN,SIZE_TTOTAL_IN,
     1	SIZE_HIT_OUT,SIZE_TTOTAL_OUT,S_HNODE_IN,TOTAL_TNODES_IN,
