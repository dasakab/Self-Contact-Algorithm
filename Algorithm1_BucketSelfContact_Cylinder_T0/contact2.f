C	SUBROUTINE TO FIND POTENTIAL HITTING NODES AND TARGET SEGMENTS

	SUBROUTINE CSEGM(XHITTING,YHITTING,ZHITTING,XSEG,YSEG,ZSEG,
     1	  HNODE,NCSEG,NCOUNT_AM,NSEG,LENGTH)


	IMPLICIT NONE

	INTEGER NCOUNT_AM,NSEG
        
	INTEGER K1,K2,K3
	
	INTEGER HNODE(NCOUNT_AM),NCSEG(NSEG)
	
	REAL*8 XHIT,YHIT,ZHIT
	REAL*8 XMAX,YMAX,ZMAX,XMIN,YMIN,ZMIN
       	REAL*8 LENGTH
	
	REAL*8 XHITTING(NCOUNT_AM),YHITTING(NCOUNT_AM),
     1	  ZHITTING(NCOUNT_AM)
	
	REAL*8 XSEG(4,NSEG),YSEG(4,NSEG),ZSEG(4,NSEG)

        REAL*8 XTERRI(2,NSEG),YTERRI(2,NSEG),ZTERRI(2,NSEG)
     	

	DO K1 = 1,NCOUNT_AM
	  HNODE(K1) = 0
	ENDDO
	
	DO K2 = 1,NSEG
	  NCSEG(K2) = 0
	ENDDO


	DO K1 = 1,NCOUNT_AM
	  
	  XHIT = XHITTING(K1)
	  YHIT = YHITTING(K1)
	  ZHIT = ZHITTING(K1)
	  
	  DO K2 = 1,NSEG
	    IF (HNODE(K1) .NE. 1 .OR. NCSEG(K2) .NE. 1) THEN   
	      XMIN = XSEG(1,K2)
	      YMIN = YSEG(1,K2)
	      ZMIN = ZSEG(1,K2)
	  
	      XMAX = XSEG(1,K2)
	      YMAX = YSEG(1,K2)
	      ZMAX = ZSEG(1,K2)
	 
	      DOK3=1,4
	        IF(XMIN.GT.XSEG(K3,K2)) XMIN = XSEG(K3,K2)
	        IF(YMIN.GT.YSEG(K3,K2)) YMIN = YSEG(K3,K2)
	        IF(ZMIN.GT.ZSEG(K3,K2)) ZMIN = ZSEG(K3,K2)
	   	     
	        IF(XMAX.LT.XSEG(K3,K2)) XMAX = XSEG(K3,K2)
	        IF(YMAX.LT.YSEG(K3,K2)) YMAX = YSEG(K3,K2)
	        IF(ZMAX.LT.ZSEG(K3,K2)) ZMAX = ZSEG(K3,K2)
	   	  
	      ENDDO

	      XTERRI(1,K2) = XMIN - LENGTH
	      XTERRI(2,K2) = XMAX + LENGTH

	      YTERRI(1,K2) = YMIN - LENGTH
	      YTERRI(2,K2) = YMAX + LENGTH
	  
	      ZTERRI(1,K2) = ZMIN - LENGTH
	      ZTERRI(2,K2) = ZMAX + LENGTH
	      
	      	      
	      IF((XHIT.GE.XTERRI(1,K2)).AND.(XHIT.LE.XTERRI(2,K2)).AND.
     1	       (YHIT.GE.YTERRI(1,K2)).AND.(YHIT.LE.YTERRI(2,K2)).AND.
     1	       (ZHIT.GE.ZTERRI(1,K2)).AND.(ZHIT.LE.ZTERRI(2,K2))) THEN
     	         
     	         HNODE(K1) = 1
     	         NCSEG(K2) = 1
     	      ENDIF

	    ENDIF
	  ENDDO
	ENDDO
	
	RETURN
	END
	
C	SUBROUTINE TO FIND CONNECTIVITY OF CONTACT SEGMENTS
	
	SUBROUTINE CON_SEGMENT(NODE,NCONTACT,CFACE,FNODE,
     1	  CONSEG,NCOUNT,ENODE,NTDOF,NELE,NSEG)
	
	IMPLICIT NONE
	
	INTEGER NDUMMY,ND,K1,K2,K3,K4,MM,MN,NN,NCF,NCE
	INTEGER ENODE,NTDOF,NELE,NSEG,NCOUNT
	INTEGER NODE(ENODE,NELE),INTNODE(ENODE,NELE)
	INTEGER NDC(NTDOF/3),NDBC(NTDOF/3)
	INTEGER CFACE(2,NSEG),NCONTACT(NCOUNT)
	INTEGER FNODE(4,6)
	
	INTEGER CONSEG(4,NSEG)

C	FINDING CONNECTIVITY IN INTERNAL SYSTEM
	
	DO K1 = 1,NTDOF/3
	  NDC(K1) = 0
	ENDDO

	  MN = 1

C	  NUMBERING CONTACT NODES FIRST
	  
	  DO K2 = 1,NCOUNT
	    NN=NCONTACT(K2)
	    NDC(NN)=MN
	    MN=MN+1
	  ENDDO

C	  NUMBERING REST NODES

	  DO K3 = 1,NTDOF/3
	    IF(NDC(K3) .EQ. 0) THEN
	      NDC(K3)=MN
	      MN=MN+1
	    ENDIF
	  ENDDO
	
	DO K4 = 1,NTDOF/3
	  MM=NDC(K4)
	  NDBC(MM)=K4
	ENDDO

	DO K1 = 1,NELE
	  DO K2 = 1,ENODE
 	    NDUMMY = NODE(K2,K1)
	    INTNODE(K2,K1) = NDC(NDUMMY)
	  ENDDO
	ENDDO

	DO K1 = 1,NSEG
	    NCF = CFACE(1,K1)
	    NCE = CFACE(2,K1)
	  DO K2 = 1,4
	    ND = FNODE(K2,NCF)
	    CONSEG(K2,K1) = INTNODE(ND,NCE)
	  ENDDO
	ENDDO

	RETURN
	END

