CC	SUBROUTINE FOR CALCULATING THE RIGHTSIDE VECTOR -
C	FOR CONTACT ITERATIONS

	SUBROUTINE CON_RSVEC(XHITTING,YHITTING,ZHITTING,XSEG,YSEG,
     1    ZSEG,CON_CONECT,NSEG,CSEG,Q1,NCOUNT_A,ID,F_HAT,GF_LANG,
     1    ROWS_Q1,S_HIT_COUNTER_IN,SIZE1,SIZE2,SIZE_SEG_IN,
     1	  S_HIT_COUNTER_OUT,SIZE3,SIZE_SEG_OUT,XHITTING_IN,YHITTING_IN,
     1	  ZHITTING_IN,CSEG_IN,CON_CONECT_IN,XSEG_IN,YSEG_IN,ZSEG_IN,
     1	  XHITTING_OUT,YHITTING_OUT,ZHITTING_OUT,CSEG_OUT,
     1	  CON_CONECT_OUT,XSEG_OUT,YSEG_OUT,ZSEG_OUT)
     

C	OUT :: GF_LANG
	
	IMPLICIT NONE

	INTEGER NCOUNT_A,ID,NSEG
	INTEGER I,J,NDUMMY,K1,K2,ND
	INTEGER S_HIT_COUNTER_IN,SIZE1,SIZE2,SIZE_SEG_IN	
	INTEGER CON_CONECT(5,NCOUNT_A)
	INTEGER CSEG(NCOUNT_A)
     	INTEGER S_HIT_COUNTER_OUT,SIZE3,SIZE_SEG_OUT
	REAL*8 XHITTING(NCOUNT_A),YHITTING(NCOUNT_A),
     1	         ZHITTING(NCOUNT_A)
	
	REAL*8 XSEG(4,NSEG),YSEG(4,NSEG),ZSEG(4,NSEG)

	REAL*8 UCOORD(ID)

	REAL*8 Q1(3*NCOUNT_A+3*SIZE1+3*SIZE3,ID)

	INTEGER ROWS_Q1
	
	REAL *8 F_HAT(ID), GF_LANG(ID+3*NCOUNT_A+3*SIZE1+3*SIZE3), 
     1	                                              P0(ROWS_Q1)
	
c*******************************************************************
C	DECLARATIONS FOR SELF CONTACT

	REAL*8  XHITTING_IN(SIZE1),YHITTING_IN(SIZE1),
     1	                           ZHITTING_IN(SIZE1)
     	INTEGER CSEG_IN(SIZE1),CON_CONECT_IN(5,SIZE1)
	REAL*8  XSEG_IN(4,SIZE_SEG_IN),YSEG_IN(4,SIZE_SEG_IN),
     1		ZSEG_IN(4,SIZE_SEG_IN)

	REAL*8  XHITTING_OUT(SIZE3),YHITTING_OUT(SIZE3),
     1	                            ZHITTING_OUT(SIZE3)
     	INTEGER CSEG_OUT(SIZE3),CON_CONECT_OUT(5,SIZE3)
	REAL*8  XSEG_OUT(4,SIZE_SEG_OUT),YSEG_OUT(4,SIZE_SEG_OUT),
     1		ZSEG_OUT(4,SIZE_SEG_OUT)	
     
C*******************************************************************

C	CALCULATION OF INITIAL PENETRATION P0
	
C	WRITE(*,*) 'CONTACT COUNTER 35'
C	WRITE(*,*) 'ID',ID
C	WRITE(*,*) 'SIZE3',SIZE3
C	
	DO K1 = 1,NCOUNT_A
	  UCOORD(3*K1-2)= XHITTING(K1)
	  UCOORD(3*K1-1)= YHITTING(K1)
	  UCOORD(3*K1)  = ZHITTING(K1)
	ENDDO

	DO K1 = 1,NCOUNT_A
	  DO K2 = 1,4
	    NDUMMY = CSEG(K1)
	    ND = CON_CONECT(K2+1,K1)
	    UCOORD(3*ND-2) = XSEG(K2,NDUMMY)
	    UCOORD(3*ND-1) = YSEG(K2,NDUMMY)
	    UCOORD(3*ND)   = ZSEG(K2,NDUMMY)
	  ENDDO
	ENDDO

	IF(S_HIT_COUNTER_IN .EQ. 1) THEN
	DO K1 = 1,SIZE1
	  UCOORD(3*NCOUNT_A+3*K1-2)= XHITTING_IN(K1)
	  UCOORD(3*NCOUNT_A+3*K1-1)= YHITTING_IN(K1)
	  UCOORD(3*NCOUNT_A+3*K1)  = ZHITTING_IN(K1)
C	  WRITE(*,*) XHITTING_IN(K1)
	ENDDO
C	WRITE(*,*) 'INSIDE CONRSVEC'
	DO K1 = 1,SIZE1
	  DO K2 = 1,4
	    NDUMMY = CSEG_IN(K1)
C	    WRITE(*,*)'SEG NO',NDUMMY
	    ND = CON_CONECT_IN(K2+1,K1)
	   
C	WRITE(*,*)'CON_CONECT_IN ...DATA..TARGET NODES',ND
	    UCOORD(3*ND-2) = XSEG_IN(K2,NDUMMY)
	    UCOORD(3*ND-1) = YSEG_IN(K2,NDUMMY)
	    UCOORD(3*ND)   = ZSEG_IN(K2,NDUMMY)
C		WRITE(*,*)XSEG_IN(K2,NDUMMY)
	  ENDDO
	ENDDO
	ENDIF
	
	IF(S_HIT_COUNTER_OUT .EQ. 1) THEN
	DO K1 = 1,SIZE3
	
	  UCOORD(3*NCOUNT_A+3*SIZE1+3*SIZE2+3*K1-2)= XHITTING_OUT(K1)
	  UCOORD(3*NCOUNT_A+3*SIZE1+3*SIZE2+3*K1-1)= YHITTING_OUT(K1)
	  UCOORD(3*NCOUNT_A+3*SIZE1+3*SIZE2+3*K1)  = ZHITTING_OUT(K1)
	ENDDO

	DO K1 = 1,SIZE3
	  DO K2 = 1,4
	    NDUMMY = CSEG_OUT(K1)
	    ND = CON_CONECT_OUT(K2+1,K1)
	    UCOORD(3*ND-2) = XSEG_OUT(K2,NDUMMY)
	    UCOORD(3*ND-1) = YSEG_OUT(K2,NDUMMY)
	    UCOORD(3*ND)   = ZSEG_OUT(K2,NDUMMY)
	  ENDDO
	ENDDO
	ENDIF
	
	
C	WRITE(*,*) 'CONTACT COUNTER 36'
	DO I = 1,ROWS_Q1
	  P0(I) = 0.0
	  
	  DO J = 1,ID
	    P0(I) = P0(I) + Q1(I,J)*UCOORD(J)
	  ENDDO
	ENDDO
	
	DO K1 = 1,ROWS_Q1
	  GF_LANG(K1) = P0(K1)
	ENDDO
C	WRITE(*,*) 'CONTACT COUNTER 37'
	DO K1 = 1,ID
	  GF_LANG(ROWS_Q1+K1)=F_HAT(K1)
	ENDDO
	
