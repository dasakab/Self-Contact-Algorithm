	SUBROUTINE K11(SKYA,SKYB,LOCA,LOCB,JCHTA,JCHTB,ZK,
     1	  NDIMSKY_A,NDIMSKY_B,NDIMLOC_A,NDIMLOC_B)


	IMPLICIT NONE

	COMMON/INTER/IA,IIA,IB,IIB,IDA,IDB,ID,IID

	INTEGER IA,IIA,IB,IIB,IDA,IDB,ID,IID

        INTEGER  I,J,I2,J2,ICHT
	INTEGER NDIMSKY_A,NDIMLOC_A
	INTEGER NDIMSKY_B,NDIMLOC_B

	INTEGER LOCA(NDIMLOC_A),JCHTA(NDIMLOC_A)
	INTEGER LOCB(NDIMLOC_B),JCHTB(NDIMLOC_B)

	REAL*8 ZK(ID,ID)
	REAL*8 SKYA(NDIMSKY_A),SKYB(NDIMSKY_B)

	DO I = 1,ID
	 DO J = I,ID
	  IF(I .LE. IA)THEN
	   IF(J .GT. IA)GO TO 305
	   J2=J
	   I2=J-I
	   ICHT=LOCA(J+1)-LOCA(J)
	   IF(I2.GE.ICHT)GO TO 305
	   ZK(I,J)=SKYA(LOCA(J2)+I2)
	   IF(J.NE.I)ZK(J,I)=ZK(I,J)
	  ELSE
	   J2=J-IA
	   I2=J2-(I-IA)
	   ICHT=LOCB(J2+1)-LOCB(J2)
	   IF(I2.GE.ICHT)GO TO 305
	   ZK(I,J)=SKYB(LOCB(J2)+I2)
	   IF(J.NE.I)ZK(J,I)=ZK(I,J)
	  ENDIF
	  GO TO 306
305	  ZK(I,J)=0.
	ZK(J,I)=0.
306	CONTINUE
	 ENDDO
	ENDDO

	RETURN
	END


