	ENDDO

C	TOTAL CONTACT FORCES AT THE HITTING NODES (NORMAL AND TANGENTIAL)

	DO K1 = 1,SIZE1
	  IF (CNODE_IN(K1) .NE. 0) THEN
	    TTF1(NCOUNT_A+K1) = INI_CFOR(3*NCOUNT_A+3*K1-2) + 
     1					C_FORCE(3*NCOUNT_A+3*K1-2)
	  ELSE
	    TTF1(NCOUNT_A+K1) = 0.0
	  ENDIF



	  IF (CNODE_IN(K1) .EQ. 0) THEN
	    TTF2(NCOUNT_A+K1) = 0.0
	    TTF3(NCOUNT_A+K1) = 0.0
	  ELSEIF(CNODE_IN(K1) .EQ. 1)THEN

	    TTF2(NCOUNT_A+K1) = 
     1		-FRI*TTF1(NCOUNT_A+K1)*COS(THETA_IN(K1))
     	    TTF3(NCOUNT_A+K1) = 
     1	 	-FRI*TTF1(NCOUNT_A+K1)*SIN(THETA_IN(K1))
           ELSE
           TTF2(NCOUNT_A+K1) = INI_CFOR(3*NCOUNT_A+3*K1-1) + 
     1		C_FORCE(3*NCOUNT_A+3*K1-1)
	   TTF3(NCOUNT_A+K1) = INI_CFOR(3*NCOUNT_A+3*K1) + 
     1		C_FORCE(3*NCOUNT_A+3*K1)
          ENDIF
	ENDDO
	
	
	ENDIF
	
	IF(S_HIT_COUNTER_OUT .EQ. 1) THEN
	
	DO K1 = 1,SIZE3
	 INI_CFOR(3*NCOUNT_A+3*SIZE1+3*K1-2) = 
     1	 -(N1_OUT(1,K1)*C_R_INI(3*NCOUNT_A+3*SIZE1+3*K1-2)+
     1	   N1_OUT(2,K1)*C_R_INI(3*NCOUNT_A+3*SIZE1+3*K1-1)+
     1     N1_OUT(3,K1)*C_R_INI(3*NCOUNT_A+3*SIZE1+3*K1))

	 INI_CFOR(3*NCOUNT_A+3*SIZE1+3*K1-1) = 
     1   -(N2_OUT(1,K1)*C_R_INI(3*NCOUNT_A+3*SIZE1+3*K1-2)+
     1	  N2_OUT(2,K1)*C_R_INI(3*NCOUNT_A+3*SIZE1+3*K1-1) +
     1	  N2_OUT(3,K1)*C_R_INI(3*NCOUNT_A+3*SIZE1+3*K1))
     	  
	  INI_CFOR(3*NCOUNT_A+3*SIZE1+3*K1) = 
     1	  -(N3_OUT(1,K1)*C_R_INI(3*NCOUNT_A+3*SIZE1+3*K1-2)+
     1	   N3_OUT(2,K1)*C_R_INI(3*NCOUNT_A+3*SIZE1+3*K1-1) +
     1	   N3_OUT(3,K1)*C_R_INI(3*NCOUNT_A+3*SIZE1+3*K1))
	  
	ENDDO

C	TOTAL CONTACT FORCES AT THE HITTING NODES (NORMAL AND TANGENTIAL)

	DO K1 = 1,SIZE3
	  IF (CNODE_OUT(K1) .NE. 0) THEN
	    TTF1(NCOUNT_A+SIZE1+K1) = 
     1	    INI_CFOR(3*NCOUNT_A+3*SIZE1+3*K1-2) + 
     1	    C_FORCE(3*NCOUNT_A+3*SIZE1+3*K1-2)
	  ELSE
	    TTF1(NCOUNT_A+SIZE1+K1) = 0.0
	  ENDIF



	  IF (CNODE_OUT(K1) .EQ. 0) THEN
	    TTF2(NCOUNT_A+SIZE1+K1) = 0.0
	    TTF3(NCOUNT_A+SIZE1+K1) = 0.0
	  ELSEIF(CNODE_OUT(K1) .EQ. 1)THEN

	    TTF2(NCOUNT_A+SIZE1+K1) = 
     1	    -FRI*TTF1(NCOUNT_A+SIZE1+K1)*COS(THETA_OUT(K1))
     	    TTF3(NCOUNT_A+SIZE1+K1) = 
     1	    -FRI*TTF1(NCOUNT_A+SIZE1+K1)*SIN(THETA_OUT(K1))
           ELSE
           TTF2(NCOUNT_A+SIZE1+K1) = 
     1	   INI_CFOR(3*NCOUNT_A+3*SIZE1+3*K1-1) + 
     1	   C_FORCE(3*NCOUNT_A+3*SIZE1+3*K1-1)
	   TTF3(NCOUNT_A+SIZE1+K1) = 
     1	   INI_CFOR(3*NCOUNT_A+3*SIZE1+3*K1) + 
     1	   C_FORCE(3*NCOUNT_A+3*SIZE1+3*K1)
          ENDIF
	ENDDO
	
	
	ENDIF


C	WRITE(*,*) 'CONTACT COUNTER 11'
	CALL CHECK_CONTACT(NDBC_A,TTF1,TTF2,TTF3,CNODE,THETA,FRI,
     1	  NTDOF_A,NCOUNT_A,IFLAG1,INC_U,N2,N3,CON_CONECT,ID,CZI,CET,
     1	  S_HIT_COUNTER_IN,S_HIT_COUNTER_OUT,SIZE1,SIZE2,SIZE3,CNODE_IN,
     1	  CNODE_OUT) 
	  
C	  WRITE(*,*) 'CONTACT COUNTER 12'
	IF(IFLAG1.NE.0) THEN
	  C_ITR = C_ITR +1
	    
	  IF (C_ITR .GT. 50) THEN
	    WRITE(711,*)'INC. NO. = ',INCNUMBER,'  ITERATION = ',ITR
	    WRITE(711,*)'CONTACT ITERATIONS ARE NOT CONVERGING'
	    WRITE(711,*)
	    WRITE(711,*)'TERMINATING THE EXECUTION'
	     
	    WRITE(*,*)'CONTACT ITERATIONS ARE NOT CONVERGING'
	      
	    STOP
	  ENDIF
	    
	  GO TO 100
	ENDIF
	
C	WRITE(*,*) 'CONTACT COUNTER 13'
	J=1
	DO I = 1,NCOUNT_A
	  B(J) = TTF1(I)
	  J = J+1
	  
	  IF (CNODE(I) .NE. 1) THEN
	    B(J) = TTF2(I)
	    B(J+1) = TTF3(I)
	    J = J+2
	  ENDIF
	
	ENDDO
	
	IF(S_HIT_COUNTER_IN .EQ. 1) THEN
	
	DO I = 1,SIZE1
	  B(J) = TTF1(NCOUNT_A+I)
	  J = J+1
	  
	  IF (CNODE_IN(I) .NE. 1) THEN
	    B(J) = TTF2(NCOUNT_A+I)
	    B(J+1) = TTF3(NCOUNT_A+I)
	    J = J+2
	  ENDIF
	
	ENDDO
	
	ENDIF
	
	IF(S_HIT_COUNTER_OUT .EQ. 1) THEN
	
	DO I = 1,SIZE3
	  B(J) = TTF1(NCOUNT_A+SIZE1+I)
	  J = J+1
	  
	  IF (CNODE_OUT(I) .NE. 1) THEN
	    B(J) = TTF2(NCOUNT_A+SIZE1+I)
	    B(J+1) = TTF3(NCOUNT_A+SIZE1+I)
	    J = J+2
	  ENDIF
	
	ENDDO
	
	ENDIF
	
C	WRITE(*,*) 'CONTACT COUNTER 14'
	
	DO K1 = 1,ID
	  C_REACT(K1) = 0.0
	  DO K2 = 1,ROWS_Q1
	    C_REACT(K1) = C_REACT(K1) + Q2(K1,K2)*B(K2)
	  ENDDO
	ENDDO
	
C	WRITE(*,*) 'CONTACT COUNTER 15'
C	-------------------------------------------------------
C
C	FINDING DISPLACMENTS FOR NON-CONTACT DOF USING
C		{U2} = [K22 INVERSE]({f2} - [K21]{U1})

50	DO I = ID+1,ID+IID
	  U(I)=0.0
	ENDDO
C	WRITE(*,*)'IID',IID
C	
	DO I = 1,ID+IID
	  U2DIS(I)=U(I)
C	  WRITE(*,*)'DISP',U2DIS(I)
	ENDDO
C	
	
	IFLAG=0
C	WRITE(*,*) 'CONTACT COUNTER 16'
	CALL DISP2(SKYA,SKYB,SKY2,LOCA,LOCB,JCHTA,JCHTB,LOC2,JCHT2,
     1	  GFOR,U2DIS,NDIMSKY_A,NDIMSKY_B,NDIMSKY2,NDIMLOC_A,NDIMLOC_B,
     1    IFLAG)
