C	SUBROUTINE TO READ PARAMETERS NEEDED FOR EXECUTION

	SUBROUTINE MREAD (MPROP_A,MPROP_B,FNODAL_A,FNODAL_B,XCOORD_A,
     1	XCOORD_B,YCOORD_A,YCOORD_B,ZCOORD_A,ZCOORD_B,B_GP,NODE_A,
     1  NODE_B,F_FACE_A,F_FACE_B,FNODE,IBDISP_A,IBDISP_B,NCONTACT_AM,
     1	NCONTACT_BM,CFACE,NELE_A,NELE_B,NTDOF_A,NTDOF_B,
     1	NCOUNT_AM,NCOUNT_BM,EDOF,ENODE,NSEG,NPROP,NMAT_A,NMAT_B,
     1	SELFCON_NODES_IN,SELFCON_NODES_OUT,S_NCONTACT_IN,
     1	S_NCONTACT_OUT)
     

	IMPLICIT NONE
     	
	INTEGER EDOF,ENODE,NSEG,NPROP
	INTEGER NELE_A,NTDOF_A,NMAT_A
	INTEGER NELE_B,NTDOF_B,NMAT_B
	INTEGER NCOUNT_AM
	INTEGER NCOUNT_BM
	INTEGER SELFCON_NODES_IN,SELFCON_NODES_OUT
	
	INTEGER K1,K2,K3

	INTEGER NODE_A(ENODE,NELE_A),NCONTACT_AM(NCOUNT_AM),
     1	  IBDISP_A(NTDOF_A)
	
	INTEGER NODE_B(ENODE,NELE_B),NCONTACT_BM(NCOUNT_BM),
     1	  IBDISP_B(NTDOF_B)
     
     	INTEGER S_NCONTACT_IN(SELFCON_NODES_IN),
     1    S_NCONTACT_OUT(SELFCON_NODES_OUT)
     
	INTEGER F_FACE_A(6,NELE_A)
	INTEGER F_FACE_B(6,NELE_B)
	
	INTEGER FNODE(4,6)
	
	INTEGER CFACE(2,NSEG)

	REAL*8 MPROP_A(NPROP,NELE_A),MPROP_B(NPROP,NELE_B)

	REAL*8 XCOORD_A(ENODE,NELE_A),YCOORD_A(ENODE,NELE_A),
     1	  ZCOORD_A(ENODE,NELE_A)
	
	REAL*8 XCOORD_B(ENODE,NELE_B),YCOORD_B(ENODE,NELE_B),
     1	  ZCOORD_B(ENODE,NELE_B)
   	
   	REAL*8 B_GP(4,3,6)

	REAL*8 FNODAL_A(NTDOF_A),FNODAL_B(NTDOF_B)
	
	REAL *8 GCOORD_A(NTDOF_A/3,3)
	
	REAL *8 GCOORD_B(NTDOF_B/3,3)
	
	INTEGER NELEX_A,NELEY_A,NELEZ_A
	INTEGER NELEX_B,NELEY_B,NELEZ_B
	INTEGER I,J,K,L,M(9)
	
	REAL *8 X,Y,Z
	
	REAL *8 ESIZX_A,ESIZY_A,ESIZZ_A
	
	REAL *8 ESIZX_B,ESIZY_B,ESIZZ_B
	
	INTEGER COUNT
	
	REAL*8 ORIGINX_A,ORIGINY_A,ORIGINZ_A
	
	INTEGER AUTO_MESH
	
C******* VARIABLE DECLARATION FOR CYLINDER RAIL PROBLEM*****

	INTEGER CYLINDER_RAIL
	
	INTEGER N_CIRCUM, N_UNI_MESH, NN, COUNT_Y
	
	REAL*8  LU, LENGTH_Y_B, RATIO_Y_B,LENGTH_1_ELE_A

C******** END OF DECLARATION'S ****************************		

C	WRITE(*,*)'READING MATERIAL PROPERTY FOR ELEMENTS'

	CALL P_READ(MPROP_A,NELE_A,NPROP,NMAT_A) 
	CALL P_READ(MPROP_B,NELE_B,NPROP,NMAT_B)
	
	CLOSE(UNIT=613)
	CLOSE(UNIT=614)

C	WRITE(*,*)'READING NODAL FORCE VECTOR'
	
	CALL NODALF(NTDOF_A,FNODAL_A)
	CALL NODALF(NTDOF_B,FNODAL_B)
	
	CLOSE(UNIT=621)

C	WRITE(*,*)'READING FACES WITH APPLIED FORCES'
	
	CALL FOR_FACE(F_FACE_A,NELE_A)
	CALL FOR_FACE(F_FACE_B,NELE_B)
	
	CLOSE(UNIT=622)
	
	
C	WRITE(*,*)'THIS PART GENERATES THE ELEMENT CONNECTIVITY'

	READ(631,*) AUTO_MESH
	
	IF (AUTO_MESH .EQ. 1) THEN
	  READ(631,*) ESIZX_A,ESIZY_A,ESIZZ_A
	  READ(631,*) ESIZX_B,ESIZY_B,ESIZZ_B
	  READ(631,*) NELEX_A,NELEY_A,NELEZ_A
	  READ(631,*) NELEX_B,NELEY_B,NELEZ_B
	ENDIF
	


	READ(631,*) ORIGINX_A,ORIGINY_A,ORIGINZ_A
	
	CYLINDER_RAIL = 0
	CLOSE(UNIT = 631)
	

C	WRITE(*,*)'GENERATION OF CONNECTIVITY FROM THE CODE'
C	THIS IS DONE WHEN BOTH THE BODIES ARE OF SIMPLE CUBICAL
C	SHAPES. THE CONNECTIVITY AND COORDINATES CAN THE BE
C	GENERATED INSIDE THE CODE ITSELF.
	
	IF (AUTO_MESH .EQ. 1) THEN	
		
C	GENERATING THE CONNECTIVITY FOR THE HITTING BODY.

	  NODE_A(1,1) = 1
	  NODE_A(2,1) = 2
	  NODE_A(3,1) = NELEX_A +3
	  NODE_A(4,1) = NELEX_A +2
	  NODE_A(5,1) = (NELEX_A+1)*(NELEY_A+1) +1
	  NODE_A(6,1) = (NELEX_A+1)*(NELEY_A+1) +2
	  NODE_A(7,1) = (NELEX_A+1)*(NELEY_A+1) + NELEX_A +3
	  NODE_A(8,1) = (NELEX_A+1)*(NELEY_A+1) + NELEX_A +2
	
	  DO I=2,NELEY_A
	    DO J=1,ENODE
	      NODE_A(J,I) = NODE_A(J,I-1) + (NELEX_A +1)
	    ENDDO
	  ENDDO
	
	  DO I=NELEY_A+1,NELEY_A*NELEZ_A
	   DO J=1,ENODE
	    NODE_A(J,I)=NODE_A(J,I-NELEY_A)+(NELEX_A+1)*(NELEY_A+1)
	   ENDDO
	  ENDDO
	
	  DO I=NELEY_A*NELEZ_A+1,NELEX_A*NELEY_A*NELEZ_A
	    DO J=1,ENODE
	      NODE_A(J,I) = NODE_A(J,I-NELEY_A*NELEZ_A)+1
	    ENDDO
	  ENDDO
	
C	WRITE(*,*)'GENERATING THE CONNECTIVITY FOT THE TARGET BODY i.e. B'

	  NODE_B(1,1) = 1
	  NODE_B(2,1) = 2
	  NODE_B(3,1) = NELEX_B +3
	  NODE_B(4,1) = NELEX_B +2
	  NODE_B(5,1) = (NELEX_B+1)*(NELEY_B+1) +1
	  NODE_B(6,1) = (NELEX_B+1)*(NELEY_B+1) +2
	  NODE_B(7,1) = (NELEX_B+1)*(NELEY_B+1) + NELEX_B +3
	  NODE_B(8,1) = (NELEX_B+1)*(NELEY_B+1) + NELEX_B +2
	
	  DO I=2,NELEY_B
	    DO J=1,ENODE
	      NODE_B(J,I) = NODE_B(J,I-1) + (NELEX_B +1)
	    ENDDO
	  ENDDO
	
	  DO I=NELEY_B+1,NELEY_B*NELEZ_B
	   DO J=1,ENODE
	    NODE_B(J,I)=NODE_B(J,I-NELEY_B)+(NELEX_B+1)*(NELEY_B+1)
	   ENDDO
	  ENDDO
	
	  DO I=NELEY_B*NELEZ_B+1,NELEX_B*NELEY_B*NELEZ_B
	    DO J=1,ENODE
	      NODE_B(J,I) =NODE_B(J,I-NELEY_B*NELEZ_B)+1
	    ENDDO
	  ENDDO
	  
	ELSE	

C	READING OF CONNECTIVITY FROM THE FILE.
C	THIS IS DONE WHEN THE BODIES ARE OF COMPLICATED SHAPES AND THUS
C	THE CONNECVITY AND COOORDINATES HAVE TO BE GENEARTED IN
C	SOME COMMERCIAL FINITE ELEMENT SOFTWARE AND THEN THEY ARE 
C	READ FROM THE FILE THAT ARE SUITABLY PREAPRED.


C******* MODIFICATION FOR CYLINDER RAIL IMPACT PROBLEM ***********

C	IF THE PROBLEM IS NOT CYLINDER OVER RAIL IMPACT PROBLEM THEN
C		CYLINDER_RAIL = 0  AND THEN
C	THE CONNECTIVITY AND COORDINATE FOR BOTH THE BODIES ARE 
C	IN FILES AND READ FROM THERE.

	IF (CYLINDER_RAIL .EQ. 0) THEN   ! @@@@@@@@@@@@@@@@@@@
	
	  OPEN(UNIT=632,FILE='UBIN1/ELE_NODE_A')
	  OPEN(UNIT=633,FILE='UBIN1/ELE_NODE_B')
	  

C	WRITE(*,*)'INITIALISING THE CONNECTIVITY MATRIX FOR HITTING BODY.'

	  DO I=1,NELE_A
	    DO J=1,ENODE
	      NODE_A(J,I) = 0
	    ENDDO
	  ENDDO

C	WRITE(*,*)'INITIALISING THE CONNECTIVITY MATRIX FOR TARGET BODY.'
	  
	  DO I=1,NELE_B
	    DO J=1,ENODE
	      NODE_B(J,I) = 0
	    ENDDO
	  ENDDO
	  
	  READ(632,*)
	  READ(632,*)
	  

C	WRITE(*,*)'READING THE CONNECTIVITY MATRIX FOR HITTING BODY.'

	  DO I=1,NELE_A
	    READ(632,*)(M(J),J=1,9)
	    
	    K=M(1)
	    DO J=1,8
	      NODE_A(J,K)=M(J+1)
	    ENDDO
	  ENDDO
	  
	  DO I=1,NELE_A
	    DO J=1,ENODE
	      
	      IF (NODE_A(J,I) .EQ. 0) THEN
	        WRITE(711,*)'ERROR IN INPUT FILE NODE_ELE_A'
	        WRITE(711,*)'CONNECTIVITY FOR ELE ',I,' NOT CORRECT'
	        WRITE(711,*)'TERMINATING EXECUTION'

	        WRITE(*,*)'ERROR IN INPUT FILE NODE_ELE_A'
	        WRITE(*,*)'CONNECTIVITY FOR ELE ',I,' NOT CORRECT'
	        WRITE(*,*)'TERMINATING EXECUTION'
	        
	        STOP
	      ENDIF
	    
	    ENDDO
	  ENDDO
	  

C	WRITE(*,*)'READING THE CONNECTIVITY MATRIX FOR TARGET BODY.'

	  READ(633,*)
	  READ(633,*)
	  
	  DO I=1,NELE_B
	    READ(633,*)(M(J),J=1,9)
C	    WRITE(*,*)'READING 2.'
	    K=M(1)
	    DO J=1,8
	      NODE_B(J,K)=M(J+1)
	    ENDDO
	  ENDDO
	  
	  DO I=1,NELE_B
	    DO J=1,ENODE
C	      WRITE(*,*)'READING 3'
	      IF (NODE_B(J,I) .EQ. 0) THEN
	        WRITE(711,*)'ERROR IN INPUT FILE NODE_ELE_B'
	        WRITE(711,*)'CONNECTIVITY FOR ELE ',I,' NOT CORRECT'
	        WRITE(711,*)'TERMINATING EXECUTION'
	        
	        WRITE(*,*)'ERROR IN INPUT FILE NODE_ELE_B'
	        WRITE(*,*)'CONNECTIVITY FOR ELE ',I,' NOT CORRECT'
	        WRITE(*,*)'TERMINATING EXECUTION'
	        
	        STOP
	      ENDIF
	    
	    ENDDO
	  ENDDO
	  
	  CLOSE(UNIT=632)
	  CLOSE(UNIT=633)
	
	ELSE	         ! @@@@@@@@@@@@@@@@@@@

C	IF THE PROBLEM IS CYLINDER IMPACTING OVER THE RAIL
C	THEN THE MODIFICATION FOR IT ARE GIVEN BELOW.

C******** MODIFICATION FOR GENERATION OF CONNECTIVITY FOR THE
