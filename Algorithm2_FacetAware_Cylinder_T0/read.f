C	SUBROUTINE TO READ OPTIONS FOR INTERNAL EXECUTION
	
	SUBROUTINE RI_EXEC(PCE,OSTIF,OSTRAIN,NPEFI,
     1   STRESS_OPTION,RESTART)

		
	IMPLICIT NONE
	
	INTEGER OSTIF,OSTRAIN,NPEFI,RESTART
	
	REAL*8 PCE
	
	INTEGER STRESS_OPTION

	OPEN(UNIT=11,FILE='UOPT1/OPT_IEXEC')


C	      UOPTIONS FOR INTERNAL EXECUTION

C	OPTION TO INCLUDE NON_LINEAR PART OF STIFFNESS MATRIX
C		OSTIF   = 1    K_LINEAR 
C		OSTIF   = 2    K_LINEAR + K_NLINER

C	OPTION TO INCLUDE NON_LINEAR PART OF STRAIN (GREEN-LAGRANGE STRAIN)
C		OSTRAIN = 1    ONLY LINEAR STRAIN
C		OSTRAIN = 2    GREEN-LAGRANGE STRAIN

C	PCE     =      % OF ELASTIC (CE) MATIX TO BE ADDED IN 
C                      ELASTOPLASTIC (CEP) MATRIX (FOR BETTER 
C		       CONVERGENCE IN STIFFENING STRUCTURES)
	
C	NPEFI   =      NO OF PARTS FOR EULER FORWARD INTEGRATION


C	STRESS_OPTION= OPTION FOR TYPE OF STRESS MEASURE TO USE
C	STRESS_OPTION = 1 JAUMANN'S STRESS MEASURE
C	STRESS_OPTION = 2 NEW OBJECTIVE STRESS MEASURE
	
	READ(11,*) OSTIF
	READ(11,*) OSTRAIN 
	READ(11,*) PCE
	READ(11,*) NPEFI 
	READ(11,*) STRESS_OPTION
        READ(11,*) RESTART
	
	CLOSE (UNIT = 11)
	
	RETURN
	END

C	READING OPTIONS FOR RESULTS

	SUBROUTINE RO_RESULT(WRELE,WRPARA,WRESULT,WRINC,NELE,
     1	IBODY)
	
	IMPLICIT NONE
	
	INTEGER NELE,IBODY
	INTEGER WRESULT,WRINC
	INTEGER WRELE(NELE),WRPARA(6)
	
	IF(IBODY.EQ.1) THEN
	  
	  OPEN(UNIT=11,FILE='UOPT1/ORES_A')
	
	ELSEIF( IBODY.EQ.2) THEN

	  OPEN(UNIT=11,FILE='UOPT1/ORES_B')
	
	ENDIF


C	         UOPTIONS FOR PRINTING RESULTS

C	WRESULT = 0	PRINT NO RESULTS
C	WRESULT = 11	PRINT RESULTS AT ALL INCREMENT FOR ALL ELEMENTS
C	WRESULT = 12 	PRINT RESULTS AT ALL INCREMENT FOR SPECIFIC ELEMENTS
C	WRESULT = 21 	PRINT RESULTS AT SOME INCREMENTS FOR ALL ELEMENTS
C	WRESULT = 22 	PRINT RESULTS AT SOME INCREMENTS FOR ALL ELEMENTS
C	WRESULT_A       FOR BODY A (HITTING BODY)
C	WRESULT_B       FOR BODY B (TARGET BODY)

C	WRINC   =       PRINT RESULTS AFTER EVERY WRINC INCREMENTS

C	WRPARA          RESULT PARAMETERS TO BE PRINTED
C       WRPARA  = 0     PARAMETER NOT TO BE PRINTED
C	WRPARA  = 1     PARAMETER TO BE PRINTED
C	WRPARA(1) =     CSTRESS	
C	WRPARA(2) =     EQUIVALENT PLASTIC STRAIN 
C	WRPARA(3) =     DISPLACEMENTS
C	WRPARA(4) =     VELOCITIES
C	WRPARA(5) =     ACCELERATIONS
C	WRPARA(6) =     NORMAL STRESS ON BOUNDARY (ONLY FOR TARGET BODY)

C	WRELE           PRINT RESULTS ONLY FOR SPECIFIED ELEMENTS
C	WRELE(K) = 1    PRINT RESULTS ELEMENT K
C	WRELE(K) = 0    DON'T PRINT RESULTS ELEMENT K

	
	READ(11,*) WRESULT 
	READ(11,*) WRINC 
	READ(11,*) WRPARA
	READ(11,*) WRELE	
	
	CLOSE(UNIT =11)
	
	RETURN
	END

C	SUBROUTINE TO READ ESSENTIAL PARAMETERS
	
	SUBROUTINE RE_PARA(NELE_A,NELE_B,NTDOF_A,NTDOF_B,NCOUNT_AM,
     1	NCOUNT_BM,NSEG,NMAT_A,NMAT_B,FRI,LENGTH,SOFT_BODY,
     1	SELFCON_NODES_IN,SELFCON_NODES_OUT)
	
	IMPLICIT NONE
	INTEGER NELE_A,NTDOF_A,NCOUNT_AM,NMAT_A
	INTEGER NELE_B,NTDOF_B,NCOUNT_BM,NMAT_B,NSEG
	INTEGER SOFT_BODY,SELFCON_NODES_IN,SELFCON_NODES_OUT

	REAL*8 FRI
	REAL*8 LENGTH
	
C	FILE FOR ESSENTIAL PARAMETERS

	OPEN (UNIT=12,FILE='UOPT1/EPREAD')

C	BODY A     HITTING BODY
C	BODY B     TARGET BODY

C	NELE_A     NO. OF ELEMENTS FOR HITTING BODY
C	NELE_B     NO. OF ELEMENTS FOR TARGET BODY
	
C	NTDOF_A    TOTAL DEGREES OF FREEDOM FOR BODY A
C	NTDOF_B    TOTAL DEGREES OF FREEDOM FOR BODY A

C	NCOUNT_AM  MAXIMUM NO OF NODES THAT CAN COME IN CONTACT FOR
C	           FOR HITTING BODY
C	NCOUNT_BM  MAXIMUM NO OF NODES THAT CAN COME IN CONTACT FOR
C	           FOR TARGET BODY

C	NSEG       TOTAL NO OF SEGMENT FOR TARGET BODY

C	NMAT_A     NO. OF MATERIALS USED FOR BODY A
C	NMAT_B     NO. OF MATERIALS USED FOR BODY B

C	FRI        FRICTION COEFFICIENT BETWEEN BODY A  AND B

	

	READ(12,*) NELE_A ,NELE_B
	READ(12,*) NTDOF_A,NTDOF_B

	READ(12,*) NCOUNT_AM,NCOUNT_BM
	READ(12,*) NSEG

	READ(12,*) NMAT_A,NMAT_B 

	READ(12,*) FRI
	
	READ(12,*) LENGTH
	
	READ(12,*) SOFT_BODY
	READ(12,*) SELFCON_NODES_IN,SELFCON_NODES_OUT
	
	CLOSE(UNIT=12)

	RETURN
	END
	
