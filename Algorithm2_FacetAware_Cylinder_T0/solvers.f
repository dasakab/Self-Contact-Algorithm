C SOLUTION OF SIMULTANEOUS EQUATION BY HOUSEHOLDER METHOD
	
	SUBROUTINE SOLVE(A,B,N,X)

	
	IMPLICIT DOUBLE PRECISION(A-H,O-Z)
	PARAMETER(MTP=1262)
	DIMENSION A(N,N),B(N),X(N),V(MTP)
	DO 10 K=1,N-1
	SUM=0.0D0
	DO 11 I=K,N
	SUM=SUM+A(I,K)*A(I,K)
11	CONTINUE
	IF(ABS(A(K,K)).LE.1.E-09)THEN
	W1=DSQRT(SUM)
	ELSE
	W1=A(K,K)+(A(K,K)/ABS(A(K,K)))*DSQRT(SUM)
	ENDIF
	ASUM=W1*W1
	DO 13 M=2,N-K+1
	ASUM=ASUM+A(M+K-1,K)**2
13      CONTINUE
        IF(ASUM.EQ.0.0)PRINT*,"K",K
	ALPHA=2./ASUM
	A(K,K)=A(K,K)-W1
	DO 14 J=K+1,N
	V(J)=A(K,J)*W1
	DO 16 M=2,N-K+1
	V(J)=V(J)+A(M+K-1,K)*A(M+K-1,J)
16      CONTINUE
	A(K,J)=A(K,J)-ALPHA*W1*V(J)
	DO 26 I=K+1,N
	A(I,J)=A(I,J)-ALPHA*A(I,K)*V(J)
26      CONTINUE
14      CONTINUE
	ETA=W1*B(K)
	DO 15 M=2,N-K+1
	ETA=ETA+A(M+K-1,K)*B(M+K-1)
15	CONTINUE
	B(K)=B(K)-ALPHA*W1*ETA
	DO 27 I=K+1,N
	B(I)=B(I)-ALPHA*A(I,K)*ETA
27 	CONTINUE
C	PRINT*,(B(I),I=1,N)
C	PRINT*,((A(I,J),J=1,N),I=1,N)
C	PRINT*,B(1),ALPHA,A(1,K),ETA
10      CONTINUE
C	BACK SUBSTITUTION
	X(N)=B(N)/A(N,N)
	DO 17 I=1,N-1
	SUM=0.0
	DO 18 J=N-I+1,N
	SUM=SUM+A(N-I,J)*X(J)
C	PRINT*,A(N-I,J),X(J)    
18      CONTINUE
C	PRINT*,SUM,10
	X(N-I)=(B(N-I)-SUM)/A(N-I,N-I)
C	PRINT*,X(N-I),B(N-I),SUM,A(N-I,N-I)
17	CONTINUE
	RETURN
	END

	
C	SUBROUTINE FOR GAUSS ELIMINATION METHOD WITH PARTIAL PIVOTING

	SUBROUTINE GAUSS_ELMN(A,B,N,X,MAX_SIZE,ROWS_Q1)

C	OUT :: X(N)

	IMPLICIT NONE
	
	INTEGER N,I,J,K,INTCHG,MAX_SIZE,ROWS_Q1
	
	REAL *8 A(MAX_SIZE,MAX_SIZE),B(MAX_SIZE),X(MAX_SIZE)
	REAL *8 NORM,TEMP,FACTOR 
	
		
C	MODIFICATION TO TAKE CARE OF THE CONTACT NODES ALONG PLANE OF -
C	SYMMETRY

	DO I=1,ROWS_Q1
	  NORM = 0.0
	  
	  DO J=1,N
	    NORM = NORM + A(I,J)**2
	  ENDDO
	  
	  NORM = SQRT(NORM)
	  
	  IF (NORM .LE. 0.1) THEN
	  
	    IF (ABS(B(I)) .LE. 0.1) THEN
	      
	      DO J=1,N
	        A(I,J) = 0.0
	      ENDDO
	      
	      A(I,I) = 1.0
	      B(I) = 0.0
	      
	    ELSE
	    
	      WRITE(711,*) 'ERROR IN SUBROUTINE GAUSS_ELMN'
	      WRITE(711,*) 'INCONSISTANT EQUATION ',I
	      WRITE(711,*) 'TERMINATING THE EXECUTION '
	    
	      WRITE(*,*) 'ERROR IN SUBROUTINE GAUSS_ELMN'
	      WRITE(*,*) 'INCONSISTANT EQUATION ',I
	      WRITE(*,*) 'TERMINATING THE EXECUTION '
	    
	      STOP
	    ENDIF
	  ENDIF
	  
	ENDDO 


C	FORWARD REDUCTION

	DO K=1,N-1
	
C	PARTIAL PIVOTING

	  INTCHG = K
	  IF (ABS(A(K,K)) .LT. 1E-4) THEN
	    DO I=K+1,N
	      IF (ABS(A(INTCHG,K)) .LT.  ABS(A(I,K))) INTCHG=I
	    ENDDO
	  ENDIF
	  
	  IF (INTCHG .NE. K) THEN
	      DO J=K,N
	        TEMP = A(K,J)
	        A(K,J) = A(INTCHG,J)
	        A(INTCHG,J) = TEMP
	      ENDDO
	      TEMP = B(K)
	      B(K) = B(INTCHG)
	      B(INTCHG) = TEMP
	      
	  ENDIF
	  
	  
	  IF (ABS(A(K,K)) .LT. 1E-10) THEN

	    WRITE(711,*) 'ERROR IN SUBROUTINE GAUSS_ELMN'
	    WRITE(711,*) 'VERY SMALL PIVOT ELEMENT = ',A(K,K)
	    WRITE(711,*) 'ROW NUMBER = ',K
	    WRITE(711,*) 'TERMINATING THE EXECUTION '
	    
	    WRITE(*,*) 'ERROR IN SUBROUTINE GAUSS_ELMN'
	    WRITE(*,*) 'VERY SMALL PIVOT ELEMENT = ',A(K,K)
	    WRITE(*,*) 'ROW NUMBER = ',K
	    WRITE(*,*) 'TERMINATING THE EXECUTION '
	    
	    STOP
	  ENDIF
	  
	  DO I = K+1,N
	    
	    FACTOR = A(I,K)/A(K,K)
	    A(I,K) = 0.0
	    
	    DO J=K+1,N
	      A(I,J)=A(I,J)-A(K,J)*FACTOR
	    ENDDO
	    
	    B(I) = B(I) - B(K)*FACTOR
	    
	  ENDDO
	  
	ENDDO
	
	IF (ABS(A(N,N)) .LT. 1E-10) THEN
	    
	    WRITE(711,*) 'ERROR IN SUBROUTINE GAUSS_ELMN'
	    WRITE(711,*) 'VERY SMALL PIVOT ELEMENT = ',A(N,N)
	    WRITE(711,*) 'ROW NUMBER = ',N
	    WRITE(711,*) 'TERMINATING THE EXECUTION '
	    
	    WRITE(*,*) 'ERROR IN SUBROUTINE GAUSS_ELMN'
	    WRITE(*,*) 'VERY SMALL PIVOT ELEMENT = ',A(N,N)
	    WRITE(*,*) 'ROW NUMBER = ',N
	    WRITE(*,*) 'TERMINATING THE EXECUTION '
	    
	    STOP
	ENDIF
	

C	BACK SUBSTITUTION

	X(N) = B(N)/A(N,N)
	
	DO I=N-1,1,-1
	  
	  TEMP = 0.0
	  DO J=I+1,N
	    TEMP = TEMP + A(I,J)*X(J)
	  ENDDO
	  
	  X(I) = (B(I) - TEMP)/A(I,I)
	  
	ENDDO
	

	RETURN
	END