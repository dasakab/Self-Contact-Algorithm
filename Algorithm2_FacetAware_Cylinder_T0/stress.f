	      ENDDO

	      DO M4 = 1,6
		DUMMY=0.0
		DO M5 = 1,6
	          DUMMY=DUMMY+CE(M4,M5)*ESTRAIN(NDUMMY,M5,K1)
	        ENDDO
		CSTRESS(NDUMMY,M4,K1)=DUMMY
	      ENDDO

	      NDUMMY=NDUMMY+1

	    ENDDO
	    ENDDO
	  ENDDO

	ENDDO

	RETURN
	END


C	SUBROUTINE TO FIND FLOW VECTOR A

	SUBROUTINE FLOWVECTOR_A(CSTRESS_C,A)


	IMPLICIT NONE

	INTEGER I

	REAL*8 EQUICSTRESS,A(6,1)

	REAL*8 DSTRESS_M(3,3),DSTRESS_C(6),CSTRESS_C(6),
     1   CSTRESS_M(3,3)


	CALL COLM_SMAT (CSTRESS_C,CSTRESS_M)

	CALL DEVIO_STRESS(CSTRESS_M,DSTRESS_M)

	CALL EQUI_CSTRESS(CSTRESS_C,EQUICSTRESS)

	CALL SMAT_COLM (DSTRESS_M,DSTRESS_C)

	DO I = 1,3
	  A(I,1) = (3./(2.*EQUICSTRESS))*DSTRESS_C(I)
	ENDDO
	
	DO I = 4,6
	  A(I,1) = (3./(EQUICSTRESS))*DSTRESS_C(I)
	ENDDO

	RETURN
	END

C	SUBROUTINE TO FIND INCREMENTAL CAUCHY STRESS

	SUBROUTINE INC_C_STRESS(CSTRESS_C,DELTA_JS_C,DELTA_UE,
     1 	  XC,YC,ZC,E,Z,SI,DELTA_CS_C,EDOF,ENODE)


	IMPLICIT NONE
	INTEGER EDOF,ENODE
	INTEGER I,J,K

	REAL*8 E,Z,SI
	REAL*8 DUMMY

	REAL*8 XC(ENODE),YC(ENODE),ZC(ENODE)

	REAL*8 DELTA_UE(EDOF),INCROT(3,3)

	REAL*8 CSTRESS_C(6),DELTA_CS_C(6),DELTA_JS_C(6),
     1    CSTRESS_M(3,3),DELTA_CS_M(3,3),DELTA_JS_M(3,3)


	CALL COLM_SMAT (CSTRESS_C,CSTRESS_M)
	CALL COLM_SMAT (DELTA_JS_C,DELTA_JS_M)
	CALL INC_ROTATION (DELTA_UE,XC,YC,ZC,E,Z,SI,INCROT,EDOF,
     1	ENODE)

	DO I = 1,3
	  DO J = 1,3
	    DUMMY=0.0
	    DO K = 1,3

     	      DUMMY=DUMMY+
     1	      CSTRESS_M(I,K)*INCROT(J,K)+CSTRESS_M(J,K)*INCROT(I,K)

	    ENDDO
	      DELTA_CS_M(I,J) = DELTA_JS_M(I,J)+DUMMY
	  ENDDO
	ENDDO

	CALL SMAT_COLM(DELTA_CS_M,DELTA_CS_C)

	RETURN
	END


C	SUBROUTINE TO FIND EQUIVALET CAUCHY STRESS

	SUBROUTINE EQUI_CSTRESS (CSTRESS_C,EQUICSTRESS)


	IMPLICIT NONE

	INTEGER I,J

	REAL*8 EQUICSTRESS,DUMMY
	REAL*8 DSTRESS_M(3,3),CSTRESS_C(6),CSTRESS_M(3,3)

	CALL COLM_SMAT(CSTRESS_C,CSTRESS_M)
	CALL DEVIO_STRESS(CSTRESS_M,DSTRESS_M)

	DUMMY=0.0

	DOI=1,3
	  DOJ=1,3
	    DUMMY =DUMMY+DSTRESS_M(I,J)**2
	  ENDDO
	ENDDO

	EQUICSTRESS =((3./2.)*DUMMY)**0.5

	RETURN
	END


C	SUBROUTINE TO FIND DEVIOTORIC STRESS

	SUBROUTINE DEVIO_STRESS(CSTRESS_M,DSTRESS_M)


	IMPLICIT NONE

	REAL*8 CSTRESS_M(3,3),DSTRESS_M(3,3),HYDRO

	HYDRO=(1.0/3.0)*(CSTRESS_M(1,1)+CSTRESS_M(2,2)+CSTRESS_M(3,3))

	DSTRESS_M(1,1) = CSTRESS_M(1,1)-HYDRO
	DSTRESS_M(2,2) = CSTRESS_M(2,2)-HYDRO
	DSTRESS_M(3,3) = CSTRESS_M(3,3)-HYDRO
	DSTRESS_M(1,2) = CSTRESS_M(1,2)
	DSTRESS_M(1,3) = CSTRESS_M(1,3)
	DSTRESS_M(2,1) = CSTRESS_M(2,1)
	DSTRESS_M(2,3) = CSTRESS_M(2,3)
	DSTRESS_M(3,1) = CSTRESS_M(3,1)
	DSTRESS_M(3,2) = CSTRESS_M(3,2)

	RETURN
	END

C	SUBROUTINE FOR INCREMENTAL STRAIN

	SUBROUTINE INC_STRAIN (XCOORD,YCOORD,ZCOORD,DELTA_U,
     1	NELE,DELTA_E,EDOF,ENODE,NG,OSTRAIN)


	IMPLICIT NONE

	INTEGER EDOF,ENODE,NG,NELE,OSTRAIN
	INTEGER NDUMMY,K1,K2,K3,M1,M2,M3,M4,N1

	REAL*8 E,Z,SI
	REAL*8 W(NG),GP(NG)
	REAL*8 BLN(6,EDOF)
	REAL*8 DUMMY

	REAL*8 XCOORD(ENODE,NELE),YCOORD(ENODE,NELE),
     1   ZCOORD(ENODE,NELE),XC(ENODE),YC(ENODE),ZC(ENODE)

	REAL*8 DELTA_U(EDOF,NELE)

	REAL*8 LDELTA_E(NG*NG*NG,6,NELE),NDELTA_E(NG*NG*NG,6,NELE)
	REAL*8 DELTA_E(NG*NG*NG,6,NELE)

	CALL GLWR(W,GP,NG)

	DO M1 = 1,NELE

	  DO N1 = 1,ENODE
	    XC(N1)=XCOORD(N1,M1)
	    YC(N1)=YCOORD(N1,M1)
	    ZC(N1)=ZCOORD(N1,M1)
	  ENDDO

	  NDUMMY = 1

	    DO M2 = 1,NG
	      DO M3 = 1,NG
	      DO M4 = 1,NG

		E = GP(M2)
		Z = GP(M3)
	        SI= GP(M4)

		CALL B_LINEAR (XC,YC,ZC,E,Z,SI,BLN,EDOF,ENODE)

	        DO K1 = 1,6

	          DUMMY =0.0

	          DO K2 = 1,EDOF

	            DUMMY = BLN(K1,K2)*DELTA_U(K2,M1)+DUMMY

	          ENDDO

	          LDELTA_E(NDUMMY,K1,M1) = DUMMY

	        ENDDO

		NDUMMY=NDUMMY+1

	      ENDDO
	      ENDDO
	    ENDDO

	  ENDDO

	  IF(OSTRAIN .EQ. 1) THEN

	    DO K1 = 1,NELE
	      DO K2 = 1,NG*NG*NG
	      DO K3 = 1,6
	       DELTA_E(K2,K3,K1) = LDELTA_E(K2,K3,K1)
	      ENDDO
	      ENDDO
	    ENDDO

	  ELSEIF(OSTRAIN .EQ. 2) THEN

	    CALL NL_STRAIN (XCOORD,YCOORD,ZCOORD,DELTA_U,
     1	    NELE,NDELTA_E,EDOF,ENODE,NG)

	    DO K1 = 1,NELE
	      DO K2 = 1,NG*NG*NG
	      DO K3 = 1,6
	       DELTA_E(K2,K3,K1) = LDELTA_E(K2,K3,K1)+NDELTA_E(K2,K3,K1)
	      ENDDO
	      ENDDO
	    ENDDO

	  ELSE

	  WRITE(601,*) ' ERROR IN READING OPTION FOR STRAIN '
	  WRITE(601,*) '    '
	  WRITE(601,*) ' TERMINATING EXECUTION   '

	  ENDIF

	  RETURN
	  END


C	SUBROUTINE FOR NONLINEAR PART OF STRAIN


	SUBROUTINE NL_STRAIN (XCOORD,YCOORD,ZCOORD,DELTA_U,
     1	NELE,NDELTA_E,EDOF,ENODE,NG)


	IMPLICIT NONE
	
	INTEGER NG
	INTEGER EDOF,ENODE,NELE
	INTEGER NDUMMY,K1,M1,M2,M3,M4,N1

	REAL*8 E,Z,SI,TH

	REAL*8 W(NG),GP(NG)
	REAL*8 BNLN(9,EDOF)

	REAL*8 XCOORD(ENODE,NELE),YCOORD(ENODE,NELE),
     1   ZCOORD(ENODE,NELE),XC(ENODE),YC(ENODE),ZC(ENODE)

	REAL*8 DELTA_U(EDOF,NELE),DELTA_U_E(EDOF)

	REAL*8 NDELTA_E(NG*NG*NG,6,NELE)
	REAL*8 DUDX(9)

	CALL GLWR(W,GP,NG)

	DO M1 = 1,NELE

	  DO N1 = 1,ENODE
	    XC(N1)=XCOORD(N1,M1)
	    YC(N1)=YCOORD(N1,M1)
	    ZC(N1)=ZCOORD(N1,M1)
	  ENDDO

	  DO K1 = 1,EDOF
	    DELTA_U_E(K1) = DELTA_U(K1,M1)
	  ENDDO

	  NDUMMY =1

	    DO M2 = 1,NG
	      DO M3 = 1,NG
	      DO M4 = 1,NG

		E = GP(M2)
		Z = GP(M3)
	        SI= GP(M4)

		CALL B_NLINEAR (XC,YC,ZC,E,Z,SI,BNLN,EDOF,ENODE)

	        CALL MATMUL(BNLN,DELTA_U_E,DUDX,9,EDOF,1)

	        NDELTA_E(NDUMMY,1,M1) = 0.5*(DUDX(1)**2 +DUDX(4)**2 +
     1                                      DUDX(7)**2)
	        NDELTA_E(NDUMMY,2,M1) = 0.5*(DUDX(2)**2 +DUDX(5)**2 +
     1                                      DUDX(8)**2)
	        NDELTA_E(NDUMMY,3,M1) = 0.5*(DUDX(3)**2 +DUDX(6)**2 +
     1                                      DUDX(9)**2)

		NDELTA_E(NDUMMY,4,M1) = DUDX(1)*DUDX(2) +DUDX(4)*DUDX(5)
     1                               + DUDX(7)*DUDX(8)
		NDELTA_E(NDUMMY,5,M1) = DUDX(2)*DUDX(3) +DUDX(5)*DUDX(6)
     1                               + DUDX(8)*DUDX(9)
		NDELTA_E(NDUMMY,6,M1) = DUDX(1)*DUDX(3) +DUDX(4)*DUDX(6)
     1                               + DUDX(7)*DUDX(9)

		NDUMMY=NDUMMY+1

	      ENDDO
	      ENDDO
	    ENDDO

	  ENDDO

	  RETURN
	  END

C	SUBROUTINE TO FIND INCREMENTAL PLASTIC STRAIN

	SUBROUTINE INC_PSTRAIN (A,DELTA_E_C,CE,HARDENA,DELTA_PE_C)


	IMPLICIT NONE

	INTEGER K1

	REAL*8 HARDENA,CE(6,6),A(6)
	REAL*8 DUMMYD,DUMMYN,DUMMY1(6)
	REAL*8 DELTA_E_C(6),DELTA_PE_C(6)

	CALL MATMUL (A,CE,DUMMY1,1,6,6)

	DUMMYN=0.0
	DO K1 = 1,6
	  DUMMYN = DUMMY1(K1)*DELTA_E_C(K1)+DUMMYN
	ENDDO

	DUMMYD =0.0

	DO K1 = 1,6
	  DUMMYD=DUMMY1(K1)*A(K1)+DUMMYD
	ENDDO

	DUMMYD =DUMMYD+HARDENA

	DO K1 = 1,6
	  DELTA_PE_C(K1)=(DUMMYN/DUMMYD)*A(K1)
	ENDDO

	RETURN
	END


C	SUBROUTINE TO FIND EQUIVALENT PLASTIC STRAIN

	SUBROUTINE EQUI_INC_PSTRAIN (DELTA_PE_C,EQUIPSTRAIN)


	IMPLICIT NONE

	INTEGER K1,K2

	REAL*8 EQUIPSTRAIN,DUMMY
	REAL*8 DELTA_PE_C(6),DELTA_PE_M(3,3)

	CALL COLM_SMAT (DELTA_PE_C,DELTA_PE_M)

C	SHEAR STRAINS TO BE HALVED TO GET TENSORIAL STRAINS

	DELTA_PE_M(1,2)=DELTA_PE_M(1,2)/2.0
	DELTA_PE_M(1,3)=DELTA_PE_M(1,3)/2.0
	DELTA_PE_M(2,1)=DELTA_PE_M(2,1)/2.0 !ONLY SHEAR PRESENT
	DELTA_PE_M(2,3)=DELTA_PE_M(2,3)/2.0
	DELTA_PE_M(3,1)=DELTA_PE_M(3,1)/2.0
	DELTA_PE_M(3,2)=DELTA_PE_M(3,2)/2.0

	DUMMY =0.0

	DO K1 = 1,3
	  DO K2 = 1,3
	    DUMMY=DUMMY+DELTA_PE_M(K1,K2)*DELTA_PE_M(K1,K2)
	  ENDDO
	ENDDO

	EQUIPSTRAIN = ((2./3.)*DUMMY)**0.5

	RETURN
	END


C	SUBROUTINE FOR INCREMENTAL ROTATION TENSOR

	SUBROUTINE INC_ROTATION (DELTA_UE,XC,YC,ZC,E,Z,SI,INCROT,
     1	EDOF,ENODE)


	IMPLICIT NONE

	INTEGER EDOF,ENODE
	INTEGER K1,K2
	REAL*8 E,Z,SI
	REAL*8 DUMMY(3)

	REAL*8 B(3,EDOF),A(3,ENODE),T(3,3)

	REAL*8 XC(ENODE),YC(ENODE),ZC(ENODE),INCROT(3,3)

	REAL*8 DELTA_UE(EDOF,1)

	DO K1 = 1,3
	  DO K2 = 1,3
	    INCROT(K1,K2) =0.0
	  ENDDO
	ENDDO

	DO K1 = 1,EDOF
	  DO K2 = 1,3
	    B(K2,K1) = 0.0
	  ENDDO
	ENDDO

	CALL DERVN (E,Z,SI,A,EDOF,ENODE)

	CALL TMAT (XC,YC,ZC,E,Z,SI,T,EDOF,ENODE)

	DO K1 = 1,ENODE

	  B(1,3*K1-2) = A(1,K1)*T(2,1)+A(2,K1)*T(2,2)+A(3,K1)*T(2,3)
	  B(1,3*K1-1) = -(A(1,K1)*T(1,1)+A(2,K1)*T(1,2)+A(3,K1)*T(1,3))

	  B(2,3*K1-2) = A(1,K1)*T(3,1)+A(2,K1)*T(3,2)+A(3,K1)*T(3,3)
	  B(2,3*K1) = -(A(1,K1)*T(1,1)+A(2,K1)*T(1,2)+A(3,K1)*T(1,3))

	  B(3,3*K1-1) = A(1,K1)*T(3,1)+A(2,K1)*T(3,2)+A(3,K1)*T(3,3)
	  B(3,3*K1) = -(A(1,K1)*T(2,1)+A(2,K1)*T(2,2)+A(3,K1)*T(2,3))

	ENDDO

	CALL MATMUL (B,DELTA_UE,DUMMY,3,EDOF,1)

	INCROT(1,2) = 0.5*DUMMY(1)
	INCROT(2,1) = -0.5*DUMMY(1)

	INCROT(1,3) = 0.5*DUMMY(2)
	INCROT(3,1) = -0.5*DUMMY(2)

	INCROT(2,3) = 0.5*DUMMY(3)
	INCROT(3,2) = -0.5*DUMMY(3)

	RETURN

	END

C	SUBROUTINE TO PUT DISPLACEMENTS IN ELEMENTAL FORM

	SUBROUTINE G_ELEMENT(DGFORCE,IDA,IG,NELE,DELTA_ITR_U,
     1	  EDOF,ENODE)


	 IMPLICIT NONE

	 INTEGER EDOF,ENODE,NELE
	 INTEGER IG(EDOF,NELE)
	 INTEGER IDA
	 INTEGER NDUMMY,K1,K2

	 REAL*8 DGFORCE(IDA),DELTA_ITR_U(EDOF,NELE)

	 DO K1 = 1,NELE
	   DO K2 = 1,EDOF
	     NDUMMY = IG(K2,K1)
	     IF (NDUMMY .EQ. 0)THEN
	       DELTA_ITR_U(K2,K1)=0.0
	     ELSE
	       DELTA_ITR_U(K2,K1)=DGFORCE(NDUMMY)
	     ENDIF
	  ENDDO
	ENDDO

	RETURN
	END

C	SUBROUTINE TO CONVERT COLUMN VECTOR TO MATRIX FORM

	SUBROUTINE COLM_SMAT (COLM,SMAT)


	IMPLICIT NONE

	REAL*8 COLM(6),SMAT(3,3)

	SMAT(1,1) = COLM(1)
	SMAT(1,2) = COLM(4)
	SMAT(1,3) = COLM(6)
	SMAT(2,1) = COLM(4)
	SMAT(2,2) = COLM(2)
	SMAT(2,3) = COLM(5)
	SMAT(3,1) = COLM(6)
	SMAT(3,2) = COLM(5)
	SMAT(3,3) = COLM(3)

	RETURN
	END


C	SUBROUTINE TO CONVERT MATRIX TO COLUMN VECTOR

	SUBROUTINE SMAT_COLM (SMAT,COLM)

	IMPLICIT NONE

	REAL*8 SMAT(3,3),COLM(6)

	COLM(1) = SMAT(1,1)
	COLM(2) = SMAT(2,2)
	COLM(3) = SMAT(3,3)
	COLM(4) = SMAT(1,2)
	COLM(5) = SMAT(2,3)
	COLM(6) = SMAT(1,3)

	RETURN
	END


C	PARAMETERS FROM STRESS_ANALYSES SUBROURTINE ARE
C	INITIALSIED HERE

	SUBROUTINE STRESS_INITIAL(CSTRESS,DISP,EQUI_PSTRAIN,MODFNODAL,
     1    Y_STRESS,NSTATE,MPROP,NELE,NG,EDOF,ENODE,NTDOF,NPROP)


	IMPLICIT NONE

	INTEGER EDOF,ENODE,NELE,NG,NTDOF,NPROP
	INTEGER K1,K2,K3

	INTEGER NSTATE(NG*NG*NG,NELE)

	REAL*8   MPROP(NPROP,NELE)
	REAL*8   CSTRESS(NG*NG*NG,6,NELE)
        REAL*8   DISP(EDOF,NELE)
        REAL*8   EQUI_PSTRAIN(NG*NG*NG,NELE)
        REAL*8   Y_STRESS(NG*NG*NG,NELE)
	REAL*8   MODFNODAL(NTDOF)

C	INITIALISING CSTRESS STRESS MATRIX

	DO K1 = 1,NELE
	  DO K2 = 1,NG*NG*NG
	    DO K3 = 1,6
	      CSTRESS(K2,K3,K1)=0.0
	    ENDDO
	  ENDDO
	ENDDO


C	INITIALISING MATRIX FOR YIELD STRESS

	DO K1 = 1,NELE
	  DO K2 = 1,NG*NG*NG
	    Y_STRESS(K2,K1)=MPROP(5,K1)
	  ENDDO
	ENDDO


C	INITIALISING STATE MATRIX TO ELASTIC
C	NSTATE=1 INDICATES POINT IS IN ELASTIC RANGE
C	NSTATE=2 INDICATES POINT IS IN PLASTIC RANGE

	DO K1 = 1,NELE
	  DO K2 = 1,NG*NG*NG
	    NSTATE(K2,K1)=1
	  ENDDO
	ENDDO

C 	INITIALISING DISPLACEMENT MATRIX

	DO K1 = 1,NELE
	  DO K2 = 1,EDOF
	    DISP(K2,K1)=0.0
	  ENDDO
	ENDDO


C	INITIALISING EQUIVALENT PLASTIC STRAIN

	DO K1 = 1,NELE
	  DO K2 = 1,NG*NG*NG
	    EQUI_PSTRAIN(K2,K1)=0.0
	  ENDDO
	ENDDO

C	INITIALISING MODIFIED NODAL FORCE VECTOR

	DO K1 = 1,NTDOF
	  MODFNODAL(K1) = 0.0
	ENDDO

	RETURN
	END

C	PARAMETERS OF STRESS ANALYSES SUBROUTINE ARE UPDATED

	SUBROUTINE STRESS_UPDATE(CSTRESS,DELTA_CSTRESS,CSTRESSTDT,
     1	  DELTA_E,DISP,DELTA_U,EQUI_PSTRAIN,DELTA_EQUI_PE,
     1	 DELTA_EQUI_PE_OBJ,NELE,NG,EDOF,ENODE,STRESS_OPTION,STNOP)



	IMPLICIT NONE

	INTEGER  EDOF,ENODE,NELE,NG
	INTEGER  K1,K2,K3

	REAL*8 CSTRESS(NG*NG*NG,6,NELE),
     1           DELTA_CSTRESS(NG*NG*NG,6,NELE)
     
        REAL*8 CSTRESSTDT(NG*NG*NG,6,NELE)

        REAL*8 DELTA_E(NG*NG*NG,6,NELE)

	REAL*8 DISP(EDOF,NELE),DELTA_U(EDOF,NELE)

	REAL*8 EQUI_PSTRAIN(NG*NG*NG,NELE),
     1           DELTA_EQUI_PE(NG*NG*NG,NELE)
     
     	REAL*8 DELTA_EQUI_PE_OBJ(NG*NG*NG,NELE)

	
        INTEGER STNOP

	INTEGER STRESS_OPTION

C	UPDATING DISPLACEMENT

	  DO K1 = 1,NELE
	    DO K2 = 1,EDOF
	      DISP(K2,K1)=DISP(K2,K1)+DELTA_U(K2,K1)
	    ENDDO
	  ENDDO


C	UPDATING STRESSES

	IF(STNOP.EQ.1) THEN ! ITERATIVE UPDATION 
	
	IF(STRESS_OPTION.EQ.1) THEN ! JAUMANNS STRESS MEASURE
	  
	  DO K1 = 1,NELE
	    DO K2 = 1,NG*NG*NG
	      DO K3 = 1,6
	        CSTRESS(K2,K3,K1)=CSTRESS(K2,K3,K1)+
     1		DELTA_CSTRESS(K2,K3,K1)
	      ENDDO
	    ENDDO
	  ENDDO
	  
	  ENDIF
	  
	ELSE        ! INCREMENTAL UPDATION
	
	IF(STRESS_OPTION.EQ.1) THEN ! JAUMANNS STRESS MEASURE
	  
	  DO K1 = 1,NELE
	    DO K2 = 1,NG*NG*NG
	      DO K3 = 1,6
	        CSTRESS(K2,K3,K1)=CSTRESS(K2,K3,K1)+
     1		DELTA_CSTRESS(K2,K3,K1)
	      ENDDO
	    ENDDO
	  ENDDO
	  
	 ELSE
	   
	     DO K1 = 1,NELE
	      DO K2 = 1,NG*NG*NG
	        DO K3 = 1,6
		   CSTRESS(K2,K3,K1)=CSTRESSTDT(K2,K3,K1)
	        ENDDO
	      ENDDO
	    ENDDO
	  
	  ENDIF	  
	  
	  ENDIF


C	UPDATING EQUIVALENT PLASTIC STRAIN
C	REQUIRED ONLY FOR THE JAUMANN STRESS MEASURE
C	AS IN NEW. OBJ. EQUI_PSTRAIN ALREADY HAS THE UPDATED VALUE
	
	  IF(STRESS_OPTION.EQ.1) THEN ! JAUMANNS STRESS MEASURE

	  DO K1 = 1,NELE
	    DO K2 = 1,NG*NG*NG
	      EQUI_PSTRAIN(K2,K1) = EQUI_PSTRAIN(K2,K1)+
     1               DELTA_EQUI_PE(K2,K1)
	    ENDDO
	  ENDDO
	  
	  ELSE
	  
	  DO K1 = 1,NELE
	    DO K2 = 1,NG*NG*NG
	      EQUI_PSTRAIN(K2,K1) = EQUI_PSTRAIN(K2,K1)+
     1               DELTA_EQUI_PE_OBJ(K2,K1)
	    ENDDO
	  ENDDO

	  ENDIF


	 RETURN
	 END
	 
C	CHANGE MADE ON 15.12.2001 TO INCORPORATE THECONCEPT OF UNLOADING

	SUBROUTINE STUCK(CSTRESS_UL,DELTA_STRAIN,YNEW_STRESS,DPROD)
	
	INTEGER I
	REAL *8 CSTRESS_UL(6),DELTA_STRAIN(6)
	REAL *8 DPROD
	REAL *8 HSTRS
	REAL *8 AFVECT(6)
	REAL *8 YNEW_STRESS
	
	HSTRS = (CSTRESS_UL(1) + CSTRESS_UL(2) + CSTRESS_UL(3))/3.0
	
	DO I = 1,3
	  AFVECT(I) = (CSTRESS_UL(I) -HSTRS)*(3.0/(2.0*YNEW_STRESS))
	ENDDO
	
	DO I = 4,6
	  AFVECT(I) = CSTRESS_UL(I)*(3.0/(2.0*YNEW_STRESS))
	ENDDO
	
	DPROD = 0.0
	DO I = 1,6
	  DPROD = DPROD + AFVECT(I) * DELTA_STRAIN(I)
	ENDDO
	
	
	RETURN 
	END


