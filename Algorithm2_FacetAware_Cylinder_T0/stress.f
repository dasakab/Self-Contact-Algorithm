C	SUBROUTINE TO FIND  STATE OF MATERIAL AT GAUSS POINTS
C	FOR EULER INTEGRATION
	
	SUBROUTINE EULER_F_INT(MPROP,XCOORD,YCOORD,ZCOORD,DELTA_E,
     1	DELTA_U,Y_STRESS,EQUI_PSTRAIN,DELTA_EQUI_PE,NSTATE,CSTRESS,
     1  DELTA_CSTRESS,NELE,EDOF,ENODE,NPROP,NG,NPEFI,OPT_ANALYSIS,
     1	INCNUMBER,ITR,RATIO)


	IMPLICIT NONE

	INTEGER NG
	INTEGER EDOF,ENODE,NELE,NPROP,INCNUMBER,ITR

	INTEGER NPEFI,NDUMMY,K1,K2,K3,K4,M1,M2,M3,M4,M5,M6,M7,M8,M9,
     1	N1,MK,MK1,MK2,MN1,MN2,I,J

	INTEGER NCHANGE(NG*NG*NG,NELE),NSTATE(NG*NG*NG,NELE)

	REAL*8 YMC,PR,EXPO,PRO,EQUICSTRESS
	REAL*8 E,Z,SI,EQUIPSTRAIN,DEQUIPSTRAIN,HARDENA,FRACTION
	REAL*8 W(NG),GP(NG)
	REAL*8 MPROP(NPROP,NELE)
	REAL*8 Y_STRESS(NG*NG*NG,NELE),RATIO(NG*NG*NG,NELE)
	REAL*8 CE(6,6),CEP(6,6),CEINVER(6,6),A(6)

	REAL*8 DUMMY,DETERM,BDUMMY(6)

	REAL*8 XCOORD(ENODE,NELE),YCOORD(ENODE,NELE),
     1   ZCOORD(ENODE,NELE),XC(ENODE),YC(ENODE),ZC(ENODE)

	REAL*8 DELTA_U(EDOF,NELE),DELTA_UE(EDOF),DELTA_UE_F1(EDOF),
     1    DELTA_UE_F2(EDOF)

	REAL*8 CSTRESS(NG*NG*NG,6,NELE),
     1	  DELTA_CSTRESS(NG*NG*NG,6,NELE),DELTA_CS(NG*NG*NG,6,NELE),
     1    CSTRESS_C(6),DELTA_CSF1_C(6),DELTA_CSF2_C(6)

	REAL*8 DELTA_JS(NG*NG*NG,6,NELE),DELTA_JSY_C(6),
     1    DELTA_JSF1_C(6),DELTA_JSF2_C(6)

	REAL*8 DELTA_E(NG*NG*NG,6,NELE),EQUI_PSTRAIN(NG*NG*NG,NELE),
     1	  DELTA_EQUI_PE(NG*NG*NG,NELE),DELTA_EY_C(6),DELTA_EPF1_C(6),
     1    DELTA_EPF2_C(6),DELTA_EP_C(6),DELTA_PE_C(6)
     
     	INTEGER OPT_ANALYSIS


	CALL  FIND_STATE (MPROP,XCOORD,YCOORD,ZCOORD,DELTA_E,DELTA_U,
     1    CSTRESS,DELTA_CSTRESS,Y_STRESS,NELE,DELTA_CS,DELTA_JS,NCHANGE,
     1    RATIO,EDOF,ENODE,NPROP,NG,INCNUMBER,ITR)
     
        

	CALL GLWR(W,GP,NG)

	DO K1 = 1,NELE

	  DO M1 = 1,ENODE
	    XC(M1)=XCOORD(M1,K1)
	    YC(M1)=YCOORD(M1,K1)
	    ZC(M1)=ZCOORD(M1,K1)
	  ENDDO

	  DO MN1 = 1,EDOF
	    DELTA_UE(MN1)=DELTA_U(MN1,K1)
	  ENDDO

	  NDUMMY=1

	  DO K2 = 1,NG
	    DO K3 = 1,NG
	      DO K4 = 1,NG
	        E = GP(K2)
	        Z = GP(K3)
	        SI= GP(K4)
	        
                IF (OPT_ANALYSIS .EQ. 1) THEN
                  NCHANGE(NDUMMY,K1)=1
                ENDIF

	IF(NCHANGE(NDUMMY,K1) .EQ. 1) THEN
 	  NSTATE(NDUMMY,K1)=1

C          CASE 1 ELASTIC TO ELASTIC
C          DELTA CAUCHY STRESS  UPDATED

          DO M1 = 1,6
            DELTA_CSTRESS(NDUMMY,M1,K1)=DELTA_CSTRESS(NDUMMY,M1,K1)
     1         +(1.0)*DELTA_CS(NDUMMY,M1,K1)
          ENDDO

        ELSEIF(NCHANGE(NDUMMY,K1).EQ.2)THEN

          NSTATE(NDUMMY,K1)=2

C          CASE 2 ELASTIC TO PLASTIC
C          DELTA CAUCHY STRESS IS UPDATED

          DO M1 = 1,6
            DELTA_CSTRESS(NDUMMY,M1,K1)=DELTA_CSTRESS(NDUMMY,M1,K1)
     1          +(1.0-RATIO(NDUMMY,K1))*DELTA_CS(NDUMMY,M1,K1)
          ENDDO


           YMC = MPROP(1,K1)
           PR  = MPROP(2,K1)

	  CALL C_ELASTIC(YMC,PR,CE)

C       ELASTO-PLASTIC PART OF STRAIN

        DO M5 = 1,6
          DELTA_EP_C(M5)=DELTA_E(NDUMMY,M5,K1)*RATIO(NDUMMY,K1)
        ENDDO

C       SMALL % OF ELASTOPLASTIC STRAIN ASSUMING EQUAL TO
C       PLASTIC STRAIN. THUS NEGLECTING ELASTIC STRAIN

	FRACTION = 0.01

	DO M6 = 1,6
	  DELTA_EPF1_C(M6)=FRACTION*DELTA_EP_C(M6)
	ENDDO

        DO MK = 1,EDOF
	  DELTA_UE_F1(MK) = FRACTION*DELTA_UE(MK)*RATIO(NDUMMY,K1)
        ENDDO

        CALL MATMUL (CE,DELTA_EPF1_C,DELTA_JSF1_C,6,6,1)

        DO MN2 = 1,6
	  CSTRESS_C(MN2)=CSTRESS(NDUMMY,MN2,K1) +
     1    DELTA_CSTRESS(NDUMMY,MN2,K1)
	ENDDO

	CALL INC_C_STRESS(CSTRESS_C,DELTA_JSF1_C,
     1	  DELTA_UE_F1,XC,YC,ZC,E,Z,SI,DELTA_CSF1_C,EDOF,
     1    ENODE)

	CALL  EQUI_INC_PSTRAIN (DELTA_EPF1_C,EQUIPSTRAIN)

C	DELTA CAUCHY STRESS UPDATED

	DO M7 = 1,6
	  DELTA_CSTRESS(NDUMMY,M7,K1)=
     1    DELTA_CSTRESS(NDUMMY,M7,K1)+DELTA_CSF1_C(M7)
	ENDDO

C       EQUIVALENT PLASTIC STRAIN UPDATED

	DELTA_EQUI_PE(NDUMMY,K1)=DELTA_EQUI_PE(NDUMMY,K1)+
     1    EQUIPSTRAIN
     
C       INTEGRATION FOR REMAINED ELASTOPLASTIC PART

	DOM6=1,6
	  DELTA_EPF2_C(M6)=((1.0-FRACTION)/NPEFI)*
     1	  DELTA_EP_C(M6)
	ENDDO
	
	DOMK=1,EDOF
	  DELTA_UE_F2(MK)=(1.0-FRACTION)*(DELTA_UE(MK)/NPEFI)
     1	    *(RATIO(NDUMMY,K1))
        ENDDO

	DO M9 = 1,NPEFI

	  DEQUIPSTRAIN=EQUI_PSTRAIN(NDUMMY,K1)+
     1	  DELTA_EQUI_PE(NDUMMY,K1)

	  DO MN2 = 1,6
	    CSTRESS_C(MN2)=CSTRESS(NDUMMY,MN2,K1)+
     1      DELTA_CSTRESS(NDUMMY,MN2,K1)
	  ENDDO

	  YMC  = MPROP(1,K1)
	  PR   = MPROP(2,K1)
	  EXPO = MPROP(3,K1)
	  PRO  = MPROP(4,K1)

	  CALL C_EPLASTIC(CSTRESS_C,DEQUIPSTRAIN,EXPO,PRO,
     1	    YMC,PR,CEP,A,HARDENA,CE)


	  CALL MATMUL(CEP,DELTA_EPF2_C,DELTA_JSF2_C,6,6,1)

	  CALL INC_C_STRESS(CSTRESS_C,DELTA_JSF2_C,
     1	    DELTA_UE_F2,XC,YC,ZC,E,Z,SI,DELTA_CSF2_C,EDOF,
     1      ENODE)

	  CALL INC_PSTRAIN (A,DELTA_EPF2_C,CE,HARDENA,
     1	    DELTA_PE_C)
	
	  CALL EQUI_INC_PSTRAIN (DELTA_PE_C,EQUIPSTRAIN)

C       DELTA CAUCHY STRESS UPDATED

	  DO M8 = 1,6
	    DELTA_CSTRESS(NDUMMY,M8,K1)=
     1	    DELTA_CSTRESS(NDUMMY,M8,K1)+DELTA_CSF2_C(M8)
	  ENDDO

C       EQUIVALENT PLASTIC STRAIN UPDATED

	  DELTA_EQUI_PE(NDUMMY,K1)=DELTA_EQUI_PE(NDUMMY,K1)+
     1      EQUIPSTRAIN
     
        ENDDO

        ELSEIF (NCHANGE(NDUMMY,K1) .EQ. 3) THEN

        NSTATE(NDUMMY,K1)=2

C       CASE 3 PLASTICS TO PLASTIC TRANSFORMATION

        DO N1 = 1,6
          DELTA_EPF2_C(N1)=DELTA_E(NDUMMY,N1,K1)/NPEFI
        ENDDO
        
        DO MK = 1,EDOF
          DELTA_UE_F2(MK)=DELTA_UE(MK)/NPEFI
        ENDDO

        DO M9 = 1,NPEFI
          DEQUIPSTRAIN=EQUI_PSTRAIN(NDUMMY,K1)+
     1       DELTA_EQUI_PE(NDUMMY,K1)

        DO MN2 = 1,6
	  CSTRESS_C(MN2)=CSTRESS(NDUMMY,MN2,K1)+
     1         DELTA_CSTRESS(NDUMMY,MN2,K1)
	ENDDO

        YMC  = MPROP(1,K1)
        PR   = MPROP(2,K1)
        EXPO = MPROP(3,K1)
        PRO  = MPROP(4,K1)

        CALL C_EPLASTIC(CSTRESS_C,DEQUIPSTRAIN,EXPO,
     1    PRO,YMC,PR,CEP,A,HARDENA,CE)

	CALL MATMUL(CEP,DELTA_EPF2_C,DELTA_JSF2_C,6,6,1)

        CALL INC_C_STRESS(CSTRESS_C,DELTA_JSF2_C,
     1    DELTA_UE_F2,XC,YC,ZC,E,Z,SI,DELTA_CSF2_C,EDOF,
     1    ENODE)

        CALL INC_PSTRAIN (A,DELTA_EPF2_C,CE,
     1    HARDENA,DELTA_PE_C)

        CALL EQUI_INC_PSTRAIN (DELTA_PE_C,EQUIPSTRAIN)

C       DELTA CAUCHY STRESS UPDATED

        DO M8 = 1,6
          DELTA_CSTRESS(NDUMMY,M8,K1)=
     1       DELTA_CSTRESS(NDUMMY,M8,K1)+DELTA_CSF2_C(M8)
        ENDDO

C       EQUIVALENT PLASTIC STRAIN UPDATED

        DELTA_EQUI_PE(NDUMMY,K1)=DELTA_EQUI_PE(NDUMMY,K1)+
     1  EQUIPSTRAIN
        
        ENDDO
        ENDIF

        NDUMMY=NDUMMY+1

        ENDDO
        ENDDO
        ENDDO

        ENDDO

        RETURN
        END


C	SUBROUTINE FINDS TRANSFORMATION PHASES OF MATERIAL
C	AT EVERY GAUSS POINTS AND CALCULATES CORRESPONDING RATIO

	SUBROUTINE FIND_STATE (MPROP,XCOORD,YCOORD,ZCOORD,DELTA_E,
     1	DELTA_U,CSTRESS,DELTA_CSTRESS,Y_STRESS,NELE,DELTA_CS,DELTA_JS,
     1  NCHANGE,RATIO,EDOF,ENODE,NPROP,NG,INCNUMBER,ITR)


	IMPLICIT NONE

	INTEGER NG
	INTEGER EDOF,ENODE,NELE,NPROP
	INTEGER NCHANGE(NG*NG*NG,NELE)
	INTEGER NDUMMY,K1,K2,K3,K4,M1,M2,M3,M4,N1

	REAL*8 YMC,PR,EQUICSTRESS
	REAL*8 E,Z,SI,EQUICSTRESSN,EQUICSTRESSN1
	REAL*8 W(NG),GP(NG)
	REAL*8 Y_STRESS(NG*NG*NG,NELE),RATIO(NG*NG*NG,NELE)
	REAL*8 CE(6,6)
	REAL*8 DUMMY

	REAL*8 MPROP(NPROP,NELE)
	REAL*8 XCOORD(ENODE,NELE),YCOORD(ENODE,NELE),
     1   ZCOORD(ENODE,NELE),XC(ENODE),YC(ENODE),ZC(ENODE)

	REAL*8 DELTA_U(EDOF,NELE),DELTA_UE(EDOF)

	REAL*8 CSTRESS(NG*NG*NG,6,NELE),
     1	  DELTA_CSTRESS(NG*NG*NG,6,NELE),DELTA_CS(NG*NG*NG,6,NELE),
     1    EQUI_CSN(NG*NG*NG,NELE),EQUI_CSN1(NG*NG*NG,NELE),
     1    CSTRESS_C(6),DELTA_CS_C(6),C_STRESSN_C(6),C_STRESSN1_C(6)

	REAL*8 DELTA_JS(NG*NG*NG,6,NELE),DELTA_JS_C(6)

	REAL*8 DELTA_E(NG*NG*NG,6,NELE)
	
C	SOME NEW VARIABLES ADDED ON 15.12.2001
C	TO INCORPORATE THEUNLOADING CONCEPTS

	REAL *8 CSTRESS_UL(6)
	REAL *8 DELTA_STRAIN(6)
	INTEGER B2B
	REAL *8 YNEW_STRESS
	REAL *8 DPROD
	
	INTEGER INCNUMBER,ITR


	CALL GLWR(W,GP,NG)

C	CHANGE OF STATE INITIALISED AS ELASTIC TO ELASTIC

	DO K1 = 1,NELE
	  DO K2 = 1,NG*NG*NG
	    NCHANGE(K2,K1) = 1
	  ENDDO
	ENDDO
	
	DO K1 = 1,NELE

	  DO M1 = 1,ENODE
	    XC(M1)=XCOORD(M1,K1)
	    YC(M1)=YCOORD(M1,K1)
	    ZC(M1)=ZCOORD(M1,K1)
	  ENDDO

	  DO N1 = 1,EDOF
	    DELTA_UE(N1)=DELTA_U(N1,K1)
	  ENDDO

	  NDUMMY =1

	  DO K2 = 1,NG
	  DO K3 = 1,NG
	  DO K4 = 1,NG

	      E = GP(K2)
	      Z = GP(K3)
	      SI= GP(K4)

	      DO M2=1,6
	        CSTRESS_C(M2)=CSTRESS(NDUMMY,M2,K1)
	      ENDDO
	     
	CALL EQUI_CSTRESS(CSTRESS_C,EQUICSTRESS)
        
        YMC = MPROP(1,K1)
	PR  = MPROP(2,K1)
	
	IF(YMC .LT. 0.0) YMC = 100.0
	      
	CALL C_ELASTIC (YMC,PR,CE)


C	      WRITE(*,*)'STUCK IN FIND_STATE'

	      DO M1 = 1,6
	        DUMMY=0.0
		DO M2 = 1,6
	          DUMMY = DUMMY+CE(M1,M2)*DELTA_E(NDUMMY,M2,K1)
	        ENDDO
	          DELTA_JS(NDUMMY,M1,K1)=DUMMY
	      ENDDO

	      DO M3 = 1,6
		DELTA_JS_C(M3)=DELTA_JS(NDUMMY,M3,K1)
		CSTRESS_C(M3) = CSTRESS(NDUMMY,M3,K1)+
     1           DELTA_CSTRESS(NDUMMY,M3,K1)
	      ENDDO

	      CALL INC_C_STRESS(CSTRESS_C,DELTA_JS_C,DELTA_UE,XC,YC,
     1           ZC,E,Z,SI,DELTA_CS_C,EDOF,ENODE)

	      DO M4 = 1,6

		DELTA_CS(NDUMMY,M4,K1)=DELTA_CS_C(M4)

	        C_STRESSN_C(M4)=CSTRESS(NDUMMY,M4,K1)+
     1                DELTA_CSTRESS(NDUMMY,M4,K1)
	        C_STRESSN1_C(M4)=CSTRESS(NDUMMY,M4,K1)+
     1            DELTA_CS_C(M4)+DELTA_CSTRESS(NDUMMY,M4,K1)

	      ENDDO

	      CALL EQUI_CSTRESS(C_STRESSN_C,EQUICSTRESSN)
	      CALL EQUI_CSTRESS(C_STRESSN1_C,EQUICSTRESSN1)
	      
	      EQUI_CSN(NDUMMY,K1)=EQUICSTRESSN
	      EQUI_CSN1(NDUMMY,K1)=EQUICSTRESSN1
	      
	      

C	      FINDING PHASE
C	      NCHANGE =1 INDICATES CHANGE FROM ELASTIC TO ELASTIC
C	      NCHANGE =2 INDICATES CHANGE FROM ELASTIC TO PLASTIC
C	      NCHANGE =3 INDICATES CHANGE FROM PLASTIC TO PLASTIC

		  IF((EQUI_CSN(NDUMMY,K1).LT.
     1		    Y_STRESS(NDUMMY,K1))
     1              .AND.(EQUI_CSN1(NDUMMY,K1)
     1              .LE.Y_STRESS(NDUMMY,K1))) THEN

		    NCHANGE(NDUMMY,K1)=1

		    RATIO(NDUMMY,K1)=0.0

		  ENDIF

		  IF(((EQUI_CSN(NDUMMY,K1).LT.
     1		  Y_STRESS(NDUMMY,K1)).OR.
     1	          ABS(EQUI_CSN(NDUMMY,K1)-Y_STRESS(NDUMMY,K1)).LE.0.01)
     1              .AND.(EQUI_CSN1(NDUMMY,K1)
     1              .GT.Y_STRESS(NDUMMY,K1))) THEN

		    NCHANGE(NDUMMY,K1)=2

		    RATIO(NDUMMY,K1)=(EQUI_CSN1(NDUMMY,K1)-
     1                                 Y_STRESS(NDUMMY,K1))/
     1				      (EQUI_CSN1(NDUMMY,K1)-
     1 				      EQUI_CSN(NDUMMY,K1))

		    ENDIF

		  IF((EQUI_CSN(NDUMMY,K1)-
     1		  Y_STRESS(NDUMMY,K1)).GT.0.01
     1              .AND.(EQUI_CSN1(NDUMMY,K1)
     1              .GT.Y_STRESS(NDUMMY,K1))) THEN

		    NCHANGE(NDUMMY,K1)=3

		    RATIO(NDUMMY,K1)=1.0
		    
C		CHANGE MADE ON 15.12.2001 TO INCORPOPATE THE CONCEPT
C		OF UNLOADING 

		DO B2B = 1,6
		  CSTRESS_UL(B2B) =CSTRESS(NDUMMY,B2B,K1)
		  DELTA_STRAIN(B2B) = DELTA_E(NDUMMY,B2B,K1)
		ENDDO
		
		YNEW_STRESS= EQUI_CSN(NDUMMY,K1)
		
		CALL STUCK(CSTRESS_UL,DELTA_STRAIN,YNEW_STRESS,DPROD)
			
		IF(DPROD .LE. 0.0) THEN		
		  NCHANGE(NDUMMY,K1) = 1
		  RATIO(NDUMMY,K1)=0.0
		  Y_STRESS(NDUMMY,K1) = EQUI_CSN(NDUMMY,K1)				
		ENDIF

C		CHANGE MADE ON 15.12.2001 TO INCORPOPATE THE CONCEPT
C		OF UNLOADING 		

		  ENDIF
		  
		  NDUMMY=NDUMMY+1
	     ENDDO
	     ENDDO
           ENDDO
	 ENDDO

	 RETURN
	 END

C	SUBROUTINE FOR CALCULATING INTERNAL FORCE VECTOR

	SUBROUTINE INT_FORCE(XCOORD,YCOORD,ZCOORD,IG,CSTRESS,
     1	  DELTA_CSTRESS,CSTRESSTDT,DELTA_U,NELE,IDA,INTFORCE,
     1    EDOF,ENODE,NG,STRESS_OPTION,STNOP)


	IMPLICIT NONE

	INTEGER NG
	INTEGER EDOF,ENODE,NELE
	INTEGER IDA,I
        INTEGER IG(EDOF,NELE)
	INTEGER MDUMMY,NDUMMY,K1,K2,K3,K4,M1,M2,M3,M4,M5

	REAL*8 E,Z,SI
	REAL*8 W(NG),GP(NG)
	REAL*8 BLINEAR(6,EDOF),JAC(3,3)

	REAL*8 DETJAC,SF,DUMMY,DUMMY1(EDOF)

	REAL*8 XCOORD(ENODE,NELE),YCOORD(ENODE,NELE),
     1   ZCOORD(ENODE,NELE),XC(ENODE),YC(ENODE),ZC(ENODE),
     1   UXCOORD(ENODE,NELE),UYCOORD(ENODE,NELE),
     1   UZCOORD(ENODE,NELE)

	REAL*8 CSTRESS(NG*NG*NG,6,NELE),
     1	  DELTA_CSTRESS(NG*NG*NG,6,NELE),UCSTRESS(NG*NG*NG,6,NELE)

	REAL*8 DELTA_U(EDOF,NELE)

	REAL*8 INTFORCE(IDA),INTELEFORCE(EDOF)
	
	REAL*8 CSTRESSTDT(NG*NG*NG,6,NELE)
	
	INTEGER STRESS_OPTION,STNOP

	CALL GLWR(W,GP,NG)

C	CAUCHY STRESS UPDATED TOGET INTERNAL FORCE VECTOR

	IF(STNOP.EQ.1) THEN ! ITERATIVE UPDATION
	
	IF(STRESS_OPTION.EQ.1) THEN
	
	DO M1 = 1,NELE
	  DO M2 = 1,NG*NG*NG
	    DO M3 = 1,6
	      UCSTRESS(M2,M3,M1)=CSTRESS(M2,M3,M1)+
     1            DELTA_CSTRESS(M2,M3,M1)
	    ENDDO
	  ENDDO
	ENDDO

	ELSE
	
	DO M1 = 1,NELE
	  DO M2 = 1,NG*NG*NG
	    DO M3 = 1,6
	      UCSTRESS(M2,M3,M1)=CSTRESS(M2,M3,M1)
	    ENDDO
	  ENDDO
	ENDDO
	
	ENDIF
	
	ELSE  ! INCREMENTAL UPDATION
	
	IF(STRESS_OPTION.EQ.1) THEN
	
	DO M1 = 1,NELE
	  DO M2 = 1,NG*NG*NG
	    DO M3 = 1,6
	      UCSTRESS(M2,M3,M1)=CSTRESS(M2,M3,M1)+
     1            DELTA_CSTRESS(M2,M3,M1)
	    ENDDO
	  ENDDO
	ENDDO

	ELSE
	
	 DO M1 = 1,NELE
	  DO M2 = 1,NG*NG*NG
	    DO M3 = 1,6
	      UCSTRESS(M2,M3,M1)=CSTRESSTDT(M2,M3,M1)
	    ENDDO
	  ENDDO
	ENDDO
	
	ENDIF
	
	ENDIF
	
	
C	UPDATING COORDINATES FOR INTEGRATING OVER CURRENT VOLUME

	DO K1 = 1,NELE
	  DO K2 = 1,ENODE
	    UXCOORD(K2,K1) = XCOORD(K2,K1)+DELTA_U(3*K2-2,K1)
	    UYCOORD(K2,K1) = YCOORD(K2,K1)+DELTA_U(3*K2-1,K1)
	    UZCOORD(K2,K1) = ZCOORD(K2,K1)+DELTA_U(3*K2,K1)
	  ENDDO
	ENDDO

C	INITILISE INTERNAL FORCE VECTOR

	DO M1 = 1,IDA
	  INTFORCE(M1)=0.0
	ENDDO

	DO K1 = 1,NELE

	  DO M1 = 1,ENODE
	    XC(M1)=UXCOORD(M1,K1)
	    YC(M1)=UYCOORD(M1,K1)
	    ZC(M1)=UZCOORD(M1,K1)
	  ENDDO

	  DO M1 = 1,EDOF
	    INTELEFORCE(M1)=0.0
	  ENDDO

	  NDUMMY =1

	  DO K2 = 1,NG
	    DO K3 = 1,NG
	    DO K4 = 1,NG

	      E = GP(K2)
	      Z = GP(K3)
	      SI= GP(K4)

	      CALL B_LINEAR (XC,YC,ZC,E,Z,SI,BLINEAR,EDOF,ENODE)

	      DO M2 = 1,EDOF

		DUMMY=0.0

		DO M3 = 1,6
		  DUMMY = DUMMY+BLINEAR(M3,M2)*UCSTRESS(NDUMMY,M3,K1)
	        ENDDO

		DUMMY1(M2)=DUMMY

	      ENDDO

	      CALL JACOBI(XC,YC,ZC,E,Z,SI,JAC,EDOF,ENODE)

	      DETJAC=JAC(1,1)*(JAC(2,2)*JAC(3,3)-JAC(2,3)*JAC(3,2))-
     1	              JAC(1,2)*(JAC(2,1)*JAC(3,3)-JAC(2,3)*JAC(3,1))+
     1		      JAC(1,3)*(JAC(2,1)*JAC(3,2)-JAC(3,1)*JAC(2,2))

	      SF = DETJAC*W(K2)*W(K3)*W(K4)

	      DO M3 = 1,EDOF
		DUMMY1(M3)=DUMMY1(M3)*SF
	      ENDDO

	      DO M4 = 1,EDOF
	        INTELEFORCE(M4)=INTELEFORCE(M4)+DUMMY1(M4)
	      ENDDO

	    NDUMMY =NDUMMY+1

	    ENDDO
	    ENDDO

	  ENDDO

	  DO M5 = 1,EDOF
	    MDUMMY = IG(M5,K1)
	    IF(MDUMMY .NE. 0) THEN
	      INTFORCE(MDUMMY)=INTFORCE(MDUMMY)+INTELEFORCE(M5)
	    ENDIF
	  ENDDO

	ENDDO
	
	
	RETURN
	END


	SUBROUTINE F_ANALYSES(CSTRESS,DELTA_CSTRESS,MPROP,NELE,NPROP,
     1	  FPOINT,NG)


	IMPLICIT NONE

	INTEGER NELE,NPROP,NG
	INTEGER FPOINT,K1,K2,K3

	REAL*8 EQUICSTRESS,MAXEQUICSTRESS,FDUMMY,MAXFDUMMY

	REAL*8 MPROP(NPROP,NELE)

	REAL*8 CSTRESS(NG*NG*NG,6,NELE),
     1	  DELTA_CSTRESS(NG*NG*NG,6,NELE),CSTRESS_C(6)

	MAXEQUICSTRESS =0.0
	MAXFDUMMY = 0.0

	DO K1 = 1,NELE
	  DO K2 = 1,NG*NG*NG
	    DO K3 = 1,6
	      CSTRESS_C(K3)=CSTRESS(K2,K3,K1)+
     1                      DELTA_CSTRESS(K2,K3,K1)
	    ENDDO

	    CALL EQUI_CSTRESS (CSTRESS_C,EQUICSTRESS)

	    IF (MAXEQUICSTRESS.LT.EQUICSTRESS)THEN
	      MAXEQUICSTRESS = EQUICSTRESS
	    ENDIF

	    FDUMMY = EQUICSTRESS/MPROP(6,K1)

	    IF(FDUMMY .GE. MAXFDUMMY) THEN
	      MAXFDUMMY = FDUMMY
	    ENDIF

	  ENDDO
	ENDDO

	IF ((MAXFDUMMY .GT. 0.99).AND.(MAXFDUMMY.LE.1.01)) THEN

	  FPOINT =1      !ANALYSES TILL FAILURE COMPLETE

	ELSEIF (MAXFDUMMY.GT.1.01)THEN

	  FPOINT =2       !ANALYSES OVERSHOOTS FAILURE

	ELSE

	  FPOINT =3       !ANALYSES TILL FAILURE INCOMPLETE

	ENDIF

	RETURN
	END

C	SUBROUTINE FOR ELASTIC ANALYSES

	SUBROUTINE E_SOLN(MPROP,DGFORCE,XCOORD,YCOORD,ZCOORD,IG,
     1    NELE,IDA,CSTRESS,ESTRAIN,DELTA_U,EDOF,ENODE,NPROP,NG)


	IMPLICIT NONE

	INTEGER EDOF,ENODE,NELE,NPROP,NG
	INTEGER IDA
	INTEGER IG(EDOF,NELE)

	INTEGER NDUMMY,K1,K2,K3,K4,M1,M2,M3,M4,M5

	REAL*8 YMC,PR,EQUICSTRESS
	REAL*8 E,Z,SI
	REAL*8 MPROP(NPROP,NELE)
	REAL*8 W(NG),GP(NG)
	REAL*8 CE(6,6),BLINEAR(6,EDOF)
	REAL*8 DUMMY,DGFORCE(IDA)

	REAL*8 XCOORD(ENODE,NELE),YCOORD(ENODE,NELE),
     1   ZCOORD(ENODE,NELE),XC(ENODE),YC(ENODE),ZC(ENODE)

	REAL*8 DELTA_U(EDOF,NELE)

	REAL*8 CSTRESS(NG*NG*NG,6,NELE)

	REAL*8 DELTA_E(NG*NG*NG,6,NELE),ESTRAIN(NG*NG*NG,6,NELE)
	REAL*8 GFORCE(IDA)


	CALL GLWR(W,GP,NG)

	CALL G_ELEMENT(DGFORCE,IDA,IG,NELE,DELTA_U,EDOF,ENODE)

	DO K1 = 1,NELE

	  EQUICSTRESS=0.0
          YMC= MPROP(1,K1)
	  PR = MPROP(2,K1)
	
	  IF (YMC .LT. 0.0) YMC = 100.0
	  
	  CALL C_ELASTIC(YMC,PR,CE)

	  DO M1 = 1,ENODE
	    XC(M1)=XCOORD(M1,K1)
	    YC(M1)=YCOORD(M1,K1)
	    ZC(M1)=ZCOORD(M1,K1)
	  ENDDO

	  NDUMMY=1
	  DO K2 = 1,NG
