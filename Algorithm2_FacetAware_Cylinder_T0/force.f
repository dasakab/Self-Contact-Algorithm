C	SUBROUTINE FOR GLOBAL FORCE VECTOR
	
	SUBROUTINE GLOBEF(XCOORD,YCOORD,ZCOORD,NODE,
     1	  FNODE,FNODAL,IDISP,F_FACE,NTDOF,IDA,NCONTACT,NCOUNT,GFV,
     1    EDOF,ENODE,NELE,RNUMBER,NG)


	IMPLICIT NONE 

	INTEGER EDOF,ENODE,RNUMBER,NELE,NCOUNT,NTDOF,NG,IDA
	
	INTEGER ND,I,II,J,K,K1,MN,NN,K4,L,TTIME,P,NDUMMY

	INTEGER NODE(ENODE,NELE),FNODE(4,6),BNODE_E(4)
	INTEGER F_FACE(6,NELE),Z

	INTEGER IDISP(NTDOF),NBCINT(NTDOF)
        INTEGER NEXTINT(NTDOF),INTEXT(NTDOF)
	INTEGER NDC(NTDOF/3),NDBC(NTDOF/3)
	
	INTEGER DNODE(NTDOF/3)

	INTEGER NCONTACT(NCOUNT),IG(EDOF,NELE)
	
	REAL*8 XCOORD(ENODE,NELE),YCOORD(ENODE,NELE),ZCOORD(ENODE,NELE)
        REAL*8 BXCOORD_E(4),BYCOORD_E(4),BZCOORD_E(4)
	REAL*8 FNODAL(NTDOF),GFV(NTDOF),GFVINT(NTDOF)
	REAL*8 FV(12),F(12)
         
	REAL*8 GFORCE(IDA)
        REAL*8 A2,A3,VEL1(EDOF,NELE),ACC1(EDOF,NELE),MK(EDOF,EDOF)
        REAL*8 ADD(EDOF,NELE)
        REAL *8 ADDNEW(NTDOF),DT
        REAL *8 NEWCON(5)
        REAL *8 ADD1(EDOF,NELE)
               
        REAL *8 NODEDOF(EDOF,NELE)
        
         
        DOJ=1,NTDOF
	  GFV(J)=0.0
	ENDDO
	

	DOK1=1,NTDOF/3
	  DNODE(K1) = 0
	ENDDO

 	 DO I=1,NELE
	    DOII =1 ,6
		
		DOK1=1,4
	          NDUMMY = FNODE(K1,II)
	   	  BXCOORD_E(K1) = XCOORD(NDUMMY,I)
		  BYCOORD_E(K1) = YCOORD(NDUMMY,I)
		  BZCOORD_E(K1) = ZCOORD(NDUMMY,I)
		 
		  BNODE_E(K1) = NODE(NDUMMY,I) 
	          
	 	ENDDO
		  
		
		IF(F_FACE(II,I).EQ.0) THEN  !ZERO LOAD APPLIED
		  
		  DOK1=1,12
		    FV(K1) = 0.0
		  ENDDO
		
		ELSEIF(F_FACE(II,I).EQ.1) THEN  !POINT LOAD APPLIED
		  
		  DOK1=1,4 
		    
		    ND = BNODE_E(K1)
		    IF(DNODE(ND).EQ.1) THEN  
		      F(3*K1-2) = 0.0 
		      F(3*K1-1) = 0.0
		      F(3*K1)   = 0.0
		    ELSE
		      DNODE(ND) = 1
		      F(3*K1-2) = FNODAL(3*ND-2)
		      F(3*K1-1) = FNODAL(3*ND-1)
		      F(3*K1)   = FNODAL(3*ND)
		    ENDIF

		  ENDDO

		  DOK1=1,12
		    FV(K1) = F(K1)
	          ENDDO
		
		ELSEIF(F_FACE(II,I).EQ.2) THEN  !PRESSURE LOADING
		  
		  DOK1=1,4 
		    ND = BNODE_E(K1)
		    F(3*K1-2) = FNODAL(3*ND-2)
		    F(3*K1-1) = FNODAL(3*ND-1)
		    F(3*K1)   = FNODAL(3*ND)
		  ENDDO
		  
		  CALL EFV (F,BXCOORD_E,BYCOORD_E,BZCOORD_E,FV,NG)
		
		ENDIF 
	        
		DOK1=1,4
		  NN = BNODE_E(K1)
		  GFV(3*NN-2) = GFV(3*NN-2) +FV(3*K1-2)
		  GFV(3*NN-1) = GFV(3*NN-1) +FV(3*K1-1)
		  GFV(3*NN)   = GFV(3*NN)   +FV(3*K1)
		 
		       ENDDO

	    ENDDO
 	ENDDO
	
	RETURN
	END
	
 
 	


C	SUBROUTINE TO FIND ELEMENTAL FORCE VECTOR
C	PASSED OUT ={FV}
C	NG=NUMBER OF GAUSS POINTS
	        
	SUBROUTINE EFV (F,BXCOORD_E,BYCOORD_E,BZCOORD_E,FV,NG)

	IMPLICIT NONE

	INTEGER NG,J,JJ,JK,M1,I,L
	
	REAL*8 W(NG),GP(NG)
        REAL*8 BXCOORD_E(4),BYCOORD_E(4),BZCOORD_E(4)

     	REAL*8 E,Z,DETJAC,SF
	
	REAL*8 F(12,1),FV(12,1),FV1(12,1)
	REAL*8 N(3,12),NTRAN(12,3),NNTRAN(12,12),SFNNT(12,12)


	DOM1=1,12
	  FV(M1,1)=0.0
	ENDDO	

	CALL GLWR (W,GP,NG)
	
	DOJ=1,NG
	  DOJK = 1,NG

	    E = GP(J)
	    Z =GP(JK)

	    CALL FORCEN (E,Z,N)
	    CALL TRANS(N,NTRAN,3,12)
	    CALL MATMUL (NTRAN,N,NNTRAN,12,3,12)
	    
	    
	    CALL S_DETJAC(BXCOORD_E,BYCOORD_E,BZCOORD_E,E,Z,DETJAC)
	    
	    SF = DETJAC*W(J)*W(JK)
	    

	    CALL SCAMUL (NNTRAN,SFNNT,12,12,SF)
	    CALL MATMUL (SFNNT,F,FV1,12,12,1)

	    DOJJ=1,12
	      FV(JJ,1)=FV1(JJ,1)+FV(JJ,1)
	    ENDDO

	  ENDDO
	ENDDO

	RETURN
	END


C	SUBROUTINE TO FIND SHAPE FUNCTION MATRIX
C	FOR FORCE
C	PASSED IN GAUSS ROOT=Z
C	PASSED OUT SHAPE FUCTION MATRIX=[A]
	
	SUBROUTINE FORCEN (E,Z,A)


	IMPLICIT NONE

	INTEGER K1,K2
	
	REAL*8 A(3,12),E,Z

	DOK1=1,12
	  DOK2=1,3
	    A(K2,K1) = 0.0
	  ENDDO
	ENDDO

	A(1,1) = (1-Z)*(1-E)/4.0
	A(1,4) = (1+Z)*(1-E)/4.0
	A(1,7) = (1+Z)*(1+E)/4.0
	A(1,10) = (1-Z)*(1+E)/4.0

	A(2,2) = (1-Z)*(1-E)/4.0
	A(2,5) = (1+Z)*(1-E)/4.0
	A(2,8) = (1+Z)*(1+E)/4.0
	A(2,11) = (1-Z)*(1+E)/4.0

	A(3,3) = (1-Z)*(1-E)/4.0
	A(3,6) = (1+Z)*(1-E)/4.0
	A(3,9) = (1+Z)*(1+E)/4.0
	A(3,12) = (1-Z)*(1+E)/4.0

	RETURN
	END

C	SUBROUTINE TO FIND DETERMINANT OF JACOBIAN MATRIX
C	FOR INTEGRATING OVER SURFACE (NEEDED FOR FINDING 
C	GLOBAL FORCE VECTOR)
	
	SUBROUTINE S_DETJAC(BXCOORD_E,BYCOORD_E,BZCOORD_E,E,Z,DETJAC)

	IMPLICIT NONE

	INTEGER K1
	
C123456	
	
	REAL*8 DERV(2,4),BXCOORD_E(4),BYCOORD_E(4),BZCOORD_E(4),DA(4),
     1           E,Z,DETJAC,DXDZI,DYDZI,DZDZI,DXDET,DYDET,DZDET     

	CALL S_DERVN(E,Z,DERV)
	
	DXDZI = 0.0
	DYDZI = 0.0
	DZDZI = 0.0
	DOK1=1,4
	  DXDZI = DERV(1,K1)*BXCOORD_E(K1) +DXDZI
	  DYDZI = DERV(1,K1)*BYCOORD_E(K1) +DYDZI
	  DZDZI = DERV(1,K1)*BZCOORD_E(K1) +DZDZI
	ENDDO

	DXDET = 0.0
	DYDET = 0.0
	DZDET = 0.0
	DOK1=1,4
	  DXDET = DERV(2,K1)*BXCOORD_E(K1) +DXDET
	  DYDET = DERV(2,K1)*BYCOORD_E(K1) +DYDET
	  DZDET = DERV(2,K1)*BZCOORD_E(K1) +DZDET
	ENDDO
	
	DA(1) = DYDZI*DZDET - DZDZI*DYDET
	DA(2) = -(DXDZI*DZDET-DZDZI*DXDET)
	DA(3) = DXDZI*DYDET - DYDZI*DXDET

	DETJAC = DSQRT(DA(1)**2+DA(2)**2+DA(3)**2)
	
	RETURN
	END

C	SUBROUTINE FOR STORING DERIVATIVES OF SHAPE FUNCTIONS
C	FOR SURFACE

	SUBROUTINE S_DERVN(E,Z,DERV)

	IMPLICIT NONE
	
	REAL*8 DERV(2,4),E,Z

	DERV(1,1) = -(1-E)/4.0
	DERV(1,2) = (1-E)/4.0
	DERV(1,3) = (1+E)/4.0
	DERV(1,4) = -(1+E)/4.0
	
	DERV(2,1) = -(1-Z)/4.0
	DERV(2,2) = -(1+Z)/4.0
	DERV(2,3) = (1+Z)/4.0
	DERV(2,4) = (1-Z)/4.0

	RETURN
	END
	
	

