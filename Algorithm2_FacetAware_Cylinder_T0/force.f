        SUBROUTINE VELASM (VEL1,ACC1,EDOF,NELE,ENODE,NODE,ADDNEW,DT,
     1  NTDOF,MODXCOORD,MODYCOORD,MODZCOORD,NG,MPROP,NPROP)
	
	IMPLICIT NONE
	INTEGER EDOF,NELE,NTDOF,ENODE,I,J
	INTEGER NODE(ENODE,NELE)
	INTEGER NODEDOF(EDOF,NELE)
	REAL *8 VEL1(EDOF,NELE)
	REAL *8 ACC1(EDOF,NELE)
	REAL *8 DT
	REAL *8 ADDNEW(NTDOF)
	REAL *8 MK(EDOF,EDOF)
	REAL *8 ADD(EDOF,NELE)
	REAL *8 ADD1(EDOF,NELE)
	REAL *8 NEWCON(5)
	
	REAL *8 VELL1(EDOF,NELE)
	REAL *8 ACCL1(EDOF,NELE)
 	
C       ==========================================================
C	NEW VARIABLE DECLARATIONS DONE ON 10.10.2002

	REAL*8  MODXCOORD(ENODE,NELE),MODYCOORD(ENODE,NELE)
        REAL*8  MODZCOORD(ENODE,NELE)
	INTEGER NPROP
	REAL*8  MPROP(NPROP,NELE),RO
	REAL*8  XC(ENODE),YC(ENODE),ZC(ENODE)
	REAL*8  DUMMY(EDOF),DUMMY1(EDOF)
	INTEGER NG,JFLAG,K1,K2,K
	
C	==========================================================	 	
 	
 	
	CALL NEWCONCS(DT,NEWCON)
	
	CALL SCAMUL(VEL1,VELL1,EDOF,NELE,NEWCON(2))
	
	CALL SCAMUL (ACC1,ACCL1,EDOF,NELE,NEWCON(3))
		
	CALL MATADD(VELL1,ACCL1,ADD,EDOF,NELE)


	DO I=1,NELE
       	  DO J=1,EDOF
        	ADD1(J,I)=0.0
	  ENDDO
	ENDDO
	
	DO I=1,NELE
	
	  DO J=1,ENODE
	    XC(J)=MODXCOORD(J,I)
	    YC(J)=MODYCOORD(J,I)
	    ZC(J)=MODZCOORD(J,I)
	  ENDDO
	
	  RO = MPROP(7,I)
		
	  CALL MASS(XC,YC,ZC,MK,EDOF,ENODE,NG,JFLAG,RO)
	
       
          DO J=1,EDOF
            DUMMY(J)=ADD(J,I)
	  ENDDO
	
	  CALL MATMUL(MK,DUMMY,DUMMY1,EDOF,EDOF,1)
	
	  DO J=1,EDOF
            ADD1(J,I)=DUMMY1(J)
	  ENDDO	
	
	ENDDO
	
	CALL NODDOF(NODE,NODEDOF,ENODE,EDOF,NELE)
	
	CALL ADDASM (ADD1,ADDNEW,EDOF,NELE,NODEDOF,NTDOF)
 	
 	
 	RETURN
 	END
 	
 	 	
 	
	SUBROUTINE MATADD(VEL1,ACC1,ADD,EDOF,NELE)
	
	
	IMPLICIT NONE
	INTEGER EDOF,NELE
	
	INTEGER I,J
	
	REAL *8 VEL1(EDOF,NELE)
	REAL *8 ACC1(EDOF,NELE)
	REAL *8 ADD(EDOF,NELE)
	
	DO I=1,NELE
	DO J=1,EDOF
	
	ADD(J,I) =VEL1(J,I) + ACC1(J,I)
	
	ENDDO
	ENDDO
	
	RETURN
	END
	
	
	SUBROUTINE NODDOF(NODE,NODEDOF,ENODE,EDOF,NELE)
	
	IMPLICIT NONE
	INTEGER EDOF,ENODE,NELE
	INTEGER I,J,DUMMY
	
	INTEGER NODE(ENODE,NELE)
	INTEGER NODEDOF(EDOF,NELE)
	
	DO I=1,NELE
	DO J=1,ENODE
	DUMMY = NODE(J,I)
	NODEDOF(3*J,I)=3*DUMMY
	NODEDOF(3*J-1,I)=3*DUMMY -1
	NODEDOF(3*J-2,I)=3*DUMMY -2
	ENDDO
	ENDDO
	
	RETURN
	END
		
	
	SUBROUTINE ADDASM(ADD1,ADDNEW,EDOF,NELE,NODEDOF,NTDOF)
	
	IMPLICIT NONE
	INTEGER EDOF,NELE,NDUMMY,NTDOF,J,I
	INTEGER NODEDOF(EDOF,NELE)
	REAL *8 ADD1(EDOF,NELE)
	REAL *8 ADDNEW(NTDOF)
	
	DO I=1,NTDOF
	ADDNEW(I) = 0.0
	ENDDO

	DO I=1,NELE
	DO J= 1,EDOF
	
	NDUMMY = NODEDOF(J,I)
	
	ADDNEW(NDUMMY) = ADD1(J,I)+ ADDNEW(NDUMMY)
	
	ENDDO
	ENDDO
	      
 	
	RETURN
 	END
 	
 	
 	
 	SUBROUTINE NEWCONCS(DT,NEWCON)
 	
 	IMPLICIT NONE

 	REAL *8 DT
 	REAL *8 NEWCON(5)
 	
 	REAL *8 ALPHA,DELTA,GAMA
 	
 	PARAMETER (ALPHA = 1.0)
	PARAMETER (DELTA = 1.50)
 	
 	NEWCON(1) = 1/((ALPHA)*(DT**2))
 	
 	NEWCON(2) = 1/((ALPHA)*(DT))

 	NEWCON(3) = (1/(2*ALPHA)) -1
 	
 	NEWCON(4) = (DT) * (1-DELTA)
 	
 	NEWCON(5) = DELTA * DT
 	
 	RETURN
 	END
 	
 	
        SUBROUTINE ACCEL (VEL1,ACC1,ACC2,U,EDOF,NELE,DT)
 	
 	IMPLICIT NONE
 	INTEGER EDOF
 	
 	INTEGER S,L,J,NELE
 	
 	REAL *8 VEL1(EDOF,NELE)
 	REAL *8 ACC1(EDOF,NELE), ACC2(EDOF,NELE)
 	REAL *8 U(EDOF,NELE)
 	REAL *8 DT
 	REAL *8 NEWCON(5)
 	
 	
 	
 	CALL NEWCONCS(DT,NEWCON)
 	
 	DO J=1,NELE
 	  DO L=1,EDOF
 	
 	ACC2(L,J) = NEWCON(1)*U(L,J) - NEWCON(2)*VEL1(L,J) - 
     1	            NEWCON(3)*ACC1(L,J)
 	
 	  ENDDO
 	ENDDO
 	
 	RETURN
 	END
 	
 	
 	
 	
 	SUBROUTINE VELOCITY (VEL1,VEL2,ACC1,ACC2,EDOF,NELE,DT)
 	
 	IMPLICIT NONE
 	INTEGER EDOF,NELE
 	
 	INTEGER S,J
 	
 	REAL *8 VEL1(EDOF,NELE),VEL2(EDOF,NELE)
	REAL *8 ACC1(EDOF,NELE),ACC2(EDOF,NELE)
	REAL *8 DT
	REAL *8 NEWCON(5)
	
	
	CALL NEWCONCS(DT,NEWCON)
	
	DO J=1,NELE
	 DO S= 1,EDOF	
	  VEL2(S,J) =VEL1(S,J)+NEWCON(4)*ACC1(S,J)+NEWCON(5)*ACC2(S,J)	
	 ENDDO
	ENDDO
	
	RETURN
	END
	
