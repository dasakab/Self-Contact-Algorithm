        SUBROUTINE EULER_F_INT_NEWOBJ(MPROP,XCOORD,YCOORD,
     1  ZCOORD,Y_STRESS,CSTRESS,CSTRESSTDT,EQUI_PSTRAIN,
     1  NODE,DELTA_U,NSTATE,NELE,ENODE,EDOF,NPEFI,NG,
     1  NPROP,ITR,INCNUMBER,DELTA_EQUI_PE_OBJ,EQUI_PSTRAIN_TEMP,
     1  Y_STRESS_TEMP,NSTATE_TEMP)

C123456     
C$RANGE ON
C$CHECK_OVERFLOW INTEGER ON

	IMPLICIT NONE
	

	INTEGER NELE,EDOF,NG,NPEFI,ENODE,NPROP
	INTEGER NODE(ENODE,NELE)
	REAL*8  MPROP(NPROP,NELE),EQUI_PSTRAIN_TEMP(NG*NG*NG,NELE)
	REAL*8  XCOORD(ENODE,NELE),YCOORD(ENODE,NELE),ZCOORD(ENODE,NELE)
	
	REAL*8  CSTRESS(NG*NG*NG,6,NELE)
	REAL*8  EQUI_PSTRAIN(NG*NG*NG,NELE),EQUI_PSTRAIN_E(NG*NG*NG)
	REAL*8  Y_STRESS(NG*NG*NG,NELE),CSTRESSTDT(NG*NG*NG,6,NELE)
	REAL*8  DELTA_U(EDOF,NELE),Y_STRESS_TEMP(NG*NG*NG,NELE)
	INTEGER NSTATE(NG*NG*NG,NELE),NSTATE_TEMP(NG*NG*NG,NELE)
	
	INTEGER K1,M1,M2,ITR
	REAL*8  XC(ENODE),YC(ENODE),ZC(ENODE)
	REAL*8  SIGYD(NG*NG*NG)
	INTEGER STATE(NG*NG*NG)
	REAL*8  CSTRESS_E(NG*NG*NG,6),DELTA_UE(EDOF)
	REAL*8  STRESSTDT(NG*NG*NG,6)
	REAL*8  YMC,PR,EXPO,PRO,FMATX(3,3)
	
	INTEGER II,JJ,INCNUMBER
	
	REAL*8 DELTA_EQUI_PE_OBJ(NG*NG*NG,NELE)
	REAL*8 DELTA_EQUI_PE_OBJ_E(NG*NG*NG)
	
	
C=========================================================	
	DO K1=1,NELE
		
		DOM1=1,ENODE
		   XC(M1)=XCOORD(M1,K1)
		   YC(M1)=YCOORD(M1,K1)
		   ZC(M1)=ZCOORD(M1,K1)
		ENDDO
	
	DO M1=1,NG*NG*NG
	   SIGYD(M1)=Y_STRESS(M1,K1)
	ENDDO
	
	DO M1=1,NG*NG*NG
	   STATE(M1)=NSTATE(M1,K1)
	ENDDO
	
	DO M1=1,NG*NG*NG
	   DO M2=1,6
	     CSTRESS_E(M1,M2)=CSTRESS(M1,M2,K1)
	   ENDDO
	ENDDO
	
	DO M1=1,NG*NG*NG
		EQUI_PSTRAIN_E(M1)=EQUI_PSTRAIN(M1,K1)
	ENDDO
	
	DO M1=1,EDOF
	   DELTA_UE(M1)=DELTA_U(M1,K1)
	ENDDO
	
	DO M1=1,NG*NG*NG
	   DELTA_EQUI_PE_OBJ_E(M1)=DELTA_EQUI_PE_OBJ(M1,K1)
	ENDDO
	
	YMC=MPROP(1,K1)
	PR=MPROP(2,K1)
	EXPO=MPROP(3,K1)
	PRO=MPROP(4,K1)
	DO M1=1,NG*NG*NG
		EQUI_PSTRAIN_E(M1)=EQUI_PSTRAIN(M1,K1)
	ENDDO
	
C123456

	CALL OBJECTIVE_STRESS2(XC,YC,ZC,CSTRESS_E,
     1     EQUI_PSTRAIN_E,DELTA_UE,SIGYD,
     1    STRESSTDT,NODE,STATE,YMC,PR,EXPO,
     1    PRO,NELE,ENODE,EDOF,NPEFI,NG,K1,ITR,INCNUMBER,
     1	  DELTA_EQUI_PE_OBJ_E)
    
         
	DO M1=1,NG*NG*NG
	   DO M2=1,6
	     CSTRESSTDT(M1,M2,K1)=STRESSTDT(M1,M2)
	   ENDDO
	ENDDO
	
	DOM1=1,NG*NG*NG
	   NSTATE_TEMP(M1,K1)=STATE(M1)
	ENDDO
	
	DOM1=1,NG*NG*NG 
	   Y_STRESS_TEMP(M1,K1)=SIGYD(M1)
	ENDDO
	DO M1=1,NG*NG*NG
	   EQUI_PSTRAIN_TEMP(M1,K1)=EQUI_PSTRAIN_E(M1)
	ENDDO
	DO M1=1,NG*NG*NG
	 DELTA_EQUI_PE_OBJ(M1,K1)=DELTA_EQUI_PE_OBJ_E(M1)
	ENDDO
	

	ENDDO

C=========================================================	
	
	
	RETURN
	END