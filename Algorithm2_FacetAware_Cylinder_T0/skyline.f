	SUBROUTINE C_ELASTIC(YMC,PR,A)
	
	
	IMPLICIT NONE

	INTEGER K1,K2

	REAL*8 YMC,PR
	REAL*8 DUMMY
	REAL*8 A(6,6)

	DUMMY = YMC/((1.0+PR)*(1.0-2.0*PR))

	DO K1 =1,6
	  DO K2 =1,6
	    A(K1,K2) = 0.0
	  ENDDO
        ENDDO

	A(1,1) = 1.0-PR 
	A(2,2) = 1.0-PR 
	A(3,3) = 1.0-PR 
	
	A(4,4) = (1.0-2.0*PR)/2.0
	A(5,5) = (1.0-2.0*PR)/2.0
	A(6,6) = (1.0-2.0*PR)/2.0
	
	A(1,2) = PR
	A(1,3) = PR
	A(2,1) = PR
	A(2,3) = PR
	A(3,1) = PR
	A(3,2) = PR

	DO K1 =1,6
	  DO K2 =1,6
	    A(K1,K2) = DUMMY*A(K1,K2)
          ENDDO
        ENDDO

	RETURN
	END


