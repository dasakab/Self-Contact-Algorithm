C	SUBROUTINE FOR MATRIX MULTIPLICATION
C	PASSED IN = MATRIX[A],[B],DIMENSION M,N,NP
C	PASSED OUT = [C] = [A][B]

	SUBROUTINE MATMUL(A,B,C,M,N,NP)
	
	
	IMPLICIT NONE
	
	INTEGER M,N,NP,I,J,K

	REAL*8 A(M,N),B(N,NP),C(M,NP)

	DO 10 I = 1,M
	  DO 20 J = 1,NP
	    C(I,J)=0
	    DO 30 K = 1,N
	      C(I,J)=C(I,J)+A(I,K)*B(K,J)
30	    CONTINUE
20	  CONTINUE
10	CONTINUE
	
	RETURN
	END

C	SUBROUTINE FOR OBTAINING TRANSPOSE OF MATRIX
C	PASSED IN=MATRIX[A],DIMENSION M,N
C	PASSED OUT=[B]=TRANPOSE OF [A]
	SUBROUTINE TRANS (A,B,M,N)
	
	
	IMPLICIT NONE
	
	INTEGER M,N,I,J
	
	REAL*8 A(M,N),B(N,M)
	DO 10 I=1,M
	  DO 20 J=1,N
	    B(J,I)=A(I,J)
20	  CONTINUE
10	CONTINUE
	
	RETURN
	END

C	SUBROUTINE FOR MATRIX SCALER MULTIPLICATION
C	PASSED IN=MATRIX[A],DIMENSIONM(M,N),SCALAR MULTIPLIER(K)	
C	PASSED OUT=[B]=K[A]
	
	SUBROUTINE SCAMUL(A,B,M,N,CK)
	
	
	IMPLICIT NONE
	INTEGER M,N,I,J
	REAL*8 A(M,N),B(M,N),CK
	
	DO 10 I=1,M
	  DO 20 J=1,N
	    B(I,J)=CK*A(I,J)
20	  CONTINUE
10	CONTINUE
	
	RETURN
	END

