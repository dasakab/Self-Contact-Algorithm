C	SUBROUTINE TO FIND B MATRIX

	SUBROUTINE B_LINEAR(XC,YC,ZC,E,Z,SI,B,EDOF,ENODE)

	
	IMPLICIT NONE
	
	INTEGER EDOF,ENODE
	INTEGER K1,K2

	REAL*8 E,Z,SI
	REAL*8 XC(ENODE),YC(ENODE),ZC(ENODE)
	REAL*8 B(6,EDOF),T(3,3),A(3,ENODE)

	
	CALL DERVN (E,Z,SI,A,EDOF,ENODE)
	CALL TMAT (XC,YC,ZC,E,Z,SI,T,EDOF,ENODE)
	
	DO K1 = 1,6
	  DO K2 = 1,EDOF
	    B(K1,K2) = 0.0
          ENDDO
        ENDDO
	
	DO K1 = 1,ENODE
	  B(1,3*K1-2) = A(1,K1)*T(1,1)+A(2,K1)*T(1,2)+A(3,K1)*T(1,3)
	  B(2,3*K1-1) = A(1,K1)*T(2,1)+A(2,K1)*T(2,2)+A(3,K1)*T(2,3)
	  B(3,3*K1)   = A(1,K1)*T(3,1)+A(2,K1)*T(3,2)+A(3,K1)*T(3,3)
	ENDDO

	DO K1 = 1,ENODE
	  B(4,3*K1-2) = A(1,K1)*T(2,1)+A(2,K1)*T(2,2)+A(3,K1)*T(2,3)
	  B(4,3*K1-1) = A(1,K1)*T(1,1)+A(2,K1)*T(1,2)+A(3,K1)*T(1,3)
	ENDDO

	DO K1 = 1,ENODE
	  B(5,3*K1-1) = A(1,K1)*T(3,1)+A(2,K1)*T(3,2)+A(3,K1)*T(3,3)
	  B(5,3*K1)   = A(1,K1)*T(2,1)+A(2,K1)*T(2,2)+A(3,K1)*T(2,3)
 	ENDDO

	DO K1 = 1,ENODE
	  B(6,3*K1-2) = A(1,K1)*T(3,1)+A(2,K1)*T(3,2)+A(3,K1)*T(3,3)
	  B(6,3*K1)   = A(1,K1)*T(1,1)+A(2,K1)*T(1,2)+A(3,K1)*T(1,3)
	ENDDO

	RETURN

	END


C 	SUBROUTINE FOR B NONLINEAR

	SUBROUTINE B_NLINEAR(XC,YC,ZC,E,Z,SI,BNLN,EDOF,ENODE)

	
	IMPLICIT  NONE

	INTEGER EDOF,ENODE
	INTEGER K1,K2

	REAL*8 E,Z,SI
        REAL*8 XC(ENODE),YC(ENODE),ZC(ENODE)
	REAL*8 BNLN(9,EDOF),A(3,ENODE),T(3,3)

C	INITIALISE B_NLINEAR MATRIX
	
	DO K1 = 1,EDOF
	  DO K2 = 1,9
	    BNLN(K2,K1)=0.0
	  ENDDO
	ENDDO
	
	CALL DERVN (E,Z,SI,A,EDOF,ENODE)

	CALL TMAT (XC,YC,ZC,E,Z,SI,T,EDOF,ENODE)

	DO K1 = 1,ENODE
	  
	  BNLN(1,3*K1-2) = A(1,K1)*T(1,1)+A(2,K1)*T(1,2)+A(3,K1)*T(1,3)
	  BNLN(2,3*K1-2) = A(1,K1)*T(2,1)+A(2,K1)*T(2,2)+A(3,K1)*T(2,3)
	  BNLN(3,3*K1-2) = A(1,K1)*T(3,1)+A(2,K1)*T(3,2)+A(3,K1)*T(3,3)
	
	  BNLN(4,3*K1-1) = A(1,K1)*T(1,1)+A(2,K1)*T(1,2)+A(3,K1)*T(1,3)
	  BNLN(5,3*K1-1) = A(1,K1)*T(2,1)+A(2,K1)*T(2,2)+A(3,K1)*T(2,3)
	  BNLN(6,3*K1-1) = A(1,K1)*T(3,1)+A(2,K1)*T(3,2)+A(3,K1)*T(3,3)
	
	  BNLN(7,3*K1)   = A(1,K1)*T(1,1)+A(2,K1)*T(1,2)+A(3,K1)*T(1,3)
	  BNLN(8,3*K1)   = A(1,K1)*T(2,1)+A(2,K1)*T(2,2)+A(3,K1)*T(2,3)
	  BNLN(9,3*K1)   = A(1,K1)*T(3,1)+A(2,K1)*T(3,2)+A(3,K1)*T(3,3)
	
	ENDDO

	RETURN
	END


C	SUBROUTINE PROGRAM TO FIND MASS MATRIX OF AN ELEMENT
	
	SUBROUTINE MASS(XC,YC,ZC,MK,EDOF,ENODE,NG,JFLAG,RO)

	
	IMPLICIT NONE
	
	INTEGER NG,JFLAG
	INTEGER EDOF,ENODE
	
	INTEGER NDUMMY,I,IK,JJ,KKK,K1,IJ ,J
	
	REAL*8 E,Z,SI,RO
	REAL*8 DETJAC,SF
	REAL*8 W(NG),GP(NG)

	REAL*8 XC(ENODE),YC(ENODE),ZC(ENODE)
	
	REAL*8 MK(EDOF,EDOF),JAC(3,3),N(3,EDOF)	
	
	REAL*8 NF(EDOF,3),S(EDOF,EDOF),G(EDOF,EDOF),
     1       NTRAN(EDOF,3)
        
        
	DO I = 1,EDOF
          DO JJ = 1,EDOF
	    MK(I,JJ)=0
	  ENDDO
 	ENDDO
	
	JFLAG = 0        !FLAG FOR JACOBIAN     

	CALL GLWR(W,GP,NG)
	
	
	DO 30 I = 1,NG
	  DO 40 JJ = 1,NG
	    DO 50 KKK = 1,NG

	      E  = GP(I)
	      Z  = GP(JJ)
	      SI = GP(KKK)
	      
	      CALL NMATRIX(E,Z,SI,N,EDOF,ENODE)
	      CALL TRANS (N,NTRAN,3,EDOF)
	      CALL SCAMUL(NTRAN,NF,EDOF,3,RO)
	      CALL MATMUL (NF,N,S,EDOF,3,EDOF)
	      CALL JACOBI (XC,YC,ZC,E,Z,SI,JAC,EDOF,ENODE)
	      
	      DETJAC=JAC(1,1)*(JAC(2,2)*JAC(3,3)-JAC(2,3)*JAC(3,2))-
     1	             JAC(1,2)*(JAC(2,1)*JAC(3,3)-JAC(2,3)*JAC(3,1))+
     1		     JAC(1,3)*(JAC(2,1)*JAC(3,2)-JAC(3,1)*JAC(2,2))
	      
	      IF(DETJAC.LE.0.0) THEN
		JFLAG = 1
	      ENDIF

	      SF=DETJAC*W(I)*W(JJ)*W(KKK)
	
	      CALL SCAMUL (S,G,EDOF,EDOF,SF)
	
	      DO 25 IK = 1,EDOF
	        DO 35 IJ = 1,EDOF
	          MK(IK,IJ)=MK(IK,IJ)+G(IK,IJ)
35	        CONTINUE
25	      CONTINUE
	      
	     

50	    CONTINUE
40	  CONTINUE
30	CONTINUE
	
	RETURN	
	END


C	SUBROUTINE TO FIND N MATRIX

	SUBROUTINE NMATRIX(E,Z,SI,N,EDOF,ENODE)

	
	IMPLICIT NONE
	
	INTEGER EDOF,ENODE
	INTEGER K1,K2,I,J

	REAL*8 E,Z,SI
	
	REAL*8 N(3,EDOF),A(1,ENODE)

	
	CALL SHAPEFN(E,Z,SI,A,EDOF,ENODE)
	
	DO K1 = 1,3
	  DO K2 = 1,EDOF
	    N(K1,K2) = 0.0
          ENDDO
        ENDDO
        
        DO K1=1,ENODE
          N(1,3*K1-2)=A(1,K1)
          N(2,3*K1-1)=A(1,K1)
          N(3,3*K1) =A(1,K1)
        ENDDO
        
	RETURN
	END


C	[DERV] STORES DERIVATIVE OF SHAPE FUNCTION OF
C	SERENDIPIDI ELEMENT W.R.T. NATURAL COORDINATES

	SUBROUTINE SHAPEFN(E,Z,SI,SHAPE,EDOF,ENODE)


	IMPLICIT NONE

	INTEGER EDOF,ENODE

	REAL*8 E,Z,SI
	REAL*8 SHAPE(ENODE)

	SHAPE(1) = (1-E)*(1-SI)*(1-Z)/8.0
	SHAPE(2) = (1-E)*(1-SI)*(1+Z)/8.0
	SHAPE(3) = (1+E)*(1-SI)*(1+Z)/8.0
	SHAPE(4) = (1+E)*(1-SI)*(1-Z)/8.0
	SHAPE(5) = (1-E)*(1+SI)*(1-Z)/8.0
	SHAPE(6) = (1-E)*(1+SI)*(1+Z)/8.0
	SHAPE(7) = (1+E)*(1+SI)*(1+Z)/8.0
	SHAPE(8) = (1+E)*(1+SI)*(1-Z)/8.0
		
        RETURN
	END
	
	SUBROUTINE DYNASTIF( STIF,MK,EDOF,DT)
	
	INTEGER EDOF,I,J
	
	REAL *8 STIF(EDOF,EDOF)
	REAL *8 MK(EDOF,EDOF)
	REAL *8 A0,DT
	
	
	A0 = 4/((DT)**2)
	
	DO I = 1,EDOF
	  DO J = 1,EDOF
	    STIF(I,J)=A0*MK(I,J) + STIF(I,J)
	  ENDDO
	ENDDO
	
	RETURN 
	END
	
	
C	SUBROUTINE TO FIND JACOBIAN MATRIX

C	GAUSSIAN COORDINATES = E,Z,SI
C	JACOBIAN MATRIX = [JAC]

	SUBROUTINE JACOBI(XC,YC,ZC,E,Z,SI,JAC,EDOF,ENODE)


	IMPLICIT NONE

	INTEGER EDOF,ENODE
	INTEGER I,J,II

     	REAL*8 E,Z,SI
	REAL*8 XC(ENODE),YC(ENODE),ZC(ENODE)
	REAL*8 JAC(3,3),DN(3,ENODE)

	DO I = 1,3
	  DO J = 1,3
	    JAC(I,J) = 0.0
          ENDDO
        ENDDO

	CALL DERVN (E,Z,SI,DN,EDOF,ENODE)
	
	DO II = 1,ENODE
	  
	  JAC(1,1)=JAC(1,1)+DN(1,II)*XC(II)
	  JAC(1,2)=JAC(1,2)+DN(2,II)*XC(II)
	  JAC(1,3)=JAC(1,3)+DN(3,II)*XC(II)
	  
	  JAC(2,1)=JAC(2,1)+DN(1,II)*YC(II)
	  JAC(2,2)=JAC(2,2)+DN(2,II)*YC(II)
	  JAC(2,3)=JAC(2,3)+DN(3,II)*YC(II)
	
	  JAC(3,1)=JAC(3,1)+DN(1,II)*ZC(II)
	  JAC(3,2)=JAC(3,2)+DN(2,II)*ZC(II)
	  JAC(3,3)=JAC(3,3)+DN(3,II)*ZC(II)
	
	ENDDO
	
	RETURN
	END

	
C	SUBROUTINE TO FIND TRASFORMATION MATRIX [T]
C	GAUSSIAN COORDINATES = E,Z,SI
C	PASSED OUT=[TT]

	SUBROUTINE TMAT(XC,YC,ZC,E,Z,SI,TT,EDOF,ENODE)
	

	IMPLICIT NONE

	INTEGER  EDOF,ENODE
	INTEGER  K1,K2
	
	REAL*8 E,Z,SI
     	REAL*8 XC(ENODE),YC(ENODE),ZC(ENODE)
	REAL*8 JAC(3,3),T(3,3),TT(3,3)
        REAL*8 BDUMMY(3),DETERM
	
	CALL JACOBI(XC,YC,ZC,E,Z,SI,JAC,EDOF,ENODE)
	
	DO K1 = 1,3
	  DO K2 = 1,3
	    T(K1,K2) = JAC(K1,K2)
	  ENDDO
	ENDDO
	
	CALL MATIN(T,3,BDUMMY,0,DETERM)

	CALL TRANS(T,TT,3,3)

	RETURN
	END


C	[DERV] STORES DERIVATIVE OF SHAPE FUNCTION OF
C	SERENDIPIDI ELEMENT W.R.T. NATURAL COORDINATES

	SUBROUTINE DERVN(E,Z,SI,DERV,EDOF,ENODE)


	IMPLICIT NONE

	INTEGER EDOF,ENODE

	REAL*8 E,Z,SI
	REAL*8 DERV(3,ENODE)

	DERV(1,1) = -(1-E)*(1-SI)/8.0
	DERV(1,2) =  (1-E)*(1-SI)/8.0
	DERV(1,3) =  (1+E)*(1-SI)/8.0
	DERV(1,4) = -(1+E)*(1-SI)/8.0
	DERV(1,5) = -(1-E)*(1+SI)/8.0
	DERV(1,6) =  (1-E)*(1+SI)/8.0
	DERV(1,7) =  (1+E)*(1+SI)/8.0
	DERV(1,8) = -(1+E)*(1+SI)/8.0

	DERV(2,1) = -(1-Z)*(1-SI)/8.0
	DERV(2,2) = -(1+Z)*(1-SI)/8.0
	DERV(2,3) =  (1+Z)*(1-SI)/8.0
	DERV(2,4) =  (1-Z)*(1-SI)/8.0
	DERV(2,5) = -(1-Z)*(1+SI)/8.0
	DERV(2,6) = -(1+Z)*(1+SI)/8.0
	DERV(2,7) =  (1+Z)*(1+SI)/8.0
	DERV(2,8) =  (1-Z)*(1+SI)/8.0

	DERV(3,1) = -(1-Z)*(1-E)/8.0
	DERV(3,2) = -(1+Z)*(1-E)/8.0
	DERV(3,3) = -(1+Z)*(1+E)/8.0
	DERV(3,4) = -(1-Z)*(1+E)/8.0
	DERV(3,5) =  (1-Z)*(1-E)/8.0
	DERV(3,6) =  (1+Z)*(1-E)/8.0
	DERV(3,7) =  (1+Z)*(1+E)/8.0
	DERV(3,8) =  (1-Z)*(1+E)/8.0
	
	
	RETURN
	END


