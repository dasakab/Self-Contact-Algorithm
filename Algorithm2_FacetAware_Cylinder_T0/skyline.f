C	SUBROUTINE TO FIND COLUMN HEIGTHS AND ADDRESS FOR 
C	DIAGONAL ELEMENTS
	
	SUBROUTINE ADDRESS(IG,LOC,JCHT,NE,EDOF,NND,NDIMSKY)

	IMPLICIT NONE

	INTEGER EDOF,NE,NDIMSKY
	INTEGER ND,NND
	INTEGER I,JI,JK,JL,MN,JN,ICHT
	
	INTEGER IG(EDOF,NE),LOC(NND),JCHT(NND-1)

	ND = NND -1    !DEGREE OF FREEDOM AVAILABLE
		       !NND = ND +1  IS TO TAKE CARE OF LOC ARRAY

	DO I = 1,ND
	 JCHT(I)=0
	 LOC(I)=0
	ENDDO

	DO JI = 1,ND
	 DO JK = 1,NE
	  DO JN = 1,EDOF
	   IF(IG(JN,JK).NE.JI) GO TO 225
	   MN=0
	   DO JL=1,EDOF
	     IF(IG(JL,JK).GT.0)MN=IG(JL,JK)
	   ENDDO
	   DO JL = 1,EDOF
	    IF(IG(JL,JK).LE.0) GO TO 245
	    IF(MN.GT.IG(JL,JK)) MN = IG(JL,JK)
245	    CONTINUE
	   ENDDO
	   ICHT=JI-MN+1
	   IF(ICHT.GT.JCHT(JI))JCHT(JI)=ICHT
225	   CONTINUE
	  ENDDO
	 ENDDO
	ENDDO

	
	LOC(1)=1
	
	DO JI = 1,ND-1
	  LOC(JI+1)=LOC(JI)+JCHT(JI)
	ENDDO
	
	NDIMSKY=LOC(ND)+JCHT(ND)-1
	
	WRITE(*,*)'SIZE OF SKYLINE MATRIX= ',NDIMSKY
	
	LOC(ND+1) = NDIMSKY+1
	
	RETURN 	
	END
	  
	SUBROUTINE SKYLN(MPROP,IG,XCOORD,YCOORD,ZCOORD,CSTRESS,
     1	EQUI_PSTRAIN,NSTATE,SKY,LOC,JCHT,NE,EDOF,ENODE,NPROP,NDIMSKY,
     1  NDIMLOC,INCNUMBER,IBODY,NG,PCE,OSTIF,MK,DT,STRESS_OPTION)

	
	IMPLICIT NONE 

	INTEGER NG,JFLAG,INCNUMBER,IBODY,OSTIF
	INTEGER EDOF,ENODE,NE,NPROP,NDIMSKY,NDIMLOC
	INTEGER I,JI,JK,JL,K1,K2,JM,JN,J
	
	INTEGER LOC(NDIMLOC),JCHT(NDIMLOC)

	INTEGER IG(EDOF,NE),NSTATE(NG*NG*NG,NE),NSTATE_E(NG*NG*NG)
	
	REAL*8 PCE
	REAL*8 YM(NG*NG*NG),PR,EXPO,PRO,RO
	
	REAL*8 MPROP(NPROP,NE)

	REAL*8 XCOORD(ENODE,NE),YCOORD(ENODE,NE),ZCOORD(ENODE,NE),
     1    XC(ENODE),YC(ENODE),ZC(ENODE)

	REAL*8 SKY(NDIMSKY),STIF(EDOF,EDOF),EQUICSTRESS,MK(EDOF,EDOF)
    
	REAL*8 CSTRESS(NG*NG*NG,6,NE),CSTRESS_E(NG*NG*NG,6),CSTRESS_C(6)

	REAL*8 EQUI_PSTRAIN(NG*NG*NG,NE),EQUI_PSTRAIN_E(NG*NG*NG)
	
	REAL *8 DT
	
	INTEGER STRESS_OPTION

C	INITIALISING SKYLINE MATRIX

	DO I = 1,NDIMSKY
	 SKY(I)=0.0
	ENDDO
	
	DO JI = 1,NE
	  
	  DO K1 = 1,ENODE
	    XC(K1)=XCOORD(K1,JI)
	    YC(K1)=YCOORD(K1,JI)
	    ZC(K1)=ZCOORD(K1,JI)
	  ENDDO

	  DO K1 = 1,NG*NG*NG
	    NSTATE_E(K1)=NSTATE(K1,JI)
	    EQUI_PSTRAIN_E(K1)=EQUI_PSTRAIN(K1,JI)

	    DO K2 = 1,6
	      CSTRESS_E(K1,K2)=CSTRESS(K1,K2,JI)
	      CSTRESS_C(K2)=CSTRESS(K1,K2,JI)
	    ENDDO

	 CALL EQUI_CSTRESS(CSTRESS_C,EQUICSTRESS)
	  
	  YM(K1)   = MPROP(1,JI)
	  ENDDO

	  PR   = MPROP(2,JI)
	  EXPO = MPROP(3,JI)
	  PRO  = MPROP(4,JI)
	  RO   = MPROP(7,JI)
	  

	  CALL ESTIFF (CSTRESS_E,NSTATE_E,EQUI_PSTRAIN_E,XC,YC,ZC,
     1	  STIF,YM,PR,EXPO,PRO,EDOF,ENODE,NG,JFLAG,PCE,OSTIF,
     1		STRESS_OPTION)
     
	  CALL MASS(XC,YC,ZC,MK,EDOF,ENODE,NG,JFLAG,RO) 
	   
	  CALL DYNASTIF(STIF,MK,EDOF,DT) 
	  
	  IF(JFLAG.EQ.1) THEN
	    
	    WRITE(711,*)'DETERMINANT OF JACOBIAN ZERO OR -VE '
	    WRITE(711,*)'   '
	    WRITE(711,*) 'ELEMENT NUMBER  =  ', JI
	    WRITE(711,*) '   '
	    WRITE(711,*)'INCREMENT NUMBER = ',INCNUMBER 
	    WRITE(711,*) '   '
	    WRITE(711,*)' IBODY  =  ',IBODY
	    WRITE(711,*) '   '
	    WRITE(711,*)'EXECUTION TERMINATED  ' 
	    WRITE(711,*)'X : ',(XCOORD(I,JI),I=1,8) 
	    WRITE(711,*)'Y : ',(YCOORD(I,JI),I=1,8) 
	    WRITE(711,*)'Z : ',(ZCOORD(I,JI),I=1,8) 
	    
	    WRITE(*,*)
	    WRITE(*,*) '  STOPPED IN SKYLN...'
	    STOP
	  
	  ENDIF

	  DO JK = 1,EDOF
	    DO JN = JK,EDOF
	      JM=IG(JK,JI)
	      JL=IG(JN,JI)
	      
	      IF(JL .EQ. 0 .OR. JM .EQ. 0)GO TO 235
	        
	      IF(JM .EQ. JL)THEN
		SKY(LOC(JM))=SKY(LOC(JL))+STIF(JK,JN)
	      
	      ELSEIF(JM .GT. JL)THEN
	        
		IF((JM-JL).GT.JCHT(JM))GO TO 235	        
		SKY(LOC(JM)-JL+JM)=SKY(LOC(JM)-JL+JM)+STIF(JK,JN)
		
	      ELSE
	         
		IF((JL-JM) .GT. JCHT(JL))GO TO 235	         
		SKY(LOC(JL)-JM+JL)=SKY(LOC(JL)-JM+JL)+STIF(JK,JN)
		 
	      ENDIF

235	      CONTINUE
	  
	    ENDDO
	  ENDDO
	ENDDO
	
	RETURN
	END


C	SUBROUTINE TO STIFFNESS MATRIX OF AN ELEMENT

	SUBROUTINE ESTIFF (CSTRESS_E,NSTATE_E,EQUI_PSTRAIN_E,XC,YC,ZC,
     1	EK,YM,PR,EXPO,PRO,EDOF,ENODE,NG,JFLAG,PCE,OSTIF,STRESS_OPTION)
	

	IMPLICIT NONE
	
	INTEGER NG,OSTIF,JFLAG
	INTEGER EDOF,ENODE
	INTEGER NSTATE_E(NG*NG*NG)
	INTEGER K1,K2
	
	REAL*8 PCE
	REAL*8 YM(NG*NG*NG),PR,EXPO,PRO
	
	REAL*8 XC(ENODE),YC(ENODE),ZC(ENODE)
	
	REAL*8 CSTRESS_E(NG*NG*NG,6)
	
	REAL*8 EK(EDOF,EDOF),EKLN(EDOF,EDOF),EKNLN(EDOF,EDOF)

	REAL*8 EQUI_PSTRAIN_E(NG*NG*NG)
	
	INTEGER STRESS_OPTION
	
	CALL K_LINEAR(CSTRESS_E,NSTATE_E,EQUI_PSTRAIN_E,
     1	XC,YC,ZC,EXPO,PRO,EKLN,YM,PR,EDOF,ENODE,NG,JFLAG,PCE,
     1	STRESS_OPTION)

	IF(OSTIF.EQ.1) THEN       ! LINEAR STIFFNESS 
	
	  DO K1 = 1,EDOF
	    DO K2 = 1,EDOF
	      EK(K1,K2)=EKLN(K1,K2)
	    ENDDO
	  ENDDO
	
	ELSEIF(OSTIF.EQ.2) THEN   ! LINEAR + NONLINEAR STIFFNESS

	  CALL K_NLINEAR (CSTRESS_E,XC,YC,ZC,EKNLN,YM,PR,EDOF,ENODE,
     1	  NG)
	  
	  DO K1 = 1,EDOF
	    DO K2 = 1,EDOF
	      EK(K1,K2)=EKLN(K1,K2)+EKNLN(K1,K2)
	    ENDDO
	  ENDDO
	
	ELSE
	  
	  WRITE(711,*) ' ERROR IN READING OPTION FOR STIFFNESS MATRIX'
	  WRITE(711,*) ' '
	  WRITE(711,*) '  EXECUTION TERMINATED  '
	  
	  STOP
	
	ENDIF

	RETURN
	END


C	SUBROUTINE TO FIND STIFFNESS MATRIX OF AN ELEMENT
	
	SUBROUTINE K_LINEAR(CSTRESS_E,NSTATE_E,EQUI_PSTRAIN_E,
     1	XC,YC,ZC,EXPO,PRO,EK,YM,PR,EDOF,ENODE,NG,JFLAG,PCE,
     1	STRESS_OPTION)

	
	IMPLICIT NONE
	
	INTEGER NG,JFLAG
	INTEGER EDOF,ENODE,NSTATE_C
	INTEGER NSTATE_E(NG*NG*NG)
	INTEGER NDUMMY,I,IK,JJ,KKK,K1,IJ 
	
	REAL*8 PCE
	REAL*8 YM(NG*NG*NG),PR,EXPO,PRO,YMC
	REAL*8 E,Z,SI,EQUIPSTRAIN
	REAL*8 DETJAC,SF
	REAL*8 W(NG),GP(NG)

	REAL*8 XC(ENODE),YC(ENODE),ZC(ENODE)
	
	REAL*8 CSTRESS_E(NG*NG*NG,6),CSTRESS_C(6)
	
	REAL*8 EQUI_PSTRAIN_E(NG*NG*NG)
	
	REAL*8 EK(EDOF,EDOF),B(6,EDOF),CE(6,6),JAC(3,3)	
	
	REAL*8 EF(EDOF,6),F(EDOF,EDOF),G(EDOF,EDOF),
     1       BTRAN(EDOF,6)
     
     	INTEGER STRESS_OPTION
        
	DO I = 1,EDOF
          DO JJ = 1,EDOF
	    EK(I,JJ)=0
	  ENDDO
 	ENDDO
	
	JFLAG = 0        !FLAG FOR JACOBIAN     

	CALL GLWR(W,GP,NG)
	
	NDUMMY=1
	DO 30 I = 1,NG
	  DO 40 JJ = 1,NG
	    DO 50 KKK = 1,NG

	      DO K1 = 1,6
	        CSTRESS_C(K1)=CSTRESS_E(NDUMMY,K1)
	      ENDDO
	      NSTATE_C = NSTATE_E(NDUMMY)
	      EQUIPSTRAIN = EQUI_PSTRAIN_E(NDUMMY)

	      YMC=YM(NDUMMY)
	      IF (YMC.LE.0.0) YMC = 100.0
	      
	      CALL C_MATRIX (CSTRESS_C,NSTATE_C,EQUIPSTRAIN,EXPO,
     1	       PRO,CE,YMC,PR,PCE,STRESS_OPTION)
	      
	      E  = GP(I)
	      Z  = GP(JJ)
	      SI = GP(KKK)
	      
	      CALL B_LINEAR(XC,YC,ZC,E,Z,SI,B,EDOF,ENODE)
	      CALL TRANS (B,BTRAN,6,EDOF)
	      CALL MATMUL (BTRAN,CE,EF,EDOF,6,6)
	      CALL MATMUL (EF,B,F,EDOF,6,EDOF)
	      CALL JACOBI (XC,YC,ZC,E,Z,SI,JAC,EDOF,ENODE)
	      
	      DETJAC=JAC(1,1)*(JAC(2,2)*JAC(3,3)-JAC(2,3)*JAC(3,2))-
     1	             JAC(1,2)*(JAC(2,1)*JAC(3,3)-JAC(2,3)*JAC(3,1))+
     1		     JAC(1,3)*(JAC(2,1)*JAC(3,2)-JAC(3,1)*JAC(2,2))
	      
	      IF(DETJAC .LE. 0.0) THEN
		JFLAG = 1
	      ENDIF

	      SF=DETJAC*W(I)*W(JJ)*W(KKK)
	
	      CALL SCAMUL (F,G,EDOF,EDOF,SF)
	
	      DO 25 IK = 1,EDOF
	        DO 35 IJ = 1,EDOF
	          EK(IK,IJ) = EK(IK,IJ)+G(IK,IJ)
35	        CONTINUE
25	      CONTINUE
	      
	      NDUMMY=NDUMMY+1

50	    CONTINUE
40	  CONTINUE
30	CONTINUE
	
	RETURN	
	END
	

C	SUBROUTINE FOR NONLINEAR PART OF STIFFNESS MATRIX

	SUBROUTINE K_NLINEAR(CSTRESS_E,XC,YC,ZC,EKNL,YM,PR,
     1   EDOF,ENODE,NG)

	
	IMPLICIT NONE

	INTEGER NG
	INTEGER EDOF,ENODE
	INTEGER NDUMMY,K1,K2,K3,M1,M2

	REAL*8 YM(NG*NG*NG),PR
	REAL*8 E,Z,SI
	REAL*8 DETJAC,SF
	REAL*8 W(NG),GP(NG)

	REAL*8 XC(ENODE),YC(ENODE),ZC(ENODE)

	REAL*8 CSTRESS_E(NG*NG*NG,6),CSTRESS_C(6)
	
	REAL*8 EKNL(EDOF,EDOF),BNLN(9,EDOF),JAC(3,3),T(9,9)
        
	REAL*8 DUMMY1(EDOF,9),DUMMY2(EDOF,EDOF),DUMMY3(EDOF,EDOF),
     1    BNLNTRAN(EDOF,9)
     
	CALL GLWR(W,GP,NG)


	DO M1 = 1,EDOF
	  DO M2 = 1,EDOF
	    EKNL(M1,M2)=0.0
	  ENDDO
	ENDDO
	
	NDUMMY =1
	DO K1 = 1,NG
	  DO K2 = 1,NG
	    DO K3 = 1,NG

	      DO M1 = 1,6
	        CSTRESS_C(M1)=CSTRESS_E(NDUMMY,M1)
	      ENDDO
	      
	      CALL MATRIX_T(CSTRESS_C,T)
	    
	      E  = GP(K1)
	      Z  = GP(K2)
	      SI = GP(K3)
	   
	      CALL B_NLINEAR(XC,YC,ZC,E,Z,SI,BNLN,EDOF,ENODE)

	      CALL TRANS (BNLN,BNLNTRAN,9,EDOF)

	      CALL MATMUL (BNLNTRAN,T,DUMMY1,EDOF,9,9)

	      CALL MATMUL (DUMMY1,BNLN,DUMMY2,EDOF,9,EDOF)

	      CALL JACOBI (XC,YC,ZC,E,Z,SI,JAC,EDOF,ENODE)
	      
	      DETJAC=JAC(1,1)*(JAC(2,2)*JAC(3,3)-JAC(2,3)*JAC(3,2))-
     1	             JAC(1,2)*(JAC(2,1)*JAC(3,3)-JAC(2,3)*JAC(3,1))+
     1		     JAC(1,3)*(JAC(2,1)*JAC(3,2)-JAC(3,1)*JAC(2,2))

	      SF = DETJAC*W(K1)*W(K2)*W(K3)

	      CALL SCAMUL (DUMMY2,DUMMY3,EDOF,EDOF,SF)

	      DO M1 = 1,EDOF
	        DO M2 = 1,EDOF
		  EKNL(M1,M2)=EKNL(M1,M2)+DUMMY3(M1,M2)
	        ENDDO
	      ENDDO
	    
	      NDUMMY=NDUMMY+1
	    ENDDO
	  ENDDO
	ENDDO

	RETURN
	END


